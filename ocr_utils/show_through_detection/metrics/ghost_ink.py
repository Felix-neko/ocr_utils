"""Доля призрака, который переживёт предварительную бинаризацию.

ЗАЧЕМ ИМЕННО ТАК. Просвет виден почти на всяком старом журнале, и вопрос не в том,
есть ли он, а в том, ПОМЕШАЕТ ли он. Бледный призрак снимается обработкой: связка
«предварительная бинаризация → маска контента → размытие фона» (ровно то, что делает
``ocr_utils.background_smoothing``) стирает всё, что осталось светлее порога
бинаризации. Пересканировать надо там, где призрак этот порог перешагивает и становится
для бинаризатора обычной краской. Метрика меряет ровно это.

Замерено на материале, который пользователь разобрал глазами: выпуск 1955/03 просвечивает
на глаз, но бледно и обработкой снимается — метрика даёт по нему 0 кадров выше порога.
Выпуск 1931/02-03 с теми же семью кадрами, что помечены как брак, даёт все семь.

КАК СЧИТАЕТСЯ

1. Порог Оцу по наборной полосе, в долях уровня бумаги (``Zones.otsu``) — модель самой
   бинаризации. Затем он сдвигается в сторону бумаги на ``BIAS`` — так же, как
   ``background_smoothing.processing.global_threshold`` двигает свой.
2. Всё, что темнее порога, внутри наборной полосы — это будущая «краска».
3. Из неё выбрасываются связные компоненты, ЗАДЕВАЮЩИЕ ядро настоящей краски. Это
   ключевой шаг: на плотной полосе — таблице с линейками, жирном заголовке — край
   настоящей буквы дотягивается в межстрочье и без этого фильтра считался бы призраком.
   Замерено: у полосы-таблицы ``02-03_0013 L`` доля падает с 0.027 до 0.002, а у полосы
   с настоящим призраком ``02-03_0152 R`` держится (0.016 → 0.005).
   Признак физический: призрак лежит в межстрочье САМ ПО СЕБЕ, краска — нет.
4. Балл — доля площади межстрочий, занятая тем, что осталось.

ПОЧЕМУ СДВИГ 0.6, А НЕ 0.5, КАК В ОБРАБОТКЕ. Детектор должен поднимать не только те
полосы, где призрак порог уже перешагнул, но и те, где он подошёл к нему вплотную:
такая полоса свалится в брак от любой мелочи — другой экспозиции, другого сканера,
другого значения ``--threshold-bias``. Замерено: при 0.5 из семи размеченных кадров
поднимаются пять, при 0.6 — все семь, и при этом ни одного кадра из 1955/03, 1945/03
и 1971/03 (все три выпуска проверены глазами как не требующие пересъёмки).

ЧЕГО МЕТРИКА НЕ УМЕЕТ. Она не отличает просвет с оборота от любой другой тёмной мелочи,
свободно лежащей в межстрочье: пятен, сыпи, следа от соседнего листа. Для отчёта это
скорее плюс (всё перечисленное тоже выживает при бинаризации и тоже требует другого
экземпляра), но называть найденное «просветом» без оговорки нельзя. Отличить одно от
другого может только сверка с зеркальным оборотом — см. README.
"""

import numpy as np

import cv2

from ocr_utils.show_through_detection.metrics.base import Algorithm
from ocr_utils.show_through_detection.zones import Zones

# Сдвиг порога Оцу в сторону бумаги, в долях расстояния до неё. Обоснование — в
# модульном докстринге; та же величина в обработке называется ``--threshold-bias``.
BIAS = 0.6

# Порог «на пересканирование»: доля межстрочий, занятая будущей краской.
# Калибровка — 1931/02-03 против 1955/03, 1945/03 и 1971/03; см. модульный докстринг.
THRESHOLD = 0.010


def _score(zones: Zones) -> float:
    """Доля межстрочий, которая после бинаризации станет краской.

    Args:
        zones: Разобранная полоса.

    Returns:
        Балл в [0, 1]; NaN, если порог бинаризации оценить не удалось.
    """
    if not np.isfinite(zones.otsu):
        return float("nan")
    level = zones.otsu + BIAS * (1.0 - zones.otsu)
    dark = ((zones.reflectance <= level) & zones.block).astype(np.uint8)

    count, labels = cv2.connectedComponents(dark, 8)
    # Компоненты, задевающие ядро краски, — это сама краска и её расплыв, не призрак.
    from_ink = np.zeros(count, dtype=bool)
    from_ink[np.unique(labels[zones.ink])] = True
    from_ink[0] = True  # фон

    free = dark.astype(bool) & ~from_ink[labels]
    total = float(zones.gap.sum())
    if total <= 0.0:
        return float("nan")
    return float((free & zones.gap).sum() / total)


ALGORITHM = Algorithm(
    name="ghost_ink",
    summary="доля межстрочий, где призрак переживёт предварительную бинаризацию",
    score=_score,
    unit="доля",
    threshold=THRESHOLD,
    params={"bias": BIAS},
)
