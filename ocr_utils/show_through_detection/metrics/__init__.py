"""Реестр метрик просвечивания бумаги.

``FALLBACK`` — не «ещё одна метрика на выбор», а страховка внутри прогона: если
выбранная метрика на полосе не считается, потому что ей нужны чистые поля, а полей нет
(набор под обрез, таблица во всю ширину), балл берётся у запасной. Иначе такие полосы
молча выпадали бы из отчёта, хотя просвет на них требует пересъёмки ровно так же.

``COMBO_NAME`` — сведение метрик по среднему рангу, а не по среднему значению: шкалы
несопоставимы (безразмерное отношение, доля площади), а порядок полос сравним всегда.
ЧТО ВЫБРАНО ПО УМОЛЧАНИЮ И ПОЧЕМУ. Метрики здесь отвечают на два РАЗНЫХ вопроса,
и путать их нельзя:

* ``ghost_ink`` — «помешает ли просвет»: переживёт ли призрак предварительную
  бинаризацию. Это операционный критерий: бледный просвет виден почти на всяком старом
  журнале и снимается обработкой, а пересъёмки требует только тот, что бинаризацию
  переживает. Метрика по умолчанию.
* ``gap_contrast``, ``gap_abs``, ``midtone`` — «есть ли просвет вообще». Они заметно
  чувствительнее и поднимают полосы, на которых призрак хорошо виден глазом, но
  обработке не мешает. Годятся, чтобы оценить состояние бумаги в выпуске, но как список
  на пересканирование дают лишнего.

Замерено на выпуске 1955/03, который пользователь разобрал глазами («просвет есть, но
бледный, обработка его победит»): ``gap_contrast`` поднимает выше порога 41 % полос,
``ghost_ink`` — ни одной.
"""

from ocr_utils.show_through_detection.metrics import gap_abs, gap_contrast, ghost_ink, midtone
from ocr_utils.show_through_detection.metrics.base import Algorithm

ALGORITHMS: dict[str, Algorithm] = {
    a.name: a for a in (ghost_ink.ALGORITHM, gap_contrast.ALGORITHM, gap_abs.ALGORITHM, midtone.ALGORITHM)
}

COMBO_NAME = "combo"
COMBO_MEMBERS = ("ghost_ink", "gap_contrast")

DEFAULT_ALGORITHM = "ghost_ink"

# Кому нужны поля — у того есть запасной вариант без полей.
FALLBACK = "gap_abs"

CHOICES = (*ALGORITHMS.keys(), COMBO_NAME)


def resolve(name: str) -> tuple[str, ...]:
    """Разворачивает имя алгоритма в список метрик, которые надо посчитать.

    Args:
        name: Имя из ``CHOICES``.

    Returns:
        Кортеж имён отдельных метрик.
    """
    return COMBO_MEMBERS if name == COMBO_NAME else (name,)


def needed(name: str) -> tuple[str, ...]:
    """Какие метрики придётся посчитать, чтобы выдать балл по имени ``name``.

    К запрошенным добавляется запасная, если хоть одной из них нужны поля.

    Args:
        name: Имя из ``CHOICES``.

    Returns:
        Кортеж имён метрик без повторов, в порядке «запрошенные, затем запасная».
    """
    names = resolve(name)
    if any(ALGORITHMS[n].needs_margin for n in names) and FALLBACK not in names:
        return (*names, FALLBACK)
    return names
