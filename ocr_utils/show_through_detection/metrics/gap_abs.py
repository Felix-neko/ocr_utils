"""Абсолютный отклик в межстрочьях — запасная метрика без опоры на поля.

Тот же полосовой отклик, что у ``gap_contrast``, но без деления: 95-й перцентиль
в межстрочьях сам по себе. Считается на карте ОТРАЖЕНИЯ, а не яркости, поэтому цвет
бумаги и уровень света уже сняты — но зерно бумаги и шум сжатия конкретной съёмки
остаются в балле, и сравнивать полосы из разных выпусков им можно только с оглядкой.

ЗАЧЕМ ОНА НУЖНА. Ради полос, где чистых полей нет вовсе: набор под обрез, таблица во
всю ширину, полоса с иллюстрацией на всё поле. Их около процента, и молча выкинуть
их из прогона нельзя — просвет на них ровно так же требует пересъёмки.

ЗАМЕРЕНО (1931/02-03, 315 полос): медиана 0.0166, p90 = 0.0214, p99 = 0.0288.
На размеченных пользователем кадрах ранжирует не хуже основной метрики (пять из семи
в верхних 8 %), но это ничего не говорит о переносимости: весь замер сделан внутри
ОДНОГО выпуска, где бумага и съёмка общие. Ровно там, где начинаются заявленные
сложности — другой год, другая бумага, другое освещение, — у неё нет никакой защиты,
и потому она запасная, а не основная.
"""

import numpy as np

from ocr_utils.show_through_detection.metrics.base import Algorithm
from ocr_utils.show_through_detection.metrics.gap_contrast import PERCENTILE
from ocr_utils.show_through_detection.zones import Zones

# Порог подобран так, чтобы на калибровочном выпуске отбирать ту же долю полос (около
# 6 %), что и порог gap_contrast: это 94-й процентиль выпуска. Иначе полосы без полей
# систематически перевешивали бы остальные в общем списке — а severity в отчёте как раз
# и нужен, чтобы их можно было сравнивать.
THRESHOLD = 0.024


def _score(zones: Zones) -> float:
    """Перцентиль полосового отклика в межстрочьях.

    Args:
        zones: Разобранная полоса.

    Returns:
        Балл в долях уровня бумаги.
    """
    return float(np.percentile(zones.dark[zones.gap], PERCENTILE))


ALGORITHM = Algorithm(
    name="gap_abs",
    summary="то же, но без нормировки на поля — для полос, у которых полей нет",
    score=_score,
    unit="доля бумаги",
    threshold=THRESHOLD,
    params={"percentile": PERCENTILE},
)
