"""Общий интерфейс метрик просвечивания бумаги.

Метрика — это функция от разобранной полосы (``Zones``), возвращающая ОДНО число,
и шкала у всех метрик общая: **больше значение — сильнее просвет с оборота**. Единое
направление нужно, чтобы сортировка, порог, сводный ранг и отчёт не знали ничего
о конкретной метрике.

Тяжёлую часть (нормировка по бумаге, маски межстрочий и полей, полосовой отклик)
метрика не делает: она приходит готовой в ``Zones``, посчитанной один раз на полосу.
Поэтому добавить новую метрику — это написать одну короткую функцию и внести её
в реестр, а не заводить второй проход по кадру.
"""

from collections.abc import Callable
from dataclasses import dataclass, field

from ocr_utils.show_through_detection.zones import Zones


@dataclass(frozen=True)
class Algorithm:
    """Описание одной метрики просвечивания.

    Attributes:
        name: Имя для CLI (``--algorithm``).
        summary: Однострочное описание для справки.
        score: Функция ``Zones -> балл``, больше = сильнее просвет. NaN означает
            «на этой полосе метрика не считается».
        unit: Подпись колонки с баллом в отчёте.
        needs_margin: Нужны ли метрике чистые поля полосы как опора. У таких метрик
            на полосе без полей (набор под обрез, таблица во всю ширину) балла нет,
            и его берёт запасная метрика — см. ``FALLBACK`` в реестре.
        threshold: Порог «полосу надо пересканировать», откалиброванный на размеченном
            материале. None — порога нет, метрика годится только для ранжирования.
        params: Замеренные константы метрики (для протокола, в отчёт не идут).
    """

    name: str
    summary: str
    score: Callable[[Zones], float]
    unit: str = "балл"
    needs_margin: bool = False
    threshold: float | None = None
    params: dict = field(default_factory=dict)

    def score_of(self, zones: Zones) -> float:
        """Балл полосы с проверкой пригодности.

        Args:
            zones: Разобранная полоса.

        Returns:
            Балл либо NaN, если полоса вырождена или метрике не хватает опоры.
        """
        if not zones.usable:
            return float("nan")
        if self.needs_margin and not zones.has_margin:
            return float("nan")
        return float(self.score(zones))
