"""Доля «полутонового слоя» в межстрочьях — метрика по площади, а не по контрасту.

ИДЕЯ. Скан просвечивающей полосы раскладывается на три уровня: бумага, призрак
с оборота и настоящая краска, — и между призраком и ядром настоящих букв есть чистый
зазор по яркости. Это наблюдение — общее место в литературе по bleed-through
(трёхслойные модели, CRF-разделение) и оно же независимо замерено в этом репозитории
на паке МТС, см. ``ocr_utils/background_smoothing/README.md``: бумага 250–253,
призрак 219–250, ядро букв ниже 200 при 600 dpi. Гистерезисный порог, как в Кэнни,
для такого зазора не нужен — хватает обычной пары порогов.

Уровни здесь берутся не абсолютные, а в долях от уровня бумаги ЭТОЙ полосы
(``Zones.paper``), иначе метрика немедленно поедет на другой бумаге.

Одной площади мало: гладкое пятно (лисьи, тень, грязь) попадает в тот же диапазон
уровней. Поэтому связные компоненты полутона фильтруются по размеру — от штриха буквы
до слова; всё крупнее — это пятно, всё мельче — зерно бумаги.

ЧЕМ ОНА ДОПОЛНЯЕТ ``gap_contrast``. Та меряет КОНТРАСТ призрака и слепа к его
количеству: одна проступившая строка и сплошь проступивший оборот дадут близкий балл.
Эта — наоборот, меряет площадь и слепа к контрасту. В ``combo`` они складываются рангами.

ЗАМЕРЕНО (1931/02-03, 315 полос): медиана 0.092, p90 = 0.140, p99 = 0.203. На
размеченных кадрах ранжирует примерно как ``gap_contrast`` (пять из семи в верхних 8 %),
но, как и ``gap_abs``, меряет абсолютную величину и потому уязвима к смене бумаги.
"""

import numpy as np

import cv2

from ocr_utils.show_through_detection.metrics.base import Algorithm
from ocr_utils.show_through_detection.zones import Zones, scaled

# Границы полутонового слоя в долях уровня бумаги полосы.
# Верхняя (ближняя к бумаге) отсекает зерно: замерено, разброс чистой бумаги на этих
# сканах держится в пределах 0.02 от медианы. Нижняя отсекает настоящую краску,
# просочившуюся сквозь раздутую маску, — кайму букв и точки пунктуации.
GHOST_MIN_DEPTH = 0.03
GHOST_MAX_DEPTH = 0.22

# Размеры связной компоненты полутона в пикселях при 300 dpi.
# Нижняя граница — примерно квадрат стороной в толщину штриха: мельче бывает только шум.
# Верхняя — площадь длинного слова: крупнее сплошным пятном идёт грязь, а не текст.
MIN_COMPONENT_PX = 25
MAX_COMPONENT_PX = 4000

# Порог — 94-й процентиль калибровочного выпуска, как и у остальных метрик: так
# severity у всех означает одно и то же и колонки отчёта сравнимы между собой.
THRESHOLD = 0.151


def _score(zones: Zones) -> float:
    """Доля межстрочий, занятая структурами полутонового слоя.

    Args:
        zones: Разобранная полоса.

    Returns:
        Балл в [0, 1]: доля площади межстрочий.
    """
    depth = zones.paper - zones.reflectance
    ghost = (zones.gap & (depth > GHOST_MIN_DEPTH) & (depth < GHOST_MAX_DEPTH)).astype(np.uint8)
    total = float(zones.gap.sum())
    if total <= 0.0:
        return float("nan")

    # Площади компонент масштабируются как площадь, то есть как КВАДРАТ линейного размера.
    height = zones.reflectance.shape[0]
    factor = (scaled(height, 100) / 100.0) ** 2
    lo, hi = MIN_COMPONENT_PX * factor, MAX_COMPONENT_PX * factor

    _, _, stats, _ = cv2.connectedComponentsWithStats(ghost, 8)
    areas = stats[1:, cv2.CC_STAT_AREA].astype(np.float64)
    kept = areas[(areas >= lo) & (areas <= hi)]
    return float(kept.sum() / total)


ALGORITHM = Algorithm(
    name="midtone",
    summary="доля межстрочий, занятая полутоновым слоем буквенного размера",
    score=_score,
    unit="доля",
    threshold=THRESHOLD,
    params={"depth": (GHOST_MIN_DEPTH, GHOST_MAX_DEPTH), "component_px": (MIN_COMPONENT_PX, MAX_COMPONENT_PX)},
)
