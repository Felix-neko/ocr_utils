"""Контраст «межстрочья против полей» — основная метрика просвечивания.

ИДЕЯ. Призрак с оборота садится в бумагу ВНУТРИ наборной полосы: в межстрочья и
просветы между словами. На полях его нет — наборные полосы лицевой и оборотной сторон
в журнальной вёрстке совпадают, поэтому поле лицевой стороны приходится на поле
оборота, где печати нет вовсе. Значит, поля этой же полосы дают опорный уровень
«как выглядит чистая бумага именно здесь»: её зерно, шум сенсора, артефакты JPEG.

Балл — отношение 95-х перцентилей полосового отклика в этих двух зонах. На чистой
полосе межстрочья и поля — одна и та же бумага, отношение около единицы. Просвет
поднимает числитель и не трогает знаменатель.

ПОЧЕМУ ЭТО ПОДХОДИТ ПОД ЗАДАЧУ. Отношение внутри одного кадра снимает разом всё, что
меняется от выпуска к выпуску и было заявлено как главная сложность: цвет бумаги,
уровень освещения, экспозицию, качество сжатия, шум конкретной съёмки. Абсолютный
порог остаётся сравнимым между 1931 и 1971 годом, потому что он вообще не про уровень
серого.

ЧТО ЭТО НЕ УМЕЕТ. Нужны чистые поля: на полосе под обрез, на полосе-таблице во всю
ширину и на шмуцтитуле опоры нет, и метрика честно не считается (балл берёт
``gap_abs``). Ещё она не отличает просвет с оборота от чужой печати той же
природы — например, от отпечатавшегося на бумаге соседнего листа; для этого нужен
второй этап со сверкой по зеркальному обороту.

ЗАМЕРЕНО (1931/02-03, 315 измеримых полос, 300 dpi, полное разрешение):
медиана по выпуску 0.885, p90 = 1.10, p99 = 1.47. Из семи кадров, размеченных
пользователем как брак, ПЯТЬ попадают в верхние 9 % рейтинга (места 1, 3, 4, 10, 14
из 159 кадров; при случайном порядке ожидалось бы около 80). Два оставшихся —
разобраны ниже.

ПОДТВЕРЖДЕНИЕ НЕЗАВИСИМЫМ СПОСОБОМ. Полосы с высоким баллом сверены с ЗЕРКАЛЬНЫМ
ОБОРОТОМ (правая полоса разворота N физически есть оборот левой полосы разворота N+1).
Доля полос, у которых слой призрака коррелирует с текстом собственного оборота сильнее,
чем с текстом чужой страницы, растёт вместе с баллом: 33 % по выпуску целиком, 47 %
среди полос с баллом ≥ 1.20 и 67 % среди полос с баллом ≥ 1.50. Сверка односторонняя
(коробление страницы её иногда срывает), поэтому это нижние оценки.

ЧЕГО МЕТРИКА НЕ ЛОВИТ — замерено на тех самых двух кадрах, 0149 и 0151. Там просвет
идёт по всему листу вместе с сильной пятнистостью самой бумаги, и поля оказываются
такими же грязными, как межстрочья (поля 0.021–0.025 против 0.016–0.018 в межстрочьях —
знаменатель БОЛЬШЕ числителя). Формально метрика права: межстрочья там не хуже полей.
Но пересъёмки такая полоса требует. Лечится это только сверкой с оборотом — единственным
признаком, отличающим просвет от грязной бумаги, когда оба размазаны по всему листу.
"""

import numpy as np

from ocr_utils.show_through_detection.metrics.base import Algorithm
from ocr_utils.show_through_detection.zones import Zones

# Перцентиль отклика, по которому сравниваются зоны. 95 — компромисс, подтверждённый
# замером: 99 ловит одиночные соринки и точки пунктуации, не попавшие в маску краски
# (AUC проваливается до 0.49), 90 и ниже начинает мерить зерно бумаги в обеих зонах
# сразу и разница между ними тает.
PERCENTILE = 95.0

# Нижняя граница знаменателя. Ниже одного шага квантования 8-битной шкалы (1/255
# в долях бумаги) измеримого шума на полях нет, и делить на такой «ноль» бессмысленно:
# получилась бы бесконечность на идеально гладкой бумаге (а на синтетике — NaN).
# Клампим, и балл честно уходит в большие значения, оставаясь конечным.
MARGIN_FLOOR = 1.0 / 255.0

# Порог «на пересканирование». Калибровка — 1931/02-03, см. модульный докстринг.
# 1.20 — это 94-й процентиль выпуска: под порог уходит около 6 % полос. Выбран по
# ПОЛНОТЕ, а не по точности: лишний пересканированный разворот стоит десяти минут,
# пропущенный уходит в готовую книгу навсегда. Порог 1.30 дал бы 2.6 % полос и поймал
# бы только три размеченных кадра из семи вместо пяти.
THRESHOLD = 1.20


def _score(zones: Zones) -> float:
    """Отношение отклика в межстрочьях к отклику на полях.

    Args:
        zones: Разобранная полоса.

    Returns:
        Балл: 1.0 — межстрочья не отличаются от полей, больше — просвет.
    """
    in_gap = float(np.percentile(zones.dark[zones.gap], PERCENTILE))
    on_margin = float(np.percentile(zones.dark[zones.margin], PERCENTILE))
    if not np.isfinite(on_margin):
        return float("nan")
    return in_gap / max(on_margin, MARGIN_FLOOR)


ALGORITHM = Algorithm(
    name="gap_contrast",
    summary="отклик в межстрочьях, делённый на отклик на чистых полях той же полосы",
    score=_score,
    unit="раз",
    needs_margin=True,
    threshold=THRESHOLD,
    params={"percentile": PERCENTILE},
)
