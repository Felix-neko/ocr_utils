"""Хеши исходных сканов: чем считаем и как решаем, что файл не менялся.

Зачем вообще. Пак обновляется по частям: выпуск перескали, страницу переобрезали в
ScanTailor, кривой кадр заменили. После этого разметка в CVAT относится уже не к тому
файлу, что лежит на диске, и надо точно знать, каких именно полос это касается — иначе
остаётся либо пересоздавать весь проект (недели ручной работы под нож), либо надеяться,
что не забыл.

**Чем считаем — sha256.** Против ожидания это не медленнее blake2b: замер на реальном
скане 40.6 МБ, прогретый кеш, эта машина —

===========  ==========
sha256        2116 МБ/с
blake2b-128   1209 МБ/с
blake2b-512   1126 МБ/с
md5            949 МБ/с
===========  ==========

sha256 выигрывает потому, что у процессора есть аппаратные инструкции SHA-NI, а у blake2b
таких нет. Обе цифры многократно выше скорости чтения с NTFS-3G, так что на холодном
файле хеш бесплатен в любом случае, а на горячем (файл только что прочитала детекция)
sha256 быстрее почти вдвое.

Дайджест не укорачиваем, хотя 12 тысяч файлов не требуют и 128 бит. Полные 64 символа
стоят 780 КБ на весь пак и дают то, чего не даёт никакая усечённая схема: строку из базы
можно проверить руками, ``sha256sum файл.tif`` выдаёт ровно её.

**Как понимаем, что можно не читать.** Пересчитать хеши всего пака — это перечитать
полтерабайта с медленного диска, то есть часы. Поэтому сначала спрашиваем ``stat``:
размер и время правки. Совпали — файл считается прежним, содержимое не читается вовсе.
Не совпали — читаем и считаем хеш; он может оказаться и прежним (файл просто скопировали
заново), и тогда меняется только отметка ``stat``, а разметка остаётся на месте.

Обратное неверно: одинаковые размер и mtime НЕ доказывают, что файл тот же. Это осознанный
размен ради часов машинного времени, и он выключается флагом ``--rehash-all``.
"""

import hashlib
from dataclasses import dataclass
from pathlib import Path

# Имя алгоритма. Хранится рядом с дайджестом в базе, чтобы смена алгоритма не превратила
# старые строки в молча несовпадающие: несовпадение имени видно сразу.
HASH_ALGO = "sha256"

# Читаем крупными кусками: файлы по 40 МБ, и мелкое чтение упирается в накладные расходы
# NTFS-3G (он работает через FUSE, то есть каждый вызов — переход в пользовательский
# процесс и обратно).
HASH_CHUNK = 4 * 1024 * 1024


@dataclass(frozen=True)
class FileStamp:
    """Отпечаток файла: дешёвая часть (``stat``) и дорогая (хеш содержимого)."""

    size: int
    mtime: float
    digest: str | None = None


def stat_stamp(path: Path) -> FileStamp:
    """Отпечаток без чтения содержимого — только ``stat``."""
    info = path.stat()
    return FileStamp(size=info.st_size, mtime=info.st_mtime)


def file_digest(path: Path) -> str:
    """Хеш содержимого файла, hex-строкой. Совпадает с выводом ``sha256sum``."""
    digest = hashlib.new(HASH_ALGO)
    with open(path, "rb") as handle:
        while chunk := handle.read(HASH_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def full_stamp(path: Path) -> FileStamp:
    """Полный отпечаток: ``stat`` плюс хеш содержимого.

    ``stat`` снимается ПЕРЕД чтением. Если файл дописывают прямо сейчас, лучше запомнить
    более старый ``stat`` при более новом хеше: следующий прогон увидит расхождение и
    перечитает файл. Обратный порядок дал бы свежий ``stat`` при хеше от недописанного
    файла, и расхождение осталось бы незамеченным навсегда.
    """
    stamp = stat_stamp(path)
    return FileStamp(size=stamp.size, mtime=stamp.mtime, digest=file_digest(path))


def stat_matches(page, stamp: FileStamp) -> bool:
    """Совпадает ли дешёвый отпечаток файла с записанным у полосы.

    Полоса без записанных размера или времени (её завёл прогон до появления хешей)
    считается несовпавшей: это заставит перечитать её и посчитать хеш.
    """
    if page.file_size is None or page.file_mtime is None:
        return False
    return page.file_size == stamp.size and page.file_mtime == stamp.mtime


def apply_stamp(page, stamp: FileStamp) -> None:
    """Записывает отпечаток в полосу. Хеш трогается, только если он посчитан."""
    page.file_size = stamp.size
    page.file_mtime = stamp.mtime
    if stamp.digest is not None:
        page.file_hash = stamp.digest
        page.hash_algo = HASH_ALGO


def is_stale_in_cvat(page) -> bool:
    """Разошлась ли полоса с тем, что залито в CVAT.

    ``cvat_file_hash`` — хеш файла НА МОМЕНТ ЗАЛИВКИ в CVAT. Пока он равен текущему
    ``file_hash``, кадр в CVAT показывает ровно тот файл, что лежит на диске, и разметку
    на нём можно принимать как есть.

    Полоса, которую ещё не заливали (``cvat_file_hash is None``), устаревшей НЕ считается:
    она просто новая, и решать про неё должен тот, кто заводит задачу.
    """
    return page.cvat_file_hash is not None and page.file_hash is not None and page.cvat_file_hash != page.file_hash
