"""Разметка полос журнала: растровые области и библиотечные печати.

ЗАЧЕМ. Финальный PDF выпуска собирается из двух бинаризованных слоёв — полного (с
распрямлением строк в FineReader) и «только полосы с растром» (без распрямления, чтобы
не поехала геометрия картинок). Чтобы это собрать, надо заранее знать по каждой полосе:

* прямоугольники растровых (полутоновых) изображений и их тип ``color``/``grayscale`` —
  для защиты от сглаживания фона, для отбора полос во второй PDF и для вклейки вырезанных
  из оригинала картинок поверх бинаризованного слоя;
* битовые маски библиотечных печатей — под закраску через LaMa.

Надёжного автодетектора печатей нет вовсе, а границы растровых областей автодетектор
угадывает лишь приблизительно, поэтому результат обязан пройти ручную правку. Отсюда три
команды (см. ``cli``):

* ``detect``    — предварительная детекция по оригиналам, результат в SQLite;
* ``to-cvat``   — уменьшенные копии в share-каталог + проект/задачи/джобы CVAT с предразметкой;
* ``from-cvat`` — уточнённая разметка обратно в SQLite той же схемы.

Иерархия сущностей одна и та же во всех трёх: пак сканов -> годовой комплект -> выпуск ->
полоса -> (растровые области | печати). В CVAT она ложится как проект -> задача -> джоб ->
кадр.
"""
