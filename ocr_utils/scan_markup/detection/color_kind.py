"""Цветная ли растровая область или полутоновая.

ЗАЧЕМ. Вырезанные из оригинала картинки вклеиваются в финальный PDF как JPEG. Серый JPEG
той же полосы весит втрое меньше цветного, а на страницу их бывает по три-четыре, так что
на выпуске это десятки мегабайт. Но пометить цветную картинку серой — значит потерять её
насовсем, поэтому при сомнении решение смещено к ``color``.

ПОЧЕМУ НЕ ПРОСТО НАСЫЩЕННОСТЬ. Сканы жёлто-бежевые: бумага 1966 года пожелтела, и серая
типографская фотография на ней даёт устойчивый сепийный налёт по всей площади. Прямая
проверка «есть насыщенность -> цветная» назвала бы цветными вообще все области.

ПОЧЕМУ НЕ ПОМОГАЕТ БАЛАНС БЕЛОГО. Первая версия снимала налёт поканальными коэффициентами
по светлым пикселям полосы и мерила ОСТАТОЧНУЮ хроматичность (``chroma_fraction`` ниже).
Так делать нельзя, и вот почему: поканальный баланс выправляет ровно ОДИН уровень яркости —
бумагу. У ч/б фотографии в средних тонах оттенок свой (у камерного скана тени уходят в
зелень или синь), и после «коррекции» она оказывается хроматичной целиком. Замер по паку-1,
66 областей с настоящими ч/б фотографиями против 20 цветных обложек:

    доля хроматичных пикселей   ч/б 0.110 .. 0.811   цветные 0.089 .. 0.749   перекрытие полное

Порог 0.10 был откалиброван по одному 1966 году, где обложки отстояли далеко; по всему паку
пустого промежутка нет вовсе — минимум у цветных 0.101, максимум у серых 0.099. Порог резал
сплошное распределение пополам, и на выходе получилось 342 «цветных» области при примерно
123 настоящих цветных обложках.

ЧТО МЕРИТЬ ВМЕСТО ЭТОГО. Не смещение оттенка, а его РАЗБРОС. У ч/б печати оттенок почти
постоянен по всей области, каким бы сильным ни был налёт; у цветной он разный. Замер по той
же выборке:

    hypot(std(a), std(b))       ч/б 2.2 .. 6.5       цветные 9.3 .. 19.6      чистый зазор

Проверено и на штриховых рисунках: чёрный штрих даёт 2.4 .. 7.1, синий рисунок обложки
1970/04 IMG_0052_2R — 17.9.

ПОЧЕМУ НЕ ГОДИТСЯ ДОЛЯ ОТКЛОНИВШИХСЯ ОТ СОБСТВЕННОЙ МЕДИАНЫ. Она напрашивается как вторая
метрика — на случай маленькой сплошной цветной плашки, у которой оттенок один на всю площадь
и разброс поэтому мал. По первому замеру (на границах областей ПРОШЛОГО детектора) она и
правда разделяла: ч/б до 0.129, цветные от 0.092. Но на границах нового детектора ч/б
области доходят до 0.293 при тех же 0.092 у цветных, то есть промежутка нет вовсе и порога,
который что-то делит, не существует. Число считается и пишется в базу, но в решении по
умолчанию НЕ участвует; ``chroma_self_frac_thr=None`` именно поэтому.

Опасение про сплошную плашку осталось теоретическим: сплошная краска не даёт растровой
сетки, и до классификации такая область просто не доходит — её не находит ``dots``.
"""

from dataclasses import dataclass

import cv2
import numpy as np

from ocr_utils.scan_markup.db.models import KIND_COLOR, KIND_GRAYSCALE

# Доля самых светлых пикселей полосы, по которой оценивается цвет бумаги. 5% — это поля
# и просветы между строк: на полосе журнала бумаги всегда заметно больше, а брать больше
# незачем, дальше в выборку полезут светлые участки самих фотографий.
PAPER_PERCENTILE = 95.0

# Порог хроматичности в CIELAB: C = hypot(a - 128, b - 128). Около 10 лежит граница
# различимости оттенка глазом на печати; ниже — шум сканера и остатки неснятого налёта.
CHROMA_THR = 10.0

# Доля хроматичных пикселей, с которой область считалась цветной в ПРОШЛОЙ версии. Решение
# по ней больше не принимается (мотивировка выше), но само число считается и пишется в базу:
# по нему сравнивается старая разметка с новой без перечитывания оригиналов.
COLOR_FRAC_THR = 0.10

# Разброс хроматичности, с которого область считается цветной. Лежит посреди промежутка
# 6.5 .. 9.3 из замера выше, ближе к серым — цена ошибок несимметрична, лишний цветной JPEG
# стоит мегабайт, а серый вместо цветного означает потерянную картинку.
CHROMA_SPREAD_THR = 8.0

# Второе условие через «или», ВЫКЛЮЧЕННОЕ по умолчанию: на выборке порога, который делит
# ч/б и цветные по этой метрике, не нашлось (мотивировка в докстринге модуля). Оставлено
# опцией, чтобы включить его на другом паке, не правя код.
CHROMA_SELF_FRAC_THR = None


@dataclass(frozen=True)
class ColorKind:
    """Решение color/grayscale вместе со всеми тремя измерениями.

    Не кортеж намеренно: значения тащатся отсюда через ``detection.run`` в базу и в
    отладочный оверлей, и три однотипных числа, разложенные позиционно, рано или поздно
    поменяются местами без единой ошибки при импорте.
    """

    kind: str
    chroma_frac: float
    chroma_spread: float
    chroma_self_frac: float


def paper_color(bgr: np.ndarray, percentile: float = PAPER_PERCENTILE) -> np.ndarray:
    """Цвет бумаги полосы: средний BGR по самым светлым пикселям, float32 из трёх чисел.

    Считается ОДИН РАЗ НА ПОЛОСУ, а не на область: внутри фотографии светлых пикселей
    может не быть вовсе (тёмный снимок), и оценка налёта по ней самой была бы взята из
    её же содержимого — то есть сняла бы ровно тот цвет, который мы ищем.
    """
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    threshold = float(np.percentile(gray, percentile))
    bright = bgr[gray >= threshold]
    if bright.size == 0:  # вырожденный кадр — считаем бумагу нейтральной
        return np.array([128.0, 128.0, 128.0], dtype=np.float32)
    return bright.reshape(-1, 3).mean(axis=0).astype(np.float32)


def balanced_lab(bgr: np.ndarray, paper: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Каналы ``a`` и ``b`` CIELAB после снятия налёта бумаги, оба float32 со сдвигом к нулю.

    Баланс белого — поканальные коэффициенты ``mean(paper) / paper[c]``: они уводят цвет
    бумаги в нейтраль, сохраняя общую яркость (обычное деление на ``paper`` затемнило бы
    или высветлило бы кадр целиком и сдвинуло бы Lab).

    Отдельной функцией — потому что все три измерения ниже обязаны считаться по ОДНОМУ И
    ТОМУ ЖЕ Lab, а перевод 21-мегапиксельного кадра в Lab стоит заметно дороже, чем сами
    измерения по нему.
    """
    paper = np.asarray(paper, dtype=np.float32)
    gains = float(paper.mean()) / np.maximum(paper, 1.0)
    balanced = np.clip(bgr.astype(np.float32) * gains, 0, 255).astype(np.uint8)

    lab = cv2.cvtColor(balanced, cv2.COLOR_BGR2LAB)
    return lab[..., 1].astype(np.float32) - 128.0, lab[..., 2].astype(np.float32) - 128.0


def chroma_fraction(bgr: np.ndarray, paper: np.ndarray, chroma_thr: float = CHROMA_THR) -> float:
    """Доля пикселей области, оставшихся хроматичными после снятия налёта бумаги.

    Метрика ПРОШЛОЙ версии. Решение по ней больше не принимается, но она считается и
    пишется в базу — иначе старую разметку не с чем будет сравнить.
    """
    if bgr.size == 0:
        return 0.0
    a, b = balanced_lab(bgr, paper)
    return float(np.count_nonzero(np.hypot(a, b) > chroma_thr)) / float(a.size)


def classify(
    bgr: np.ndarray,
    paper: np.ndarray,
    chroma_thr: float = CHROMA_THR,
    color_frac_thr: float = COLOR_FRAC_THR,
    chroma_spread_thr: float = CHROMA_SPREAD_THR,
    chroma_self_frac_thr: float | None = CHROMA_SELF_FRAC_THR,
) -> ColorKind:
    """Решение color/grayscale по области вместе со всеми измерениями.

    Решает ``chroma_spread``. ``color_frac_thr`` в решении не участвует вовсе и оставлен
    ради опции CLI, управляющей записываемым ``chroma_frac``; ``chroma_self_frac_thr``
    добавляет второе условие через «или», только если задан явно.
    """
    if bgr.size == 0:  # вырожденная область не должна ронять прогон
        return ColorKind(KIND_GRAYSCALE, 0.0, 0.0, 0.0)

    a, b = balanced_lab(bgr, paper)
    chroma_frac = float(np.count_nonzero(np.hypot(a, b) > chroma_thr)) / float(a.size)
    spread = float(np.hypot(a.std(), b.std()))
    self_frac = float(np.count_nonzero(np.hypot(a - np.median(a), b - np.median(b)) > chroma_thr)) / float(a.size)

    is_color = spread > chroma_spread_thr or (chroma_self_frac_thr is not None and self_frac > chroma_self_frac_thr)
    return ColorKind(KIND_COLOR if is_color else KIND_GRAYSCALE, chroma_frac, spread, self_frac)
