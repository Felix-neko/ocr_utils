"""Цветная ли растровая область или полутоновая.

ЗАЧЕМ. Вырезанные из оригинала картинки вклеиваются в финальный PDF как JPEG. Серый JPEG
той же полосы весит втрое меньше цветного, а на страницу их бывает по три-четыре, так что
на выпуске это десятки мегабайт. Но пометить цветную картинку серой — значит потерять её
насовсем, поэтому порог смещён к ``color``.

ПОЧЕМУ НЕ ПРОСТО НАСЫЩЕННОСТЬ. Сканы жёлто-бежевые: бумага 1966 года пожелтела, и серая
типографская фотография на ней даёт устойчивый сепийный налёт по всей площади. Прямая
проверка «есть насыщенность -> цветная» назвала бы цветными вообще все области. Поэтому
налёт сначала СНИМАЕТСЯ: по светлым пикселям полосы оценивается цвет бумаги, область
балансируется по нему, и лишь потом меряется остаточная хроматичность. У серой печати
краска нейтральная, и после снятия налёта хроматичность схлопывается к нулю; у цветной
остаётся.

Мерится ДОЛЯ хроматичных пикселей, а не средняя хроматичность: цветной на полосе бывает
одна плашка на краю картинки, и в среднем по площади она тонет.
"""

import cv2
import numpy as np

from ocr_utils.scan_markup.db.models import KIND_COLOR, KIND_GRAYSCALE

# Доля самых светлых пикселей полосы, по которой оценивается цвет бумаги. 5% — это поля
# и просветы между строк: на полосе журнала бумаги всегда заметно больше, а брать больше
# незачем, дальше в выборку полезут светлые участки самих фотографий.
PAPER_PERCENTILE = 95.0

# Порог хроматичности в CIELAB: C = hypot(a - 128, b - 128). Около 10 лежит граница
# различимости оттенка глазом на печати; ниже — шум сканера и остатки неснятого налёта.
CHROMA_THR = 10.0

# Доля пикселей выше порога, с которой область считается цветной.
#
# Замер по 1966 целиком (582 полосы, 19 найденных областей, все проверены глазами):
#
#     ч/б фотографии внутри номера   0.000 .. 0.052   (остаточный налёт бумаги)
#     цветные обложки                0.177 .. 0.229
#
# Порог 0.10 лежит посреди пустого промежутка, с запасом почти вдвое в обе стороны, так
# что разделение устойчивое. Первоначальные 0.02 отправляли в color КАЖДУЮ ч/б фотографию:
# полностью снять сепийный налёт балансом белого по всей полосе не получается — у самой
# фотографии свой оттенок, отличный от полей.
#
# Смещение к color при этом сохраняется: слабейший настоящий цвет (0.177) отстоит от
# порога дальше, чем сильнейший ложный (0.052). Цена ошибок несимметрична — лишний цветной
# JPEG стоит мегабайт, а серый вместо цветного означает потерянную картинку.
#
# Выборка невелика и взята из одного года, поэтому величина остаётся опцией CLI, а
# chroma_frac пишется в базу по каждой области: перекалибровать порог можно будет по
# всему паку, не перечитывая оригиналы.
COLOR_FRAC_THR = 0.10


def paper_color(bgr: np.ndarray, percentile: float = PAPER_PERCENTILE) -> np.ndarray:
    """Цвет бумаги полосы: средний BGR по самым светлым пикселям, float32 из трёх чисел.

    Считается ОДИН РАЗ НА ПОЛОСУ, а не на область: внутри фотографии светлых пикселей
    может не быть вовсе (тёмный снимок), и оценка налёта по ней самой была бы взята из
    её же содержимого — то есть сняла бы ровно тот цвет, который мы ищем.
    """
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    threshold = float(np.percentile(gray, percentile))
    bright = bgr[gray >= threshold]
    if bright.size == 0:  # вырожденный кадр — считаем бумагу нейтральной
        return np.array([128.0, 128.0, 128.0], dtype=np.float32)
    return bright.reshape(-1, 3).mean(axis=0).astype(np.float32)


def chroma_fraction(bgr: np.ndarray, paper: np.ndarray, chroma_thr: float = CHROMA_THR) -> float:
    """Доля пикселей области, оставшихся хроматичными после снятия налёта бумаги.

    Баланс белого — поканальные коэффициенты ``mean(paper) / paper[c]``: они уводят цвет
    бумаги в нейтраль, сохраняя общую яркость (обычное деление на ``paper`` затемнило бы
    или высветлило бы кадр целиком и сдвинуло бы Lab).
    """
    if bgr.size == 0:
        return 0.0

    paper = np.asarray(paper, dtype=np.float32)
    gains = float(paper.mean()) / np.maximum(paper, 1.0)
    balanced = np.clip(bgr.astype(np.float32) * gains, 0, 255).astype(np.uint8)

    lab = cv2.cvtColor(balanced, cv2.COLOR_BGR2LAB)
    a = lab[..., 1].astype(np.float32) - 128.0
    b = lab[..., 2].astype(np.float32) - 128.0
    return float(np.count_nonzero(np.hypot(a, b) > chroma_thr)) / float(a.size)


def classify(
    bgr: np.ndarray, paper: np.ndarray, chroma_thr: float = CHROMA_THR, color_frac_thr: float = COLOR_FRAC_THR
) -> tuple[str, float]:
    """``(kind, chroma_frac)`` для области: ``KIND_COLOR`` либо ``KIND_GRAYSCALE``.

    ``chroma_frac`` возвращается вместе с решением и сохраняется в базу: без него
    перекалибровать порог по 12 тысячам полос значило бы второй проход по полутерабайту
    оригиналов с медленного диска.
    """
    fraction = chroma_fraction(bgr, paper, chroma_thr)
    return (KIND_COLOR if fraction > color_frac_thr else KIND_GRAYSCALE), fraction
