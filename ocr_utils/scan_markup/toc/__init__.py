"""Полосы оглавления: «Содержание» выпуска и указатель статей за год.

ЗАЧЕМ. Перед основным OCR-прогоном выпуска во внешней модели нужно знать полосы
оглавления заранее: их не отправлять в основной прогон, а сначала отправить отдельно,
извлечь список статей с авторами и рубриками и вставить его в промпт основного прогона
(тогда ``#`` получают только названия статей из списка). Всё это — до того, как хоть одна
обычная полоса ушла в модель, поэтому оглавление ищется здесь, на этапе детекции, а не
по ответу модели.

УСТРОЙСТВО ЖУРНАЛА (пак-1, 123 выпуска). До 1970/03 оглавление — одна полоса в конце
выпуска (1-4 полосы от конца), часто верхняя половина полосы, ниже — редколлегия. С
1970/04 оно на полосе 3 (шапка журнала + «СОДЕРЖАНИЕ» в правой колонке) и полосе 4 (хвост
оглавления + редколлегия и выходные данные; блок бывает крошечным). В декабрьских номерах
дополнительно «Указатель статей» / «Перечень материалов, опубликованных в журнале» —
3-7 полос в конце, начиная за 4-9 полос от последней; в 1967/12 в середину указателя
вклинился некролог с фотографией.

ДВА ПРИЗНАКА И ОКНО. Первый — метка ``TableOfContents`` surya layout из кэша разметки
(``detection/layout_cache``): по паку она помечает 230 полос, все внутри окна «первые 5 /
последние 12 полос выпуска», ложных в середине выпусков нет, но по полосам пропускает
10-15 % (вторая полоса оглавления, продолжения указателя). Второй — tesseract на полосах
окна: ключевые слова («СОДЕРЖАНИЕ», «УКАЗАТЕЛЬ», «ПЕРЕЧЕНЬ») и доля строк, кончающихся
числом у общего правого края (номера страниц). Окно режет пространство поиска в шесть раз
и делает tesseract посильным: ~2 200 полос на пак вместо 12 135.

ПОЛНОТА ВАЖНЕЕ ТОЧНОСТИ. Ложный кандидат стоит долю цента: запрос извлечения оглавления
ответит «не оглавление», и полоса уйдёт в основной прогон. Пропуск стоит неверного
промпта на весь выпуск. Поэтому решение — «ИЛИ» по признакам, а не «И», и помеченная
полоса подтягивает соседей, похожих на список.
"""

# Версия детектора оглавлений. Своя, как у ориентации и таблиц: правка порога здесь не
# должна заставлять перечитывать пак ради растра — и наоборот. Поднимать при изменении
# признаков или правил решения.
TOC_VERSION = 1

# Виды полос оглавления в решении детектора. В базе им отвечают два булевых признака
# ``pages.is_toc`` и ``pages.is_year_index`` (см. :func:`flags_from_kind`), в CVAT — два тега.
KIND_CONTENTS = "contents"  # «Содержание» выпуска
KIND_INDEX = "index"  # указатель статей за год в декабрьском номере
KINDS = (KIND_CONTENTS, KIND_INDEX)


def flags_from_kind(kind: "str | None") -> tuple[bool, bool]:
    """Вид -> (``is_toc``, ``is_year_index``); ``None`` -> (False, False)."""
    return kind == KIND_CONTENTS, kind == KIND_INDEX


def kind_from_flags(is_toc: "bool | None", is_year_index: "bool | None") -> "str | None":
    """(``is_toc``, ``is_year_index``) -> вид. Оба сразу — указатель: у него приоритет как у
    более редкого признака, а в списках для внешнего OCR полоса всё равно одна."""
    if is_year_index:
        return KIND_INDEX
    if is_toc:
        return KIND_CONTENTS
    return None


# Кто поставил вид: детектор или человек в CVAT. По этому полю видно, чему верить при
# расхождении, и прогон не затирает ручное решение.
SOURCE_AUTO = "auto"
SOURCE_CVAT = "cvat"

# Окно кандидатов: сколько полос от начала (обложка = 0) и от конца выпуска смотреть.
# По паку-1 все 230 полос с меткой surya лежат в idx_from_start <= 3 или idx_from_end <= 9;
# запас в одну-две полосы на выпуски с лишней вклейкой.
WINDOW_START = 4
WINDOW_END = 11

# Разрешение копии для tesseract: на 150 dpi откалиброван арбитр ориентации, и она вчетверо
# дешевле оригинала 600 dpi при уверенном чтении цифр номеров страниц.
WORK_DPI = 150
