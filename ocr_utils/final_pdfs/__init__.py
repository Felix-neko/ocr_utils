"""Сборка финальных PDF выпуска из двух прогонов FineReader, с правкой слоя и возвратом иллюстраций.

ЗАЧЕМ. FineReader распознал промежуточные PDF пака дважды: с коррекцией геометрии (выпрямляет
прогиб у корешка и перекос, но на части страниц гнёт линейки, чертежи и заголовки) и без неё
(геометрия как на скане — только так можно точно вернуть на место цветные и серые
иллюстрации, которых бинаризация лишила). Финальный PDF выпуска собирается ПОСТРАНИЧНО из
лучшего источника, потом на каждой странице чинится текстовый слой и поверх бинарного растра
кладутся иллюстрации из очищенных сканов.

ЧТО ДЕЛАЕМ, по странице:

1. Источник. Есть размеченный растр (``rect_regions.kind`` из ``PICTURE_KINDS``) — страница
   без коррекции (иначе иллюстрацию некуда класть). Иначе детектор порчи геометрии
   (``ocr_utils.geometry_regression``): ``bad`` — без коррекции, ``mixed``/``ok`` — с коррекцией.
2. Текстовый слой (``ocr_utils.text_layer_fix``): зоны повёрнутого текста и прямого текста
   без слоя на растре выбранной страницы, удаление россыпи FineReader по словам, чтение
   tesseract (второе мнение surya отдельной стадией на GPU), вставка своего невидимого текста.
3. Иллюстрации: вырезка из очищенной полосы шага 7 (``blurred/``, до заострения) по разметке базы, поворот на ``rotate_cw``
   полосы, сдвиг на поля промежуточной PDF, уменьшение до ``--picture-dpi`` (INTER_AREA,
   опционально Gaussian против растровой сетки), JPEG (серые — одноканальные) верхним слоем.
   Образы-фигуры FineReader под иллюстрацией (он кладёт фото отдельными JBIG2, 60–120 КБ
   каждый, а под ними основной образ пуст) снимаются с страницы — это и есть «затирание»
   без перекодирования JBIG2; при полностраничном растре снимаются все образы страницы.

Привязка страницы PDF к полосе — по порядку полос в базе (``order_index``), и на каждой
странице с иллюстрациями она СВЕРЯЕТСЯ: образ страницы без коррекции обязан быть равен
повёрнутой полосе плюс поля. Расхождение — выпуск не собирается: сборка со сдвигом на
страницу хуже отсутствия сборки.

Стадии прогона (``cli.run``): A — анализ страниц в пуле процессов (выбор источника, зоны,
tesseract; JSON на страницу в ``--work-dir``); B — surya в родителе по всем ненадёжным
зонам; C — сборка выпусков в пуле, сверка каждой страницы по сохранённому файлу,
``pages.csv`` и ``summary.csv``. Все стадии идемпотентны (``--skip-done``).
"""

