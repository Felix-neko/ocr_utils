"""Миллиметры бумаги ↔ пиксели скана: общий пересчёт размеров под любое разрешение (300, 450, 600 dpi).

ЗАЧЕМ. Пак-1 и пак-2 приходят TIFF с тегом 600 dpi (сняты в 300 и апскейлены), новые паки —
450 dpi без апскейла. Размер, названный в пикселях, при смене разрешения меняет смысл: окно 15 px
при 600 dpi — 0.64 мм бумаги, а при 450 — уже 0.85 мм. Поэтому все размеры, привязанные к бумаге
(штрих, отступ, ядро морфологии, площадь пятна), задаются в миллиметрах и переводятся в пиксели
по разрешению конкретной картинки.

ПЕРЕВОД СТАРЫХ ЧИСЕЛ. Константа, раньше заданная в пикселях, переводится в мм так, чтобы при
эталонном разрешении замера давать РОВНО прежнее число пикселей (с учётом округления). Рядом с
ней пишется происхождение: ``GROW_STEP_MM = 2.709  # 64 px при 600 dpi``. Тест
``tests/ocr_utils/test_units_legacy_px.py`` сверяет это для каждой переведённой константы.

Здесь же — ``ocr_utils.page_layout`` реэкспортирует ``MM_PER_INCH``, ``mm_to_px``, ``px_to_mm``,
чтобы старые импорты из него продолжали работать.
"""

MM_PER_INCH = 25.4


def mm_to_px(mm: float, dpi: float, minimum: int = 1) -> int:
    """Миллиметры бумаги → целые пиксели при данном dpi (не меньше ``minimum``).

    Args:
        mm: Длина на бумаге в миллиметрах.
        dpi: Разрешение картинки, точек на дюйм.
        minimum: Нижняя граница результата; 0 — для опций, где ноль значит «выключено».

    Returns:
        Длина в целых пикселях, округлённая к ближайшему и не меньше ``minimum``.
    """
    return max(minimum, int(round(mm * dpi / MM_PER_INCH)))


def mm_to_px_float(mm: float, dpi: float) -> float:
    """Миллиметры бумаги → пиксели без округления — для сигм размытия и дробных допусков.

    Args:
        mm: Длина на бумаге в миллиметрах.
        dpi: Разрешение картинки, точек на дюйм.

    Returns:
        Длина в пикселях (дробная).
    """
    return mm * dpi / MM_PER_INCH


def px_to_mm(px: float, dpi: float) -> float:
    """Пиксели при данном dpi → миллиметры бумаги.

    Args:
        px: Длина в пикселях.
        dpi: Разрешение картинки, точек на дюйм.

    Returns:
        Длина на бумаге в миллиметрах.
    """
    return px * MM_PER_INCH / dpi


def mm2_to_px2(mm2: float, dpi: float, minimum: int = 1) -> int:
    """Площадь на бумаге в мм² → целая площадь в пикселях² при данном dpi (не меньше ``minimum``).

    Площадь масштабируется квадратом разрешения: 900 px² при 600 dpi — это 506 px² при 450.

    Args:
        mm2: Площадь на бумаге в квадратных миллиметрах.
        dpi: Разрешение картинки, точек на дюйм.
        minimum: Нижняя граница результата; 0 — для опций, где ноль значит «выключено».

    Returns:
        Площадь в пикселях², округлённая к ближайшему и не меньше ``minimum``.
    """
    return max(minimum, int(round(mm2 * (dpi / MM_PER_INCH) ** 2)))


def px2_to_mm2(px2: float, dpi: float) -> float:
    """Площадь в пикселях² при данном dpi → площадь на бумаге в мм².

    Args:
        px2: Площадь в пикселях².
        dpi: Разрешение картинки, точек на дюйм.

    Returns:
        Площадь на бумаге в квадратных миллиметрах.
    """
    return px2 * (MM_PER_INCH / dpi) ** 2


def odd_px(mm: float, dpi: float) -> int:
    """Миллиметры бумаги → нечётная сторона ядра OpenCV (медиана, адаптивный порог): не меньше 3.

    Чётный результат округления добирается вверх до нечётного — так же, как раньше подбирались
    пиксельные ядра (41, 21), поэтому при эталонном dpi получается прежнее число.

    Args:
        mm: Сторона ядра на бумаге в миллиметрах.
        dpi: Разрешение картинки, точек на дюйм.

    Returns:
        Нечётная сторона ядра в пикселях, не меньше 3.
    """
    side = max(3, int(round(mm * dpi / MM_PER_INCH)))
    return side if side % 2 else side + 1
