"""Подпакет детектирования расфокуса в сканах газетных полос (RAF/JPEG).

Назначение — скрининг/ранжирование: найти среди сотен сканов выпуска те, где есть
расфокус (в т.ч. ЗОНАЛЬНЫЙ — размыта лишь часть полосы из-за наклона плоскости фокуса).

Структура (по одному модулю на «кирпич»):
- ``image_io``   — загрузка превью из RAF/JPEG, сбор файлов, тепловые карты;
- ``grid``       — разбиение кадра на сетку тайлов;
- ``moire``      — основной метод (энергия растрового муара) + нормировка (A),
                   гейт обложек (B), поиск связной 2D-зоны (C);
- ``laplacian``  — альтернативная метрика резкости (variance of Laplacian);
- ``fft_hf``     — независимый метод HF/MID (доля ВЧ-энергии) для кросс-проверки (E);
- ``pipeline``   — оркестрация: прогон метода + B/C/E, сводный вердикт;
- ``detect_defocus`` — CLI (склейка пайплайна и печать отчёта).

CLI: ``uv run python -m ocr_utils.legacy.defocus_detection ПУТЬ`` (см. README.md).

Подробное обоснование методов и история итераций — в README.md этого подпакета и в
``defocus_moire_improvement_plan.md`` / ``focus_detection_report.md`` в корне репозитория.
"""
