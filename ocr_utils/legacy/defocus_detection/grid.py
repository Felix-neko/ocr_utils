"""Разбиение кадра на равномерную сетку тайлов.

Все метрики считаются по тайлам, а не по всему кадру: это и ускоряет счёт, и
позволяет ловить ЗОНАЛЬНЫЙ расфокус (когда размыта лишь часть полосы).
"""


def tile_bounds(size: int, n: int, idx: int) -> tuple[int, int]:
    """Границы тайла [start, end) по одной оси для равномерной сетки.

    Args:
        size: Полный размер оси в пикселях.
        n: Число тайлов по этой оси.
        idx: Индекс тайла (0..n-1).

    Returns:
        Пара (start, end) — целочисленные границы тайла. Из-за целочисленного
        деления крайние тайлы могут отличаться по размеру на 1 пиксель.
    """
    return idx * size // n, (idx + 1) * size // n
