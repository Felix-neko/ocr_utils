"""Классы объектов, которые могут скрываться за подсказкой или областью line art: рисунок, схема, бланк, формула, таблица, надпись."""

from __future__ import annotations

from enum import Enum


class ObjectClass(str, Enum):
    """Класс объекта на полосе; значения — русские слова, как вид в ``detector_info`` базы.

    Подсказка детектору (``HintBox.likely``) несёт классы, которые подозревает её источник:
    блок surya ``Equation`` — формулу, ``Figure`` — схему или рисунок, схема детектора таблиц —
    схему. Вердикт стенда ``research/line_art_titles`` раскладывает области по тем же классам.
    """

    DRAWING = "рисунок"  # рисунок штрихом, чертёж, график
    DIAGRAM = "схема"  # блок-схема: коробки с текстом и связи
    FORM = "бланк"  # бланк: строки текста с линейками для заполнения
    FORMULA = "формула"  # выносная формула
    TABLE = "таблица"  # таблица
    TITLE = "надпись"  # стилизованный заголовок, рубрика, обрывок жирного набора


__all__ = ["ObjectClass"]
