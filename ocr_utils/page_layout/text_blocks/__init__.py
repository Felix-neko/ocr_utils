"""Детектор текстовых блоков: осевые кривые строк и гладкие огибающие блоков на кривой бумаге."""

from __future__ import annotations

# Версия разбора: меняется, когда меняются модель данных или алгоритмы — по ней инвалидируется кэш.
# v3 (2026-10-24, по коммиту 1d2de54): ось по базовой линии строки, колонка номеров оглавления, выключка блока,
# межколонники и края рядов.
# v4 (2026-10-26): серии выключки без отступов (``smooth_sides.TrendMode.SKIP_INDENT``), флаги строк с неизвестным краем
# у гладкой стороны, фильтр псевдоглифов (``pseudo_glyphs``, по умолчанию выключен) и отчёт ``pseudo_glyphs`` в разборе.
# v5 (2026-10-26): блоки делятся по смене стороны выключки с промежутком (``flush_split.FlushSplit.ALIGN_GAP``): подпись
# под абзацем и «г. Город» — свои блоки; ряд из далёких кусков с пустым просветом режется (ХиП 1991/01 IMG_1008 R).
# v6 (2026-10-26): короткий хвост строки без замеренных глифов сливается со своей строкой по одной жирности
# (``regroup._line_style_distance``, ХиП 1991/01 IMG_1030 R: «143 с.—» отдельным рядом ломал левую сторону списка).
# v7 (2026-10-31): разрез по смене выключки — ``FlushSplit.ALIGN_RIGHT_GAP`` (разрез ``ALIGN_RIGHT`` или ``ALIGN_GAP``,
# не внутри подписи); вертикальные линейки краски — барьеры рядов и блоков горизонтального текста
# (``page.RuleBarriers.INK``), горизонтальные — только в боковых областях вертикального текста (``side_rules``).
# v8 (2026-11-01): перекрытые по x компоненты маски глифов (точка «i», кратка «й», оторванная Оцу ветвь «к») — одна
# буква во всех замерах высот и боксах глифов (``glyph_merge.GlyphMerge.OVERLAP``): «к» из «ко-» больше не режется как
# сросшийся глиф двух строк, и «ко-» не уходит отдельным рядом (1968/05 IMG_0074_1L).
# v9 (2026-11-01): кегль куска строки и группы глифов достоверен только от трёх букв без мелочи
# (``typeset.KeglTrust.RELIABLE``): запреты по разнице кегля молчат, если хоть один кегль не замерен (сцепка «ОБ» +
# «ОПЕРАТИВНО…», 1973/03 IMG_0116_2R); мелочь отсекается по верхнему квартилю высот, а не по медиане (ось «СК» с
# тремя соринками, 1967/02 IMG_0095_2R). Резка высоких глифов — переключатель ``segment.TallGlyphCut``.
# v10 (2026-11-01): ряд режется в широком просвете и по баллу набора «кегль + жирность» (``blocks.RowStyleSplit.STYLE``):
# светлая подпись автора на высоте строки жирного заголовка близкого кегля — свой ряд (1969/05 IMG_0072_2R); строка-
# продолжение висячего списка пояснений («Q — объем…» / «поставки, руб.;») не уходит в свой блок как подпись
# (``blocks.HangingList.ALIGN``, 1975/02 IMG_0066_1L); подпись по центру своей оси под абзацем — свой блок
# (``flush_split.FlushChange.TO_CENTRE``, 1973/10 IMG_0173_2R).
TEXT_BLOCKS_VERSION = 10

# Рендер и рабочая копия. Строки ищутся на копии 150 dpi (как во всём проекте), центр-линии и края
# краски — на копии 300 dpi: бинарный рендер FineReader на 150 dpi теряет тонкие засечки.
RENDER_DPI = 300
WORK_DPI = 150

# Способ сцепки кусков в строки. ``zones`` — по зонам поиска (каждый кусок ведёт свою ось),
# ``greedy`` — прежняя жадная цепочка с полем хода строк (``legacy_linking``), оставлена для
# сравнения и как запасной ход.
LINKING_ZONES = "zones"
LINKING_GREEDY = "greedy"
LINKING_CHOICES = (LINKING_ZONES, LINKING_GREEDY)
LINKING_DEFAULT = LINKING_ZONES
