"""Разбор структуры страницы одним пакетом: растр, таблицы, line art, повёрнутый текст, ориентация, surya layout.

ЗАЧЕМ. До этого пакета одни и те же вопросы «где на странице фотография, где таблица, где
схема» решались в пяти местах пятью способами: растр — в ``scan_markup.detection``, таблицы и
схемы — в ``scan_markup.table_detection`` (с surya из кэша), крупный штрих — в
``line_art_detection`` (без surya), повёрнутый текст — в ``text_layer_fix``, и у каждого была
своя обёртка над surya и свой кэш. Этап ``detect`` размечал полосу одним набором детекторов, а
сборка финальных PDF (``geometry_regression``, ``text_layer_fix``) — другим, поэтому оценка
разметчика в CVAT говорила не о том детекторе, который реально решает судьбу страницы.

ЧТО ЗДЕСЬ. Единый вход ``PageImage`` (файл, массив или страница PDF; вариант картинки:
скан, заострённая, размытая, бинаризация FineReader с коррекцией геометрии и без), единая
модель surya и единый кэш её ответов (``surya``), детекторы по семействам (``raster``,
``tables``, ``line_art``, ``rotated_text``, ``orientation``) и фасад ``PageLayout``, который
зовёт их в правильном порядке: растр → таблицы → line art только вне растра и таблиц →
повёрнутый текст вне таблиц. Версии семейств — здесь же, чтобы у ``detect``, у детектора порчи
геометрии и у правки текстового слоя они были одни.

РАБОЧЕЕ РАЗРЕШЕНИЕ. Все пиксельные детекторы, кроме растрового, считают по копии
``WORK_DPI`` = 150 dpi (у 600-dpi сканов — копия 1/4); размеры в коде — в миллиметрах бумаги
через :func:`mm_to_px`. Растровому нужен полный кадр: точки сетки при 150 dpi уже не видны.
"""

# Рабочее разрешение пиксельных детекторов и кадра surya. 150 dpi: страница ~900×1400 px,
# линейки и штрих различимы, а один кадр весит мегабайт и без потерь ездит между процессами.
WORK_DPI = 150

MM_PER_INCH = 25.4


def mm_to_px(mm: float, dpi: float) -> int:
    """Миллиметры бумаги → целые пиксели при данном dpi (не меньше 1)."""
    return max(1, int(round(mm * dpi / MM_PER_INCH)))


def px_to_mm(px: float, dpi: float) -> float:
    """Пиксели при данном dpi → миллиметры бумаги."""
    return px * MM_PER_INCH / dpi


# --- Версии семейств детекторов -------------------------------------------------------------
# Каждое семейство помнит себя порознь: правка порога у таблиц не должна заставлять перечитывать
# пак ради растра (полтерабайта с медленного диска). Номер пишется потребителями рядом с
# результатом (колонки ``Page.*_version`` базы разметки, JSON кэшей geometry_regression и
# text_layer_fix) и решает при повторном прогоне, пересчитывать ли страницу.
#
# Поднимать при ЛЮБОМ изменении, меняющем результат семейства: пороги, морфология, правило вида,
# состав затравок. Не поднимать за оверлеи, сообщения, переименования.
RASTER_VERSION = 10  # растровый детектор: тот же алгоритм, что DETECTOR_VERSION 10 у scan_markup
TABLES_VERSION = 1  # детектор таблиц v4.2 (бывший TABLE_DETECTOR_VERSION)
LINE_ART_VERSION = 2  # единый line art: схемы детектора таблиц + surya Figure/Form/Picture + пятна и линейки, вне растра и таблиц; v2 — без формул (surya Equation)
ROTATED_TEXT_VERSION = 1  # зоны повёрнутого текста вне таблиц (Docstrum)
ORIENTATION_VERSION = 1  # ориентация полосы (бывший scan_markup.orientation.ORIENTATION_VERSION)


def version_tag() -> str:
    """Все версии одной строкой — для кэшей потребителей, которым нужен один ключ."""
    return f"r{RASTER_VERSION}-t{TABLES_VERSION}-l{LINE_ART_VERSION}-x{ROTATED_TEXT_VERSION}-o{ORIENTATION_VERSION}"
