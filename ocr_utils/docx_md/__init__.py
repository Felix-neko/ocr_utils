"""Подпакет конвертации DOCX → Markdown и нарезки Markdown на куски для LLM.

Два независимых инструмента для постобработки OCR-выгрузок журналов/книг (когда
OCR-движок отдаёт .docx, а дальше нужен удобный для LLM текст):

- ``docx_to_md``          — экспорт .docx в .md с сохранением структуры: заголовки,
                            абзацы, таблицы, полужирный/курсив и, главное,
                            КОЛОНТИТУЛЫ (в OCR-DOCX они лежат в текстовых блоках
                            внутри ``w:drawing`` и обычным ``paragraph.text`` не
                            видны — вытаскиваем их из XML);
- ``split_md_by_articles`` — нарезка полученного .md на куски по статьям для подачи
                            в LLM по стратегии Long Context (одна статья никогда не
                            рвётся между кусками).

CLI (каждый модуль — отдельная точка входа):

    uv run python -m ocr_utils.docx_md.docx_to_md          ФАЙЛ.docx | КАТАЛОГ ...
    uv run python -m ocr_utils.docx_md.split_md_by_articles ФАЙЛ.md   | КАТАЛОГ ...

Подробности, примеры и разбор устройства — в README.md этого подпакета.
"""
