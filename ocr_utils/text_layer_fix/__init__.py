"""Чистка и дополнение текстового слоя FineReader там, где на странице есть повёрнутый текст.

ЗАЧЕМ. Финальные PDF пака собираются из бинаризованных страниц FineReader с невидимым
текстовым слоем (render mode 3): читать будут глазами картинку, а искать — по слою.
Повёрнутый на 90/180/270° текст (шапки узких граф таблиц, подписи на блок-схемах и
чертежах, отдельные боковые подписи и колонтитулы) FineReader распознаёт как
горизонтальный: в слое на месте такого текста лежит россыпь «слов» из одного-трёх
случайных знаков, а на чертежах слоя нет вовсе. Поиск по таким местам не работает.

ЧТО ДЕЛАЕМ. Три шага на страницу. (1) На растре самой PDF-страницы (600 dpi JBIG2) находим
зоны повёрнутого текста: ячейки таблиц с боковым текстом (сетка и ориентация ячеек из
``ocr_utils.rotated_text.tables``), подписи на line art и отдельный повёрнутый текст
(направление на ближайших соседей глифа). (2) Разбираем поток содержимого страницы до
отдельных слов FineReader (один маркированный спан ``/Span <</MCID n>>`` на слово, один
``Tj`` на глиф), привязываем глифы к символам ``rawdict`` и решаем по каждому слову:
оставить, удалить (лежит в зоне), усечь (задето зоной частично) или только показать
как подозрительное. Удаление — вырезание ``BT … ET`` внутри спана; сам спан и дерево
структуры остаются, картинка не трогается. (3) Читаем зоны tesseract-ом (второе мнение
surya — отдельной стадией на GPU) и вписываем прочитанное невидимым повёрнутым текстом своим
``BT … ET`` в тот же поток (шрифт Noto Sans, Identity-H; не ``TextWriter`` — тот плодит потоки).
Прямой текст, для которого FineReader не написал ничего (подписи на схемах, ячейки без слоя),
тоже читается и вписывается.

ГРАНИЦА ЗАДАЧИ. Здесь ядро: разбор слоя (``text_layer``), растр (``raster``), зоны (``zones``,
``docstrum``), чтение (``ocr``, ``second_opinion``), вердикты (``classify``), правка и сверка
(``rewrite``, ``fixer``), кэш JSON на страницу (``cache``). Вызывает его сборщик финальных PDF
``ocr_utils.final_pdfs`` постранично; обзор слоя по паку, выборки, оверлеи, оценка источников
line art и сравнение с LLM — стенд ``ocr_utils.text_layer_fix``. Пороги — по отчёту
``reports/text_layer_fix.md``.
"""

from __future__ import annotations

# Версия алгоритма: входит в кэш JSON на страницу, старые записи при смене не подхватываются.
VERSION = 2  # v2: структура страницы (таблицы, line art, цепочки) — единым разбором page_layout с surya

# Рабочее разрешение анализа растра. Страница пака — 600 dpi; 150 dpi — 1/4, ~1000×1600 px.
# Размеры в коде заданы в миллиметрах бумаги и переводятся через ``mm_to_px`` от фактического dpi.
WORK_DPI = 150

# Разрешение растра страницы в PDF FineReader (JBIG2 в промежуточных PDF собран из сканов 600 dpi).
PAGE_DPI = 600

MM_PER_INCH = 25.4


def mm_to_px(mm: float, dpi: float) -> int:
    """Миллиметры бумаги → целые пиксели при данном dpi (не меньше 1).

    Args:
        mm: Размер на бумаге в миллиметрах.
        dpi: Разрешение растра, точек на дюйм.

    Returns:
        Число пикселей, округлённое, но не меньше единицы.
    """
    return max(1, int(round(mm * dpi / MM_PER_INCH)))


def px_to_mm(px: float, dpi: float) -> float:
    """Пиксели растра → миллиметры бумаги при данном dpi.

    Args:
        px: Расстояние в пикселях.
        dpi: Разрешение растра.

    Returns:
        Расстояние в миллиметрах (дробное).
    """
    return px * MM_PER_INCH / dpi
