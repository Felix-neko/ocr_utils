"""Уровень бумаги и отражение: общая нормировка скана, независимая от света.

ИДЕЯ. Работаем не с яркостью, а с ОТРАЖЕНИЕМ ``R = g / bg``, где ``bg`` — гладкая
оценка уровня бумаги: светлое раздувается, потом сильно размывается (та же «raise above
background», что в ScanTailor Equalize Illumination и в ``defocus_detection.scale.ink_map``).
У чистой бумаги R ≈ 1 независимо от того, жёлтая она или серая и как лёг свет.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Этим пользуются две подсистемы, и по разным поводам:

* ``show_through_detection`` — там нормировка и родилась: цвет бумаги и освещение
  гуляют от года к году, и абсолютный уровень серого признаком быть не может;
* ``background_smoothing`` — при чистке маски надо отличать настоящую краску от
  просвета с оборота, и абсолютная яркость тут тоже подводит. Замер на паке-1:
  в пересвеченной таблице 1966/01 IMG_0047_2R «краска» имеет яркость 123-193 при
  бумаге 255, то есть светлее, чем крапины просвета на 1976/01 IMG_0052_1L (медиана
  183 при бумаге 252). По ОТРАЖЕНИЮ они расходятся надёжно: 0.53 против 0.83.

Импортировать это из ``show_through_detection`` в ``background_smoothing`` было бы
неверно: обработка не должна зависеть от подсистемы детекции. Поэтому общий модуль, а
в ``zones.py`` остался реэкспорт — его потребители ничего не заметили.

РАЗМЕРЫ ОКОН ЗАДАЮТСЯ В ПИКСЕЛЯХ, А НЕ ДОЛЕЙ КАДРА. Соблазн вывести их из высоты
полосы велик и неверен: в «Готовое» попадают и НЕПОЛНЫЕ страницы — если текст занимал
треть листа, пустые две трети обрезаны, — и окно, посчитанное от высоты такого кадра,
схлопнется втрое, а набор на нём ровно тот же. Размеры определяются НАБОРОМ (толщиной
штриха и шагом строк), поэтому меряются один раз на паке и передаются явно; для
``show_through_detection`` пересчёт от высоты сохранён в его собственном ``zones.py``,
где он и был откалиброван.
"""

import cv2
import numpy as np

# Высота кадра, для которой названы размеры ниже: разворот пака «Плановое хозяйство»
# в 300 dpi. Свой эталон, а не ``scale.REFERENCE_HEIGHT`` (там 2944 — высота JPEG-превью
# из RAF совсем другого пака): числа замерены именно на этих сканах.
REFERENCE_HEIGHT = 2800.0

# Умолчания для пака-1 при 600 dpi. Замерено на нём же: толщина штриха 7 px, шаг строк
# 89 px (``defocus_detection.scale``). Радиус раздутия берётся в пару штрихов — чтобы
# буквы ушли из оценки бумаги целиком; окно размытия — крупнее буквы, но мельче
# неровности света, то есть порядка полутора шагов строк. Для другого пака или другого
# разрешения их надо ПЕРЕМЕРИТЬ и передать явно, а не полагаться на эти числа.
PAPER_DILATE_PX = 15
PAPER_BLUR_PX = 150

# Темнее этой доли от бумаги — настоящая краска, а не призрак. Замерено на просвете
# пака «Плановое хозяйство»; на паке-1 порог подтвердился: при нём подтверждается 96.3%
# площади краски в пересвеченной таблице и лишь 13.5% площади призрака.
INK_LEVEL = 0.65

# Часовой для ``--ink-level auto``: порог считается по самой полосе, а не берётся из
# константы. Отрицательное число — чтобы его нельзя было спутать с настоящей долей.
AUTO_INK_LEVEL = -1.0


def scaled(height: int, px_at_reference: float) -> int:
    """Пересчитывает размер, названный для ``REFERENCE_HEIGHT``, под текущую полосу.

    Args:
        height: Высота обрабатываемой полосы в пикселях.
        px_at_reference: Размер в пикселях при эталонной высоте.

    Returns:
        Размер в пикселях текущей полосы, не меньше единицы.
    """
    return max(1, int(round(scaled_float(height, px_at_reference))))


def scaled_float(height: int, px_at_reference: float) -> float:
    """То же, что :func:`scaled`, но без округления — для сигм гауссова размытия.

    Args:
        height: Высота обрабатываемой полосы в пикселях.
        px_at_reference: Размер в пикселях при эталонной высоте.

    Returns:
        Размер в пикселях текущей полосы.
    """
    return px_at_reference * height / REFERENCE_HEIGHT


def odd(value: int) -> int:
    """Ближайшее нечётное число не меньше единицы (ядра OpenCV любят нечётную сторону).

    Args:
        value: Желаемая сторона ядра.

    Returns:
        Нечётная сторона.
    """
    return value if value % 2 else value + 1


def disk(radius: int) -> np.ndarray:
    """Круглый структурный элемент заданного радиуса.

    Args:
        radius: Радиус в пикселях.

    Returns:
        Ядро для морфологии.
    """
    side = odd(2 * max(1, radius) + 1)
    return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (side, side))


def paper_level(gray: np.ndarray, dilate_px: int = PAPER_DILATE_PX, blur_px: int = PAPER_BLUR_PX) -> np.ndarray:
    """Гладкая оценка уровня бумаги: «сколько было бы яркости, не будь тут краски».

    Args:
        gray: Полутоновая полоса.
        dilate_px: Радиус раздутия светлого, пикс. Должен перекрывать толщину штриха,
            иначе буквы останутся в оценке бумаги и отражение под ними уедет к единице.
        blur_px: Сторона окна размытия, пикс. Крупнее буквы, мельче неровности света.

    Returns:
        Массив float32 той же формы.
    """
    img = gray.astype(np.float32)
    dilated = cv2.dilate(img, disk(dilate_px))
    side = odd(blur_px)
    return cv2.blur(dilated, (side, side))


def reflectance(gray: np.ndarray, dilate_px: int = PAPER_DILATE_PX, blur_px: int = PAPER_BLUR_PX) -> np.ndarray:
    """Отражение относительно бумаги: бумага ≈ 1.0, краска — заметно ниже.

    Args:
        gray: Полутоновая полоса.
        dilate_px, blur_px: см. :func:`paper_level`.

    Returns:
        Массив float32 в диапазоне [0, 1.2].
    """
    img = gray.astype(np.float32)
    return np.clip(img / np.maximum(paper_level(gray, dilate_px, blur_px), 1.0), 0.0, 1.2)
