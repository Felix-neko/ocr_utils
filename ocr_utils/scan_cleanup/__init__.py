"""Очистка пака сканов по разметке, уточнённой руками в CVAT.

Две операции за один проход по файлу:

1. ЗАКРАС размеченного под удаление — библиотечных печатей, рукописных надписей и
   «прочего» (``inpaint``). Маски берутся из базы ``scan_markup`` и им доверяют
   полностью: их проверил человек. Связные области группируются ПО ВСЕЙ ПОЛОСЕ, без
   деления по видам: надпись, обведённая по буквам, идёт в закрас одной операцией, а
   не буква за буквой, и соседняя с печатью пометка — вместе с ней, чтобы её штрихи
   не затекли в дыру печати. Заливщик — LaMa.
2. РАЗМЫТИЕ ФОНА вне контента (``smoothing``). Иллюстрации не ищутся сетью — их
   границы уже размечены и лежат в базе (``protect``).

Порядок именно такой: маска контента для размытия считается ПОСЛЕ закраса, иначе
краска печати попала бы под защиту и осталась неразмытой.

Устройство:

* ``source`` — база → плоские пиклуемые датаклассы (воркеры базу не видят);
* ``protect`` — защитная маска из растровых областей;
* ``prompts`` — промпты Stable Diffusion и выбор по фону под зоной;
* ``inpaint`` / ``smoothing`` — две операции;
* ``runner`` — обход пака: GPU-полосы в родителе, остальные в пуле;
* ``overlay`` — debug-оверлеи;
* ``compare`` — сравнение бэкендов закраса и вариантов защитной маски.

Механика закраса (ROI, группировка, вклейка) — в общем пакете ``ocr_utils.inpainting``,
который обслуживает и удаление пальцев; расчёт размытия — в
``ocr_utils.background_smoothing.processing``.
"""
