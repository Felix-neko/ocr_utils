"""Имена очищенных полос: к имени файла дописывается отпечаток исходника.

ЗАЧЕМ. Имена полос в паке ПОВТОРЯЮТСЯ: ``IMG_0034_1L.tif`` есть в тридцати выпусках
пака-1, и различает их только папка. Любой инструмент, который берёт полосы плоским
списком и теряет папку — а именно так их разбирает Capture One, — способен перепутать
одноимённые. На паке-1 это уже случилось: в ``1975/04/IMG_0034_1L.jpg`` легла полоса из
``1968/07``, обнаружилось это только сверкой содержимого, и по одному имени файла отличить
подмену было нечем.

С отпечатком в имени такая подмена перестаёт быть возможной незаметно: имя само называет,
из какого файла полоса получена, и несовпадение видно, не открывая картинку.

ПОЧЕМУ ОТПЕЧАТОК ИСХОДНИКА, А НЕ РЕЗУЛЬТАТА. Имя выходного файла должно быть известно ДО
того, как этот файл посчитан: на нём стоит ``--skip-if-exists``, ради которого прогон по
паку можно продолжить с середины. Отпечаток результата зависит от параметров очистки и
становится известен только после работы сети и фильтров — то есть проверять «уже готово?»
пришлось бы, посчитав всё заново, и флаг терял бы смысл целиком.

Отпечаток исходника, наоборот, лежит в базе с шага ``detect`` (``pages.file_hash``,
sha256), и по нему имя собирается мгновенно.

ДЛИНА. Восьми шестнадцатеричных знаков хватает: по паку-1 (12 135 полос) все 8-символьные
префиксы различны, а вероятность совпадения на выборке такого размера — порядка 1e-5.
Полный дайджест в имя не годится — 64 знака делают имя нечитаемым, а укоротить его всегда
можно так, что ``sha256sum`` исходника по-прежнему начинается ровно с этих знаков.
"""

import re

# Сколько знаков дайджеста уходит в имя.
HASH_PREFIX_LEN = 8

# Имя вида ``IMG_0034_1L.a1b2c3d4.tif``: основа, отпечаток, расширение.
_CLEANED_RE = re.compile(r"^(?P<stem>.+)\.(?P<hash>[0-9a-f]{%d})$" % HASH_PREFIX_LEN)


def hash_suffix(file_hash: "str | None") -> str:
    """Кусок имени с отпечатком: ``a1b2c3d4``. Пустой, если отпечатка нет."""
    if not file_hash:
        return ""
    return file_hash[:HASH_PREFIX_LEN].lower()


def cleaned_file_name(source_file_name: str, file_hash: "str | None", suffix: str) -> str:
    """Имя очищенной полосы: ``IMG_0034_1L.a1b2c3d4.tif``.

    Без отпечатка (полоса не проходила ``detect``) имя остаётся прежним: молча выдумывать
    отпечаток нельзя, а ронять прогон из-за отсутствующего — несоразмерно.
    """
    stem = source_file_name.rsplit(".", 1)[0]
    tag = hash_suffix(file_hash)
    return f"{stem}.{tag}{suffix}" if tag else f"{stem}{suffix}"


def cleaned_rel_path(source_rel_path: str, file_hash: "str | None", suffix: str) -> str:
    """То же, но для относительного пути: папка выпуска сохраняется."""
    head, _, name = source_rel_path.rpartition("/")
    cleaned = cleaned_file_name(name, file_hash, suffix)
    return f"{head}/{cleaned}" if head else cleaned


def split_cleaned_stem(stem: str) -> "tuple[str, str | None]":
    """Разбирает основу имени обратно: ``IMG_0034_1L.a1b2c3d4`` -> ``(основа, отпечаток)``.

    Нужен потребителям, которые получают файл СНАРУЖИ и должны понять, какой полосе он
    отвечает: выгрузка Capture One приходит без папок пака, и отпечаток в имени —
    единственное, что связывает её с базой надёжно.
    """
    match = _CLEANED_RE.match(stem)
    if match is None:
        return stem, None
    return match.group("stem"), match.group("hash")
