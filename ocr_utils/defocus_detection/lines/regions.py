"""Область строки -> прямоугольные куски, по которым честно мерить резкость.

ГЛАВНАЯ ПРОБЛЕМА, КОТОРУЮ РЕШАЕТ ЭТОТ МОДУЛЬ, — НАКЛОН СТРОК. Снимают с рук, плоскость
кадра заваливается, и строка на снимке идёт не строго горизонтально: трапециевидные
искажения дают наклон в несколько градусов, а по краям кадра он ещё и меняется от строки
к строке. Surya возвращает не оси-выровненный прямоугольник, а ПОЛИГОН из четырёх углов,
так что наклон известен точно. Вопрос в том, что с ним делать.

Три способа, и выбран третий:

1. **Взять охватывающий прямоугольник (bbox).** У наклонной строки он прихватывает
   бумагу сверху и снизу, а заодно выносные элементы соседних строк. Разбавление тем
   сильнее, чем больше наклон, — то есть в замер вносится ровно та пространственная
   зависимость, которую мы потом собираемся измерять как зональный расфокус. Негодно.

2. **Повернуть кроп по ``cv2.minAreaRect`` и ``warpAffine``.** Для метрики РЕЗКОСТИ это
   смертельно: любая интерполяция сама по себе размывает край (билинейная — примерно на
   треть-половину пикселя), и размывает тем сильнее, чем дальше угол от кратного 90°.
   Наклон по кадру меняется плавно — значит и добавленное размытие будет меняться плавно
   по кадру, и мы получим идеально гладкий ложный зональный сигнал, неотличимый от
   настоящего завала фокуса. Негодно категорически.

3. **Резать строку на короткие куски и брать ВПИСАННЫЙ прямоугольник каждого.** На
   отрезке в несколько высот строки наклон уводит границу на доли пикселя, и прямоугольник
   ``[max верхних y; min нижних y]`` целиком лежит внутри полигона. Ни одного
   пересчитанного пикселя: кроп берётся срезом массива. Это и сделано.

Побочная выгода третьего способа: кусок — более точная единица локализации, чем строка.
Строка газетной колонки бывает длиной в треть кадра и своим центром тяжести попадает в
тайл, к которому относится лишь наполовину; кусок в 6 высот строки лежит в одном тайле
почти всегда.
"""

from dataclasses import dataclass

import numpy as np

# Ширина куска в высотах породившей его строки. Шесть — компромисс между двумя
# требованиями. Снизу: в куске должно набраться достаточно перепадов, чтобы ``edge_stats``
# посчитал σ по статистике, а не по десятку случайных краёв (при высоте 20 px это кусок
# 20x120, то есть порядка сотни-двух измеримых краёв). Сверху: чем длиннее кусок, тем
# больше наклон уводит его границы, и тем уже становится вписанный прямоугольник — при
# наклоне 3° кусок в 6 высот теряет по вертикали около 0.3 высоты строки, а кусок в 20
# высот потерял бы её целиком.
DEFAULT_CHUNK_ASPECT = 6.0
# Какую долю высоты строки позволено съесть наклону. Вписанный прямоугольник куска ниже
# самой строки ровно на её вертикальный снос по длине куска, поэтому у наклонной строки
# кусок фиксированной ширины тем тоньше, чем сильнее наклон: при 3° кусок в шесть высот
# теряет треть высоты строки. Терять треть замеров там, где искажения сильнее, — это
# ровно тот пространственно неоднородный перекос, который мы собираемся измерять как
# зональный расфокус. Поэтому ширина куска не фиксирована, а УКОРАЧИВАЕТСЯ под наклон
# так, чтобы потеря не превышала этой доли (см. ``line_chunks``).
MAX_SLANT_LOSS = 0.25
# Кусок тоньше этого не измеряем: на трёх строках развёртки статистики краёв не построить.
MIN_CHUNK_HEIGHT = 6
# И короче этого тоже: слишком мало краёв вдоль строки.
MIN_CHUNK_WIDTH = 16


@dataclass(frozen=True)
class LineRegion:
    """Область одной строки текста, найденная детектором.

    Attributes:
        polygon: Четыре угла (4, 2) в координатах ПОЛНОГО кадра, порядок произвольный —
            приводится к каноническому в ``corners()``.
        confidence: Уверенность детектора либо NaN, если он её не сообщил.
    """

    polygon: np.ndarray
    confidence: float = float("nan")

    def corners(self) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        """Углы полигона в каноническом порядке.

        Порядок углов от surya не документирован и зависит от постобработки тепловой
        карты, поэтому он не предполагается, а восстанавливается.

        Канонизация идёт СНАЧАЛА ПО X: два левых угла, два правых, и уже внутри пары —
        верхний и нижний. Наивный порядок «сначала по Y» здесь неверен, и неверен не в
        экзотическом случае, а в самом обычном. Газетная строка длиной в колонку — это
        сотни пикселей при высоте в два десятка, и наклона в три градуса хватает, чтобы
        снос по вертикали (31 px на длине 600) превысил высоту строки (20 px). Тогда оба
        «наименьших y» оказываются на ОДНОМ, левом конце строки, полигон рассыпается, и
        высота строки вылезает завышенной в полтора раза. Ширина же строки превосходит её
        высоту всегда, так что разделение по X устойчиво при любом реальном наклоне.

        Returns:
            Кортеж (верх-лево, верх-право, низ-право, низ-лево), каждый — массив (2,).
        """
        points = np.asarray(self.polygon, dtype=np.float64).reshape(4, 2)
        by_x = points[np.argsort(points[:, 0], kind="mergesort")]
        left, right = by_x[:2], by_x[2:]
        left = left[np.argsort(left[:, 1], kind="mergesort")]
        right = right[np.argsort(right[:, 1], kind="mergesort")]
        return left[0], right[0], right[1], left[1]

    @property
    def height(self) -> float:
        """Высота строки в пикселях.

        Меряется как средняя вертикальная толщина полигона по левому и правому краю, а НЕ
        как высота охватывающего прямоугольника: у наклонной строки последняя завышена на
        весь вертикальный снос и растёт вместе с наклоном. Нам же нужен кегль, и он от
        наклона зависеть не должен — иначе фильтр «мелкий текст» выкосил бы наклонные
        строки, то есть один край кадра.

        Returns:
            Высота в пикселях.
        """
        tl, tr, br, bl = self.corners()
        return float(((bl[1] - tl[1]) + (br[1] - tr[1])) / 2.0)

    @property
    def centre(self) -> tuple[float, float]:
        """Центр тяжести полигона (x, y).

        Returns:
            Пара координат в пикселях полного кадра.
        """
        points = np.asarray(self.polygon, dtype=np.float64).reshape(4, 2)
        return float(points[:, 0].mean()), float(points[:, 1].mean())


@dataclass(frozen=True)
class Chunk:
    """Прямоугольный кусок строки, вписанный в её полигон.

    Attributes:
        x1: Левая граница (включительно).
        y1: Верхняя граница (включительно).
        x2: Правая граница (исключительно).
        y2: Нижняя граница (исключительно).
        line_height: Высота породившей строки — нужна для нормировки σ на кегль.
    """

    x1: int
    y1: int
    x2: int
    y2: int
    line_height: float

    @property
    def centre(self) -> tuple[float, float]:
        """Центр куска (x, y) — по нему кусок относится к тайлу зональной сетки.

        Returns:
            Пара координат в пикселях.
        """
        return (self.x1 + self.x2) / 2.0, (self.y1 + self.y2) / 2.0

    def crop(self, gray: np.ndarray) -> np.ndarray:
        """Вырезает кусок из кадра.

        Это именно СРЕЗ массива, без копирования и без единой интерполяции: любой
        пересчёт пикселей исказил бы измеряемую величину (см. докстринг модуля).

        Args:
            gray: Полутоновый кадр полного разрешения.

        Returns:
            Представление участка кадра.
        """
        return gray[self.y1 : self.y2, self.x1 : self.x2]


def _edge_y(x: float, left: np.ndarray, right: np.ndarray) -> float:
    """Ордината ребра полигона в точке x (линейная интерполяция между его концами).

    Args:
        x: Абсцисса, в которой берётся ребро.
        left: Левый конец ребра (2,).
        right: Правый конец ребра (2,).

    Returns:
        Ордината ребра; у вырожденного по x ребра — ордината левого конца.
    """
    span = right[0] - left[0]
    if abs(span) < 1e-9:
        return float(left[1])
    return float(left[1] + (right[1] - left[1]) * (x - left[0]) / span)


def _slant(tl: np.ndarray, tr: np.ndarray, bl: np.ndarray, br: np.ndarray) -> float:
    """Наклон строки как модуль тангенса — среднее по верхнему и нижнему ребру.

    Args:
        tl: Верхний левый угол.
        tr: Верхний правый угол.
        bl: Нижний левый угол.
        br: Нижний правый угол.

    Returns:
        Модуль наклона (0 — строка горизонтальна).
    """
    slopes = []
    for left, right in ((tl, tr), (bl, br)):
        span = right[0] - left[0]
        if abs(span) > 1e-9:
            slopes.append(abs((right[1] - left[1]) / span))
    return float(np.mean(slopes)) if slopes else 0.0


def line_chunks(
    region: LineRegion,
    shape: tuple[int, int],
    aspect: float = DEFAULT_CHUNK_ASPECT,
    min_height: int = MIN_CHUNK_HEIGHT,
    min_width: int = MIN_CHUNK_WIDTH,
) -> list[Chunk]:
    """Режет строку на куски и вписывает в каждый прямоугольник.

    Кусок гарантированно лежит внутри полигона строки: его верх — НИЖНЯЯ из ординат
    верхнего ребра на концах куска, низ — ВЕРХНЯЯ из ординат нижнего ребра. Поэтому
    бумага над наклонной строкой и выносные элементы соседей в замер не попадают, а
    поворачивать (и тем самым пересчитывать) кроп не приходится.

    Args:
        region: Область строки.
        shape: Размер кадра (height, width) — куски обрезаются по его границам.
        aspect: Ширина куска в высотах строки.
        min_height: Минимальная высота куска в пикселях.
        min_width: Минимальная ширина куска в пикселях.

    Returns:
        Список кусков; пустой, если строка слишком тонкая, короткая или наклонена так
        сильно, что вписанного прямоугольника не остаётся.
    """
    tl, tr, br, bl = region.corners()
    height = region.height
    if height < min_height:
        return []

    # Горизонтальный диапазон, где определены ОБА ребра. У наклонного полигона левый
    # верхний и левый нижний углы стоят на разных x, и за пределами их пересечения
    # «вписанный прямоугольник» пришлось бы достраивать экстраполяцией.
    x_left = max(tl[0], bl[0])
    x_right = min(tr[0], br[0])
    frame_h, frame_w = shape
    x_left = max(0.0, x_left)
    x_right = min(float(frame_w), x_right)
    if x_right - x_left < min_width:
        return []

    # Ширина куска: не длиннее ``aspect`` высот строки и не длиннее того, на чём наклон
    # съедает больше ``MAX_SLANT_LOSS`` её высоты. У ровной строки (наклон ~0) работает
    # только первое ограничение, у сильно наклонной — второе.
    slant = _slant(tl, tr, bl, br)
    step = aspect * height
    if slant > 1e-6:
        step = min(step, MAX_SLANT_LOSS * height / slant)
    step = max(float(min_width), step)

    # Округление ВВЕРХ, а не к ближайшему: ``step`` — это верхняя граница, при которой
    # обещание «наклон съест не больше MAX_SLANT_LOSS» ещё выполняется, и округление
    # вниз молча делало бы куски длиннее допустимого.
    count = max(1, int(np.ceil((x_right - x_left) / step)))
    edges = np.linspace(x_left, x_right, count + 1)

    chunks: list[Chunk] = []
    for xa, xb in zip(edges[:-1], edges[1:]):
        # Горизонтальные границы округляются до целых ПЕРВЫМИ, и рёбра считаются уже в
        # них. Порядок важен: округление раздвигает кусок наружу (floor слева, ceil
        # справа), а у наклонной строки на этой добавке ребро успевает уйти — и
        # вписанный прямоугольник, посчитанный по дробным границам, вылезал бы за
        # полигон на доли пикселя.
        x1 = max(0, int(np.floor(xa)))
        x2 = min(frame_w, int(np.ceil(xb)))
        if x2 - x1 < min_width:
            continue
        # Вписанный прямоугольник: у верхнего ребра берём НАИБОЛЬШУЮ ординату на концах
        # отрезка (она ниже, то есть внутри строки), у нижнего — наименьшую.
        top = max(_edge_y(x1, tl, tr), _edge_y(x2, tl, tr))
        bottom = min(_edge_y(x1, bl, br), _edge_y(x2, bl, br))
        y1 = max(0, int(np.ceil(top)))
        y2 = min(frame_h, int(np.floor(bottom)))
        if y2 - y1 >= min_height:
            chunks.append(Chunk(x1=x1, y1=y1, x2=x2, y2=y2, line_height=height))
    return chunks
