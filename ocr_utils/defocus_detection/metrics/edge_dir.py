"""Направленная резкость по спектру: отделяет смаз от движения от промаха фокуса.

ИДЕЯ. Промах фокуса размывает одинаково во все стороны: круглая апертура даёт круглое
пятно рассеяния, и высокие частоты гаснут равномерно по всем направлениям. Смаз от
движения — это свёртка с отрезком, и в спектре она гасит частоты ВДОЛЬ направления
движения, почти не трогая поперечные. Значит достаточно посмотреть, как распределена
высокочастотная энергия по направлениям: у расфокуса поровну, у смаза — провал в одном
секторе, и этот сектор указывает, куда дёрнулась камера.

ПОЧЕМУ ПО СПЕКТРУ, А НЕ ПО ШИРИНЕ КРАЯ. Первая версия меряла ширину края в четырёх
повёрнутых копиях кадра, и обе попытки провалились по измеримым причинам, которые стоит
помнить:

* поворот сам размывает, причём тем сильнее, чем дальше угол от нуля, — на идеально
  резком кадре получалась «анизотропия» 1.40 просто из-за билинейной интерполяции;
* чтобы увидеть смаз в 15 px, пришлось поднять отсечку длины перепада с 12 до 36 px, а
  вместе с длинными штрихами в замер хлынули плавные фоновые градиенты, одинаковые во
  всех направлениях, — и направленная чувствительность пропала вовсе (анизотропия 1.01
  на кадре, смазанном на 15 пикселей).

Спектральный замер свободен от обоих: он не двигает пиксели вообще и не опирается ни на
какие пороги «что считать штрихом».

ПРО НАКЛОН СТРОК. Камера смотрит на полосу то прямо, то под углом, и текст сам по себе
анизотропен — вертикальные штрихи букв дают в спектре не то же, что горизонтальные. Чтобы
наклон полосы не притворялся смазом, секторы отсчитываются не от осей кадра, а от
направления строки (``scale.text_angle``). Поворачивать при этом ничего не нужно: секторы
— это маска в частотной области, её достаточно построить со сдвигом.

ЧТО ЭТО НЕ УМЕЕТ. Собственная анизотропия набора никуда не девается: у гарнитуры с
контрастным штрихом вертикали и горизонтали заведомо неравноправны, поэтому «анизотропия
1.0» на резком газетном кадре не гарантирована, и абсолютный порог «смаз/не смаз» обязан
калиброваться на материале. Мера отвечает на вопрос «насколько этот кадр анизотропнее
обычного», а не «есть ли анизотропия вообще».
"""

import numpy as np

from ocr_utils.defocus_detection.metrics.base import Algorithm
from ocr_utils.defocus_detection.scale import text_angle
from ocr_utils.defocus_detection.tiles import Grid

# Сколько секторов по направлениям. Спектр вещественного изображения центрально
# симметричен, поэтому весь диапазон направлений — это 180°, и четыре сектора дают
# разрешение 45°: достаточно, чтобы назвать направление смаза, и достаточно широко,
# чтобы в каждом секторе набралось сколько-то энергии.
N_SECTORS = 4

# Радиальная полоса, в которой сравниваются секторы, в долях частоты Найквиста. Низкие
# частоты выброшены: там сидит вёрстка (колонки, поля, плашки), а не резкость. Совсем
# высокие тоже: там шум матрицы, который у размытого кадра никуда не девается и
# провалы в спектре замазывает.
BAND_LO, BAND_HI = 0.18, 0.62
# Опорная полоса средних частот. Нужна, чтобы получить БАЛЛ РЕЗКОСТИ, а не только меру
# анизотропии: доли энергии по секторам в сумме дают единицу, поэтому по ним не видно,
# сколько высоких частот кадр потерял вообще. Отношение ВЧ к СЧ внутри того же сектора
# эту информацию возвращает и при этом не зависит ни от контраста, ни от плотности набора.
MID_LO, MID_HI = 0.06, 0.18

# Минимальная сторона тайла: на меньшем куске спектральное разрешение по направлениям
# уже не позволяет разделить секторы.
MIN_TILE = 96


def _sector_energy(tile: np.ndarray, base_angle: float) -> tuple[np.ndarray, np.ndarray]:
    """Высокочастотная энергия тайла по секторам направлений.

    Args:
        tile: Полутоновый кусок кадра.
        base_angle: Наклон строк в градусах — от него отсчитываются секторы.

    Returns:
        Кортеж (доли ВЧ-энергии по секторам, сумма равна 1; отношение ВЧ/СЧ по секторам).
        Оба массива длины ``N_SECTORS``, NaN — если тайл мал или энергии нет вовсе.
    """
    height, width = tile.shape[:2]
    nan = np.full(N_SECTORS, np.nan)
    if min(height, width) < MIN_TILE:
        return nan, nan

    img = tile.astype(np.float64)
    img = img - img.mean()
    # Окно Хэннинга гасит разрыв на границах тайла: без него шов даёт крест в спектре,
    # то есть ложную энергию строго вдоль осей — ровно там, где мы ищем анизотропию.
    img = img * np.hanning(height)[:, None] * np.hanning(width)[None, :]
    power = np.abs(np.fft.rfft2(img)) ** 2

    fy = np.fft.fftfreq(height)[:, None]
    fx = np.fft.rfftfreq(width)[None, :]
    radius = np.sqrt(fy**2 + fx**2) / 0.5  # 1.0 — частота Найквиста
    band = (radius >= BAND_LO) & (radius <= BAND_HI)
    mid = (radius >= MID_LO) & (radius < MID_HI)
    if not band.any() or not mid.any():
        return nan, nan

    # Направление частоты, отсчитанное от строки текста и свёрнутое в диапазон [0, 180).
    angle = (np.degrees(np.arctan2(fy, fx)) - base_angle) % 180.0
    sector = np.clip((angle / (180.0 / N_SECTORS)).astype(np.int64), 0, N_SECTORS - 1)

    high = np.bincount(sector[band].ravel(), weights=power[band].ravel(), minlength=N_SECTORS)
    low = np.bincount(sector[mid].ravel(), weights=power[mid].ravel(), minlength=N_SECTORS)
    total = float(high.sum())
    if total <= 0:
        return nan, nan
    with np.errstate(invalid="ignore", divide="ignore"):
        ratio = high / np.maximum(low, 1e-12)
    return high / total, ratio


def sector_map(gray: np.ndarray, grid: Grid, base_angle: float | None = None) -> tuple[np.ndarray, np.ndarray]:
    """Доли высокочастотной энергии по секторам для каждого тайла.

    Args:
        gray: Полутоновый кадр.
        grid: Сетка тайлов.
        base_angle: Наклон строк в градусах; None — оценить по центру кадра.

    Returns:
        Кортеж (доли ВЧ-энергии, отношения ВЧ/СЧ), оба формы (ny, nx, N_SECTORS);
        NaN там, где посчитать не удалось.
    """
    if base_angle is None:
        # Наклон берём по центральной части кадра: там гарантированно текст, а трапеция
        # искажает угол слабее всего.
        height, width = gray.shape[:2]
        cy, cx = height // 2, width // 2
        half = min(height, width) // 6
        base_angle = text_angle(gray[cy - half : cy + half, cx - half : cx + half])

    shares = np.full((grid.ny, grid.nx, N_SECTORS), np.nan)
    ratios = np.full((grid.ny, grid.nx, N_SECTORS), np.nan)
    for iy in range(grid.ny):
        for ix in range(grid.nx):
            y1, y2, x1, x2 = grid.bounds(iy, ix)
            shares[iy, ix], ratios[iy, ix] = _sector_energy(gray[y1:y2, x1:x2], base_angle)
    return shares, ratios


def anisotropy(sectors: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Насколько неравномерно распределена энергия по направлениям и куда провал.

    Args:
        sectors: Массив долей ВЧ-энергии (ny, nx, N_SECTORS) — первый элемент того,
            что вернул ``sector_map``.

    Returns:
        Кортеж (отношение max/min по тайлам, направление провала в градусах относительно
        строки — то есть предполагаемое направление смаза).

    Note:
        Направление квантовано шагом 45°, и когда смаз идёт ровно по границе секторов,
        он может попасть в любой из двух соседних. Величина отношения при этом верна —
        грубая тут только стрелка, а не сам факт смаза.
    """
    complete = np.isfinite(sectors).all(axis=2)
    with np.errstate(invalid="ignore", divide="ignore"):
        strongest = np.nanmax(sectors, axis=2)
        weakest = np.nanmin(sectors, axis=2)
        ratio = np.where(complete, strongest / np.maximum(weakest, 1e-12), np.nan)
    # Смаз гасит частоты ВДОЛЬ движения, поэтому направление движения — это сектор с
    # наименьшей энергией, а не с наибольшей.
    index = np.argmin(np.where(np.isfinite(sectors), sectors, np.inf), axis=2)
    step = 180.0 / N_SECTORS
    angle = np.where(complete, index * step + step / 2.0, np.nan)
    return ratio, angle


def _tile_sharpness(gray: np.ndarray, grid: Grid) -> np.ndarray:
    """Карта резкости по САМОМУ МЯГКОМУ направлению (больше = резче).

    Балл — отношение ВЧ-энергии к СЧ-энергии В ТОМ СЕКТОРЕ, ГДЕ ВЧ МЕНЬШЕ ВСЕГО, то есть
    вдоль направления наибольшего размытия. Читаемость определяет именно худшее
    направление, а не среднее по кадру.

    Долю энергии сектора как балл резкости брать НЕЛЬЗЯ, и это не мелочь: доли в сумме
    дают единицу, поэтому равномерная потеря высоких частот их не меняет вовсе — при
    расфокусе такой «балл» даже растёт (замерено: 0.65 у резкого кадра против 0.72 при
    σ=2). Отношение ВЧ/СЧ этим не страдает.

    Args:
        gray: Полутоновый кадр.
        grid: Сетка тайлов.

    Returns:
        Массив (ny, nx); NaN там, где посчитать не удалось.
    """
    shares, ratios = sector_map(gray, grid)
    complete = np.isfinite(shares).all(axis=2) & np.isfinite(ratios).all(axis=2)
    weakest = np.argmin(np.where(np.isfinite(shares), shares, np.inf), axis=2)
    value = np.take_along_axis(ratios, weakest[:, :, None], axis=2)[:, :, 0]
    return np.where(complete, value, np.nan)


ALGORITHM = Algorithm(
    name="edge_dir",
    summary="направленная ВЧ-энергия спектра: ловит смаз, который изотропная метрика усредняет",
    tile_sharpness=_tile_sharpness,
    unit="ВЧ/СЧ в слабейшем направлении",
    # По областям строк эта метрика не работает: кусок строки — это десятки пикселей, а
    # разделить там четыре сектора спектра нечем. Режим --use-surya-lines с ней запрещён
    # явно (см. cli.py), чтобы не получить молча полный NaN.
    supports_regions=False,
)
