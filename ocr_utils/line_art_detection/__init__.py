"""Поиск страниц с крупным штриховым рисунком в бинаризованных PDF.

ЗАЧЕМ. FineReader с включённым «исправлением искажений строк» иногда корёжит на странице
line art: на стр. 80 файла ``full_1967_01_bg_off_ori_off.pdf`` схема организации
диспетчерской службы вышла с чёрными гребёнками вместо рамок и надписей. Такие страницы
при сборке финального PDF надо брать из бинаризации, сделанной БЕЗ распрямления строк.
Чтобы найти их глазами, не просматривая все девять тысяч полос пака, нужен признак «на
этой странице есть сколько-нибудь крупный штрих».

ЧТО ИЩЕТСЯ. Крупные штриховые рисунки, гравюры, схемы и карты; крупные разлинованные
таблицы; графики и диаграммы; многострочные формулы (последние — только с
``--use-surya-layout``). Мелочь — виньетки, эмблемы рубрик, буквицы — не ищется
намеренно: покорёженная виньетка никому не мешает.

ЧТО НЕ ИЩЕТСЯ. Полутоновые фотографии: распрямление строк их так заметно не портит.
Отделить их от штриха по пикселям на этом материале не вышло (замер — в ``features``),
поэтому они отсеиваются по выверенной вручную разметке из базы ``scan_markup`` (``--db``).

КАК ЭТО РАБОТАЕТ. Текст распадается на пятна размером с букву, рисунок даёт одно длинное
связное пятно, типографская линейка — пятно длинное, но одномерное, а чёрная кайма скана —
сплошная масса. Отсюда четыре правила: площадь, короткая сторона, вытянутость рамки и
ПЛОТНОСТЬ (штрих исчезает при эрозии диском в два штриха, сплошная масса остаётся).
Разлинованная таблица не является одним пятном вовсе — линейки в этой печати друг друга не
касаются, — поэтому ищется отдельно, по скоплению линеек обеих ориентаций. Подробности и
все замеры — в докстринге ``features``.

ПРОГОН РАЗБИТ НА ДВЕ КОМАНДЫ. ``scan`` считает признаки всех страниц и кладёт их в CSV
вместе с найденными прямоугольниками; ``export`` применяет к готовому CSV порог и
раскладывает картинки по папкам. Порог подбирается глазами и не с первого раза, а
тяжёлый проход при этом делается один раз.

    # признаки всех страниц -> CSV (единожды)
    uv run python -m ocr_utils.line_art_detection scan \\
        --input-dir /mnt/SYSTEM/raw/mts/pack1_pdf/full_pdfs_binary_brightened_bg \\
        --db ~/Projects/mts_markup/pack1_reviewed.sqlite --pack-name пак-1 \\
        --csv line_art_pack1.csv --md-report reports/line_art_pack1.md

    # картинки для просмотра (сколько угодно раз, с разными порогами)
    uv run python -m ocr_utils.line_art_detection export \\
        --csv line_art_pack1.csv --out-dir line_art_pack1_05 --min-coverage 0.05

НЕДОПИСАННАЯ ВЫГРУЗКА. Эти PDF выгружает FineReader часами, и прогон легко приходится на
середину выгрузки. Поэтому ``scan`` пропускает файлы моложе ``--min-age-minutes`` (10) и
говорит об этом в stderr: отчёт по неполной папке внешне неотличим от полного.

СТОИМОСТЬ. 0.25 с на страницу в один поток при полных 600 dpi, то есть порядка двух с
половиной минут на весь пак при ``--jobs 16``. С ``--use-surya-layout`` — около двух
часов, поэтому разметка Surya кэшируется на диск.
"""
