"""Сглаживание фона сканов перед бинаризацией в FineReader.

ЗАЧЕМ. Сканы после ScanTailor отдаются в FineReader НЕбинаризованными намеренно:
полутона на границах букв помогают распознаванию. Но FineReader бинаризует
локально-адаптивным порогом и на пустом поле цепляется за две вещи — просвет
текста с оборота листа (bleed-through) и неровный тон бумаги. В итоге «перец»
там, где не было ничего. Замер по паку 1966/03 (600 dpi): бумага 250-253,
призрак с оборота 219-250 и до 4.65% площади кадра, ядро букв ниже 200.

ИДЕЯ. Грубо найти тёмный контент, защитить его маской с солидным припуском, а
весь остальной кадр заменить сильно размытым. Локальная фактура фона (и призрак,
и зерно бумаги) усредняется в ровное поле, а буквы со всеми полутонами доходят
до FineReader нетронутыми — под маской результат побитово равен исходнику.

ПАЙПЛАЙН (по кадру):

1. ``M_primary`` — первичная маска контента: глобальный порог Оцу, сдвинутый в
   сторону бумаги (щедрее — лучше не размыть часть фона, чем размыть контент),
   опционально уточнённый локальным порогом Саволы.
2. ``M_dilated`` — та же маска с припуском ≈15 px при 600 dpi (ядро ≈30x30,
   половинка средней буквы): под защиту должны попасть полутона на границах букв,
   бледные перемычки и тонкие переходы.
3. ``I_blurred`` — размытие радиусом в несколько раз больше припуска, НОРМИРОВАННОЕ:
   пиксели ``M_dilated`` исключены из усреднения, иначе чернила соседних строк
   затягиваются в фон (мотивировка с замерами — в докстринге ``processing``).
4. ``I_final`` — под ``M_dilated`` берётся исходник, вне её — ``I_blurred``.

Растровые иллюстрации и обложки этим не обрабатываются: здесь цель — текст и line
art. Такие кадры распознаются автоматически (крупные сплошные области средних тонов
либо отсутствие разделения на чернила и бумагу) и копируются на выход БЕЗ ИЗМЕНЕНИЙ —
у них зерно является содержимым, и размытие выело бы его островами. Копируются, а не
пропускаются, чтобы в паке не оставалось дыр.

РАСКЛАДКА:

* ``processing`` — весь расчёт по кадру (пороги, маска, размытие, композиция);
* ``pipeline`` — ``SmoothParams``, обход пачки, ввод-вывод, debug-оверлей;
* ``cli`` — только click.

DEBUG-ОВЕРЛЕЙ (``--debug-dir``) — исходный кадр с полупрозрачной заливкой масок:
жёлтая ``M_dilated`` (что не размывается), красная ``M_primary`` (найденный
контент) поверх неё.

Запуск::

    uv run python -m ocr_utils.background_smoothing \\
        --input-dir /path/to/1966/03 --output-dir /path/to/1966/03_smooth \\
        --debug-dir /path/to/1966/03_debug --log-level INFO
"""
