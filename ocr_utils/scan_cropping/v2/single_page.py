"""Сколько страниц в кадре: разворот, одна страница (обложка или крышка, лист без разреза), страница с полоской соседней у корешка, страницы нет (ярлык на закрытой крышке); правило по трапециям страниц и рамке бумаги.

Перенос правила стенда ``research/single_page`` (``reports/single_page.md``). Пороги — середины зазоров распределений
4 739 кадров пяти кэшей v2 (ПХ 1974/01 и 1975, ХиП 1991, пак-5 1990/01–03, пак-6), отсмотр по поясам 2026-10-24:

* высота рамки бумаги: ярлыки на закрытой крышке — 53–72 мм, самая низкая страница (ХиП 1991) — 195 мм;
* узкая / широкая трапеция: у одностраничных кадров 0.07–0.39, у разворотов не ниже 0.714 (поднятая рукой страница
  РИСК 1991/03 IMG_0327);
* ширина / высота рамки бумаги: у одностраничных 0.57–0.72, у разворотов не ниже 0.807 (тот же IMG_0327; обычный
  разворот — 0.97–1.41).

На 4 658 разворотах ложных срабатываний нет; из 81 неразворота верно 79 (два промаха — голубые обложки РИСК 1993,
у которых SAM 3 не нашёл бумаги; их закрыла запасная подсказка ``paper.SAM3_FALLBACK_PROMPTS``).
"""

from __future__ import annotations

from enum import StrEnum

import numpy as np

# Бумага ниже этого, мм, — не страница (ярлык на закрытой крышке 53–72 мм, страница не ниже 195 мм).
MIN_PAPER_H_MM = 130.0
# Узкая трапеция уже этой доли широкой — кусок, а не страница (одностраничные ≤ 0.39, развороты ≥ 0.714).
MAX_WIDTH_RATIO = 0.5
# Рамка бумаги уже этой доли своей высоты — в кадре лист одной страницы (одностраничные ≤ 0.72, развороты ≥ 0.807).
MAX_ASPECT = 0.78


class FrameKind(StrEnum):
    """Сколько страниц в кадре; значение — колонка ``frame_kind`` сводки и поле ``pages.json``."""

    SPREAD = "spread"  # разворот: две страницы, резать по корешку
    SINGLE = "single"  # одна страница: лист без разреза (ложный корешок по провалу печати или страница одна)
    SLIVER = "sliver"  # одна страница и полоска соседней у настоящего корешка: страница — только широкая
    NO_PAGE = "no_page"  # страницы нет: закрытая крышка подшивки, бумага — только ярлык (или не найдена вовсе)


def quad_width_px(quad: np.ndarray) -> float:
    """Ширина трапеции: средняя длина верхней и нижней сторон, px.

    Args:
        quad: Вершины (4, 2) по часовой стрелке от левого верхнего угла.

    Returns:
        Ширина, px.
    """
    q = np.asarray(quad, np.float64)
    return float((np.linalg.norm(q[1] - q[0]) + np.linalg.norm(q[2] - q[3])) / 2)


def bbox_size_mm(mask: np.ndarray, px_per_mm: float) -> tuple[float, float]:
    """Ширина и высота осевой рамки маски, мм.

    Args:
        mask: Маска bool.
        px_per_mm: Плотность масштаба маски, px/мм.

    Returns:
        ``(ширина, высота)``; пустая маска — ``(0, 0)``.
    """
    ys, xs = np.nonzero(mask)
    if not len(xs):
        return 0.0, 0.0
    return (xs.max() - xs.min() + 1) / px_per_mm, (ys.max() - ys.min() + 1) / px_per_mm


def classify_frame(quads: list[np.ndarray | None], paper: np.ndarray, n_inst: int, px_per_mm: float) -> FrameKind:
    """Сколько страниц в кадре по трапециям страниц и рамке бумаги.

    Порядок: нет трапеций или бумага ниже :data:`MIN_PAPER_H_MM` — ``NO_PAGE``; одна трапеция — ``SINGLE``; две
    (крайние), рамка бумаги уже :data:`MAX_ASPECT` своей высоты, и узкая уже :data:`MAX_WIDTH_RATIO` широкой или
    экземпляр SAM 3 один — одна страница: при одном экземпляре (две «страницы» дал запасной разрез
    ``glue.split_pages`` по провалу печати) — ``SINGLE``, при двух и больше (настоящий корешок, у края — полоска
    соседней) — ``SLIVER``; иначе ``SPREAD``. Узость бумаги нужна всегда: по одному отношению ширин ловятся и
    развороты с поднятой страницей. Один экземпляр при двух страницах на стенде (16 кадров) — всегда лист одной
    страницы или ярлык; разрез по печати бывает и косым, с отношением ширин выше порога (РИСК 1993/01 IMG_0176:
    0.69 — разрез наискось через «93»).

    Args:
        quads: Трапеции страниц слева направо (None — вырожденная).
        paper: Итоговая маска бумаги (масштаб сегментации).
        n_inst: Число экземпляров-страниц SAM 3 в карте ``inst``.
        px_per_mm: Плотность масштаба сегментации, px/мм (``page_pose.SEG_PX_PER_MM``).

    Returns:
        Вид кадра.
    """
    real = [q for q in quads if q is not None]
    paper_w, paper_h = bbox_size_mm(paper, px_per_mm)
    if not real or paper_h < MIN_PAPER_H_MM:
        return FrameKind.NO_PAGE
    if len(real) == 1:
        return FrameKind.SINGLE
    widths = (quad_width_px(real[0]), quad_width_px(real[-1]))
    ratio = min(widths) / max(max(widths), 1e-6)
    if paper_w / max(paper_h, 1e-6) < MAX_ASPECT and (ratio < MAX_WIDTH_RATIO or n_inst <= 1):
        return FrameKind.SINGLE if n_inst <= 1 else FrameKind.SLIVER
    return FrameKind.SPREAD


def wide_index(quads: list[np.ndarray | None]) -> int:
    """Индекс самой широкой страницы с трапецией (страница кадра ``SLIVER``).

    Args:
        quads: Трапеции страниц слева направо (хотя бы одна не None).

    Returns:
        Индекс в ``quads``.
    """
    widths = [-1.0 if q is None else quad_width_px(q) for q in quads]
    return int(np.argmax(widths))
