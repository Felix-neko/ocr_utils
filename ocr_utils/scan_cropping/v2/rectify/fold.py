"""Складка карты у корешка и своя сторона страницы на итоге второго преобразования: полоса повтора концов строк и чужая страница за кривой линией разреза; закрас чужого в вырезке разбора тем же способом, что докрас страниц до прямоугольника."""

from __future__ import annotations

import numpy as np

from ocr_utils.scan_cropping.v2.fill import FillMethod, fill_to_rectangle
from ocr_utils.scan_cropping.v2.rectify.coons import Layout

# Допуск обратного хода точки-источника вдоль строки, px холста: меньше — шум поля и интерполяции, не складка.
FOLD_EPS_PX = 0.5


def unfolded(xs: np.ndarray, eps: float = FOLD_EPS_PX) -> tuple[np.ndarray, np.ndarray]:
    """Пиксели без складки карты вдоль строки: точка-источник не возвращается на уже показанное.

    Поле по тексту одно на холст; у корешка поле левой страницы сдвигает её содержимое влево, поле правой — вправо, и
    между ними скачок за несколько пикселей. В полосе скачка точки-источники идут назад: столбцы итога снова берут
    концы строк левой страницы, уже показанные левее (ХиП 1991/01 IMG_0982 L: «кафедрой» → лишняя «й» за корешком,
    полоса до 50 px в 1895 строках из 3446). Настоящего источника у этой полосы нет — она пробел между разведёнными
    страницами и должна закрашиваться.

    Левая страница читается слева направо: пиксель годен, если его источник не левее самого правого источника
    пикселей левее него (с допуском ``eps``). Правая — справа налево: источник не правее самого левого источника
    пикселей правее него. Так полоса повтора выпадает из обеих страниц, а не переходит к соседней.

    Args:
        xs: Абсциссы точек-источников на холсте Кунса ``X + D_x(X)``, (H, W) float32.
        eps: Допуск обратного хода, px холста Кунса.

    Returns:
        ``(для левой страницы, для правой)`` — маски bool размера ``xs``.
    """
    forward = xs >= np.maximum.accumulate(xs, axis=1) - eps
    backward = xs <= np.minimum.accumulate(xs[:, ::-1], axis=1)[:, ::-1] + eps
    return forward, backward


def own_sides(layout: Layout, dense: tuple[np.ndarray, np.ndarray]) -> tuple[np.ndarray, np.ndarray] | None:
    """Своя сторона каждой страницы разворота на итоге: точка-источник по свою сторону корешка и вне складки карты.

    В отличие от областей страниц (``pages.page_areas``) прямоугольник страницы расклада не ограничивает: поля вокруг
    страницы (выступы текста, рисунки за краем рамки) остаются своими. Чужое — только то, что пришло с другой
    стороны корешка (концы строк соседней страницы за кривой линией разреза), и полоса повтора у корешка.

    Args:
        layout: Расклад холста Кунса.
        dense: Поле ``(D_x, D_y)`` размера холста итога (при растяжении у корешка он шире ``layout``) в координаты
            холста Кунса.

    Returns:
        Маски bool левой и правой страницы размера холста итога или None — у кадра одна страница (чужого нет).
    """
    if layout.single:
        return None
    xs = np.arange(dense[0].shape[1], dtype=np.float32)[None, :] + dense[0]
    forward, backward = unfolded(xs)
    return (xs < layout.spine_x) & forward, (xs >= layout.spine_x) & backward


def own_view(
    image: np.ndarray, own: np.ndarray, box: tuple[int, int, int, int], method: FillMethod, px_per_mm: float,
    seam_mm: float,
) -> np.ndarray:  # fmt: skip
    """Итог, где в вырезке разбора страницы чужое закрашено способом докраса страниц до прямоугольника.

    Разбор итога режет страницу по прямой линии корешка (``text_field.crop_box``), а после поля содержимое левой
    страницы заходит за неё: повторённые концы строк и чужие буквы пришивались к строкам правой страницы, и оси
    начинались на 1–1.7 мм левее текста (ХиП 1991/01 IMG_0982 R, 7 осей из 45 в верхних 40 мм).

    Args:
        image: Итог BGR (холст текущего прохода).
        own: Своя сторона страницы (:func:`own_sides`), bool размера ``image``.
        box: Вырезка разбора ``(x0, y0, x1, y1)``.
        method: Способ закраса (``--fill``, как у ``pages.cut_pages``).
        px_per_mm: Плотность итога, px/мм.
        seam_mm: Ширина мягкого шва для ``pull_push_seam``, мм.

    Returns:
        ``image`` без изменений, если в вырезке нет чужого, иначе копия с закрашенной вырезкой.
    """
    x0, y0, x1, y1 = box
    if own[y0:y1, x0:x1].all():
        return image
    filled = fill_to_rectangle(image, own, method, box=box, px_per_mm=px_per_mm, seam_mm=seam_mm)
    if filled is None:
        return image
    out = image.copy()
    out[y0:y1, x0:x1] = filled
    return out
