#!/usr/bin/env bash
#
# Общие параметры боевого внешнего OCR по паку-1 (ocr_utils.external_ocr_services). Сам ничего
# не запускает — подключается через `source` из соседних run_*.sh.
#
# Ключ OpenRouter берётся из $OPENROUTER_API_KEY; в скриптах и логах он не появляется.

# Пути пака (SHARPENED_DIR, DB_REVIEWED и прочие) — из общего файла разметки.
source "$(dirname "${BASH_SOURCE[0]}")/../scan_markup/pack1/common.sh"

# Выходы — на SSD, рядом с остальными результатами по паку-1 и отдельно от стенда
# research/external_ocr_models (pack1_external_ocr): у боевого прогона своя схема ответа и своя
# нумерация промптов, смешивать их с пробниками нельзя. Две папки: полосы (рабочий выход — та же
# раскладка {год}/{выпуск}/полоса.{md,json,meta.json}, что у входа, плюс toc.json/toc.md и sidecar
# {год}_{выпуск}.pages.json на выпуск, summary.csv, run.log, списки) и выпуски — только конечные md
# {год}/{год}_{выпуск}.md, больше там ничего нет.
EXTERNAL_OCR_SERVICES_ROOT="/mnt/system/raw/mts/pack1_external_ocr_services"
EXTERNAL_OCR_SERVICES_PAGES="$EXTERNAL_OCR_SERVICES_ROOT/pages"
EXTERNAL_OCR_SERVICES_OUT="$EXTERNAL_OCR_SERVICES_ROOT/out"
# Сырые ответы модели, промпты и отправленные тайлы — по полосе; полезно при разборе сбоев
# и при проверке сетки тайлов. Весит примерно как вход в JPEG 2200 px (~0.6 МБ на полосу).
EXTERNAL_OCR_SERVICES_DEBUG="$EXTERNAL_OCR_SERVICES_ROOT/debug"
# Кэш запросов к модели (README, «Кэш запросов»): на каждый запрос — папка с промптами и ответом,
# по всем проходам полосы (этап toc, понижение, круг повтора, откаты режима JSON). Повтор прогона
# с тем же промптом и теми же тайлами берёт ответы отсюда и в сеть не ходит. Без тайлов — около
# 30 КБ на запрос, по паку ≈ 0.5 ГиБ. Не удалять между прогонами: это и есть «продолжить с места».
EXTERNAL_OCR_SERVICES_CACHE="$EXTERNAL_OCR_SERVICES_ROOT/cache"

# Описание издания для промпта. Без года намеренно: описание стоит в первом абзаце системного
# промпта, и любое различие между выпусками ломает общий кэшируемый префикс у провайдера.
# Подстановка «{year}» в коде осталась, но здесь не используется.
EXTERNAL_OCR_SOURCE="журнал «Материально-техническое снабжение», Москва, 1966–1976"

# Параллельных запросов. Это сеть, а не CPU. Было 4 из-за лимитов провайдера (429 у Fireworks
# ловился уже на одиночных запросах в стенде); DeepSeek на 4 потоках 429 не давал ни разу
# (1966/03, 1968/12, 1976/12, 1974/01–02, ≈ 500 полос), с 20.09.2026 — 12. Если 429 пойдут, клиент
# повторяет с паузой (--attempts 5), полосы не теряются, прогон только замедлится — тогда сбавить.
JOBS=12
