#!/usr/bin/env bash
#
# Поиск страниц с крупным line art в бинаризованных PDF пака-1 и выгрузка их картинками.
#
# ЗАЧЕМ. FineReader с включённым «исправлением искажений строк» иногда корёжит line art
# (эталон дефекта — стр. 80 файла /mnt/system/raw/full_1967_01_bg_off_ori_off.pdf: схема
# организации диспетчерской службы вышла с чёрными гребёнками вместо рамок). Такие
# страницы при сборке финального PDF надо брать из бинаризации БЕЗ распрямления строк.
# Чтобы найти их глазами, не листая девять тысяч полос, прогоняем детектор и смотрим
# только то, что он отобрал.
#
# ПОЧЕМУ ДВА ШАГА. Признаки считаются один раз в CSV, а порог применяется отдельной
# командой. Порог подбирается глазами и не с первого раза, поэтому ниже сразу три
# выгрузки — 2%, 5% и 15% площади полосы — в три разные папки. Тяжёлый проход при этом
# делается ровно один.
#
# РАЗМЕРЫ. Шаг текстовых строк 89 px и толщина штриха 7 px при 600 dpi — замер пака-1
# (см. ocr_utils/paper.py). Они зашиты умолчаниями в ocr_utils/page_layout/line_art/features.py;
# для ДРУГОГО пака их надо перемерить (ocr_utils/defocus_detection/scale.py:
# text_line_pitch и stroke_width) и передать ключами --pitch-px / --stroke-px.
#
# ВРЕМЯ. Замерено: 0.25 с на страницу в один поток при полных 600 dpi, то есть порядка
# двух с половиной минут на весь пак при --jobs 16. Прогон всё равно стоит пускать фоном
# и ждать ПО СОХРАНЁННОМУ PID, а не по шаблону командной строки:
#
#     bash run_scripts/line_art_detection/run_line_art_pack1.sh & PID=$!
#     while kill -0 "$PID" 2>/dev/null; do sleep 10; done
#
# РАЗМЕТКА. --db отсеивает полутоновые фотографии по выверенной вручную разметке CVAT:
# распрямление строк их заметно не портит, и в список они не нужны. Отделить фотографию
# от штриха ПИКСЕЛЯМИ на этом материале не вышло — почему именно, замерено и записано
# в докстринге ocr_utils/page_layout/line_art/features.py.
#
# SURYA. Ключ --use-surya-layout добавляет таблицы без линеек и многострочные формулы,
# которых связная статистика не видит по построению. Он выключен: стоит около двух часов
# GPU против двух с половиной минут CPU. Включать при необходимости вместе с
# --surya-cache, чтобы повторный прогон не трогал GPU.
#
# ФОРМУЛЫ ПОРОГОМ НЕ ДОСТАТЬ. Замер по эталонному выпуску: многострочная формула занимает
# 0.4-1.3% полосы (стр. 23, 25, 85, 87), то есть порог, настроенный на рисунки, отсекает
# её всегда. Поэтому формулы выбираются не порогом, а ИСТОЧНИКОМ находки, и только после
# прогона с --use-surya-layout:
#
#     uv run python -m ocr_utils.line_art_detection export \
#         --csv line_art_pack1.csv --out-dir line_art_pack1_formulas \
#         --min-coverage 0.003 --source surya:Equation
#
# ПАПКА МОЖЕТ БЫТЬ НЕДОПИСАНА. Бинаризованные PDF выгружает FineReader в виртуалке, и
# выгрузка идёт часами. Прогон 8 сентября пришёлся ровно на неё: число PDF под руками
# менялось 93 -> 89 -> 90, а число страниц в отчёте 9170 -> 8774, и отличить это от
# правки порогов по самому отчёту невозможно. Поэтому --min-age-minutes 10 (умолчание):
# файл, которого касались меньше десяти минут назад, пропускается, и о каждом таком
# сказано в stderr. Перед ОКОНЧАТЕЛЬНЫМ прогоном убедиться, что выгрузка закончилась:
#
#     find "$INPUT_DIR" -name '*.pdf' -mmin -30 | wc -l    # должно быть 0
#
set -euo pipefail

cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/system/raw/mts/pack1_pdf/full_pdfs_binary_brightened_bg"
DB="$HOME/Projects/mts_markup/pack1_reviewed.sqlite"
BASE_NAME="line_art_pack1"
CSV="${BASE_NAME}.csv"

echo "line_art_detection (пак-1):"
echo "  input = $INPUT_DIR"
echo "  csv   = $CSV"

uv run python -m ocr_utils.line_art_detection scan \
    --input-dir "$INPUT_DIR" \
    --db "$DB" \
    --pack-name "пак-1" \
    --csv "$CSV" \
    --md-report "reports/${BASE_NAME}.md" \
    --threshold 0.05 \
    --jobs 16

# Три порога в три папки: смотреть начинать с 15% (там самое крупное), а 2% держать
# рядом, чтобы проверить, не потерялось ли что-то между порогами.
for THRESHOLD in 0.02 0.05 0.15; do
    SUFFIX="${THRESHOLD#0.}"
    uv run python -m ocr_utils.line_art_detection export \
        --csv "$CSV" \
        --out-dir "${BASE_NAME}_${SUFFIX}" \
        --min-coverage "$THRESHOLD" \
        --long-side 1600 \
        --jobs 16
done
