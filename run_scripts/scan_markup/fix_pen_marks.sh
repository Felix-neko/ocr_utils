#!/usr/bin/env bash
#
# Починка исходников с пометками шариковой ручкой: оставляем один цветовой канал.
#
# Одним каналом обе стороны задачи не взять. Замер по 1968/01 IMG_0045_2R после приведения
# «бумага 245, печатный текст 30»:
#
#     только синий                клякса 151, текст под кляксой  79  — клякса ещё видна
#     только красный              клякса   0                         — клякса чернее текста
#     B - 0.47R (точное гашение)  клякса 243, текст под кляксой 148  — текст под ней выцвел
#     0.9B + 0.8G - R             клякса 217, текст под кляксой 118  — так и берём
#
# Последняя комбинация найдена перебором по сетке весов при двух ограничениях: клякса не
# темнее 215 и шум бумаги не выше 9 уровней. Ограничение по шуму существенно — комбинации
# вида G - 0.8R делят классы по средним лучше, но вычитают два похожих канала, и бумага
# после них идёт пятнами.
#
# Комбинация подмешивается ТОЛЬКО внутри маски кляксы с растушёванным краем: на всю полосу
# она поднимала бы шум ради пятна в сантиметр. На 1968/01 IMG_0045_2R затронуто 0.42%
# площади полосы.
#
# Результат кладётся в ОТДЕЛЬНУЮ папку рядом с паком, а не внутрь него: лишний файл рядом
# с оригиналом стал бы лишней полосой в выпуске и сдвинул бы порядок остальных.
# Подкладывать в пак — руками, поверх оригинала.
#
# Это правка ИСХОДНИКА, а не детекции: пометка не растровая иллюстрация, и в бинаризованный
# PDF она попадёт ровно так же, независимо от разметки.

set -euo pipefail
source "$(dirname "$0")/pack1/common.sh"

FIXED_DIR="$(dirname "$PACK_DIR")/пак-1-починенные"
echo "Починенные: $FIXED_DIR"

PAGES=(
    --page 1968/01/IMG_0045_2R.tif
)

uv run python -m ocr_utils.scan_markup fix-pen-marks \
    --pack-dir "$PACK_DIR" \
    --out-dir "$FIXED_DIR" \
    --weights 0.9,0.8,-1.0 \
    "${PAGES[@]}"
