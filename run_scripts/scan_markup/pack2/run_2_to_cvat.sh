#!/usr/bin/env bash
#
# Шаг 2: уменьшенные копии полос в share + проект, задача 1977 и джобы-выпуски CVAT
# с предразметкой.
#
# Требует поднятого CVAT (docker/up.sh) и того, чтобы SHARE_ROOT лежал внутри IMAGES_DIR
# из docker/.env: задачи заводятся из смонтированного share, по сети файлы не передаются.
#
# Проект в CVAT заводится по имени пака — «пак-2», отдельно от пака-1; превью ложатся в
# $SHARE_ROOT/пак-2/1977/{выпуск}/. Задача одна (год), джобов шесть (выпуски).
#
# Оригиналы читает второй и последний раз — ради уменьшенных копий (597 полос, минуты).
# Идемпотентен: готовые копии пропускаются, существующие задачи не пересоздаются.
#
# ПРОЕКТ ЗАВОДИТСЯ ЗАНОВО (2026-10-18): старый удалён run_2a_delete_cvat_project.sh, поэтому
# задача 1977 создаётся с нуля и получает первичную предразметку. Метки в проекте — ВСЕ (LABELS
# из scan_markup.cvat.project: растр, печати, рукописное, цветной текст, таблицы, line art,
# повёрнутый текст, теги). Предразметка прямоугольниками — только растр (цветной и серый —
# разные метки), таблицы и line art, включая блок-схемы; плюс теги поворота и оглавления.
# «Цветной текст или штрих» детектора не имеет и ставится разметчиком вручную; повёрнутый текст
# и подозрения на печать в базе есть, но в предразметку не идут — решение пользователя.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Share:    $SHARE_ROOT"

TO_CVAT_ARGS=(
    --db "$DB"
    --pack-name "$PACK_NAME"
    --share-root "$SHARE_ROOT"
    # Уменьшение упирается в CPU, а не в диск: на полосу 25 МиБ чтение с NTFS-3G 0.06 с,
    # декодирование LZW-TIFF 0.38 с, LANCZOS 1/8 — 0.13 с (замер 2026-09-21, пак-2 06/0300_2R).
    # В один процесс это 1.7 полосы/с; «--jobs 1» когда-то попал сюда отладочным остатком.
    --jobs 16
    # Разрешение уменьшенных копий: делитель полосы = round(её dpi / этого), 600 dpi -> 8.
    # Полосам, уже залитым в CVAT, делитель не меняется — их разметка в прежнем масштабе.
    # --cvat-dpi 75
    # Картинки уже готовы прошлым прогоном.
    # --skip-images
    # ОСТОРОЖНО: заливка заменяет разметку задачи целиком, то есть затирает ручную правку.
    # --force-annotations
    # Пересоздать задачу-год, если изменились исходники. Ручная разметка неизменившихся
    # полос переносится в новую задачу, изменившиеся получают свежую предразметку.
    # CVAT не умеет удалять отдельные джобы, поэтому пересоздаётся вся задача-год.
    # Перед этим стоит прогнать шаг 3: снимок разметки в базу — лучшая страховка.
    # --recreate-stale
    # Назначить джобы разметчику. БЕЗ ЭТОГО он не увидит ничего: роль worker показывает
    # только назначенное лично, и списки проектов и задач у неё пустые.
    --annotator user
    # Виды прямоугольников первичной предразметки (см. шапку). Метки проекта это не сужает.
    --kinds color,grayscale,table,line_art_schema
    # Когда в задаче уже появится ручная правка, новые находки детекторов — только дозаливкой
    # (PATCH, ручная разметка и теги целы):
    # --append-kinds table,line_art_schema
    # --append-tags
)
uv run python -m ocr_utils.scan_markup to-cvat "${TO_CVAT_ARGS[@]}" "$@"
