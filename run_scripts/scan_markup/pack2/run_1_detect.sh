#!/usr/bin/env bash
#
# Шаг 1: предварительная детекция растровых областей и обложек по оригиналам -> SQLite.
#
# Читает пак целиком — 597 полос, около 15 ГБ с медленного NTFS-3G. Идемпотентен: с включённым
# --skip-detected прерванный прогон продолжается с того же места.
#
# ПЕРВИЧНЫЙ ДЕТЕКТОР — SURYA, то есть нужен GPU. Она предлагает блоки Picture, а пиксельные
# проверки уточняют границу, отличают растр от штриха и решают про цвет. Без неё детектор
# точек даёт ложный прямоугольник на каждой полосе содержания: строка отточий — это ряд
# мелких круглых пятен одинакового размера, ровно та статистика, по которой опознаётся
# растровая сетка.
#
# Пулу это не мешает. Работа разбита на два этапа: воркеры читают файл и считают всё
# пиксельное, родитель зовёт GPU и собирает области. Сериализуется только инференс, а чтение
# с медленного диска и счёт по полному кадру идут в шестнадцать процессов.
#
# В ОТЛИЧИЕ ОТ ПАКА-1 ГОТОВОГО КЭША SURYA НЕТ: разметка считается на каждую полосу (~1 с GPU)
# и пишется в LAYOUT_CACHE_DIR; ориентир — 10-15 минут на пак вместе с загрузкой модели.
# Повторный прогон берёт разметку из кэша.
#
# ПОРОГИ — УМОЛЧАНИЯ ПАКА-1. Тот же журнал, тот же масштаб набора (файлы апскейлены до 600 dpi,
# шаг строк и штрих совпадают с паком-1 — см. common.sh), поэтому ничего не перекручено. Если
# оверлеи покажут системный дефект, крутить пороги по выборке, а не по полному прогону.
#
# ТАБЛИЦЫ И БЛОК-СХЕМЫ (page_layout.tables) считаются тем же прогоном по копии 1/4.
# Разметка surya у них общая с растром и берётся из того же кэша. Версия детектора таблиц своя:
# с --skip-detected по паку с уже посчитанным растром пересчитываются ОДНИ таблицы.
#
# ПРОБА ПЕРЕД ПОЛНЫМ ПРОГОНОМ — один выпуск: `run_1_detect.sh --only-issue 01` (~100 полос).
# --only-year здесь бессмыслен: год в паке один.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Оверлеи:  $DEBUG_DIR"

DETECT_ARGS=(
    --pack-dir "$PACK_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"
    # Оверлеи с подписями kind/разброс/доля точек: по ним и разбирается, что пошло не так.
    --debug-dir "$DEBUG_DIR"
    # Продолжение прерванного прогона и обновление пака: перечитываются только полосы,
    # у которых разошлись размер и время правки ИЛИ версия детектора, а из них
    # пересчитываются те, у которых разошёлся и хеш содержимого.
    --skip-detected
    --jobs 16
    # Кэш разметки surya: есть файл — модель не зовётся; нет или битый — разбирается и пишется.
    --layout-cache "$LAYOUT_CACHE_DIR"
    # Что искать. Выключать растр имеет смысл, только когда нужны одни таблицы и растр
    # уже свежий, — --skip-detected сделает то же сам, не трогая свежее.
    # --no-raster
    # --no-tables
    # Line art — единый детектор page_layout (схемы детектора таблиц + surya + связные пятна,
    # только ВНЕ растра и таблиц), тот же, что решает судьбу страницы при сборке финальных PDF;
    # повёрнутый текст вне таблиц — Docstrum по глифам. У каждого своя версия: с --skip-detected
    # пересчитывается только устаревшее.
    # --no-line-art
    # --no-rotated-text
    # Ориентация полосы считается ЭТИМ ЖЕ прогоном с уже разжатого кадра. Версия ориентации
    # своя, независимая от версии детектора растра.
    --angles 0,90,270
    # Записывается в пак и дальше берётся оттуда. 180 не входит: на паке-1 все боковые полосы
    # требовали поворота ПО ЧАСОВОЙ, вверх ногами не оказалось ни одной — широкие рисунки в
    # советских изданиях ставили одинаково. Ответ, которого в наборе нет, не может быть дан.
    --orientation-detectors ink_axis,osd,surya_lines,ocr_vote
    # ocr_vote — арбитр: он читает полосу на каждом допустимом повороте и потому дорог
    # (секунды против долей секунды), поэтому идёт вторым проходом только по кандидатам.
    # Первая полоса выпуска — обложка: одна цветная область во весь кадр, пиксели не
    # декодируются вовсе. Проверено глазами на 1977/01 и 1977/04 (синяя обложка с
    # библиотечной печатью, как у пака-1). Остальные обложки идут обычной детекцией.
    --first-page-is-cover
    # Не верить stat вообще: пересчитать хеш каждой полосы. Это перечитывание всего пака.
    # --rehash-all
    # Один выпуск — для пробы перед полным прогоном.
    # --only-issue 01
    # Пороги детекции. Замеры, по которым они выбраны, — в detection/dots.py и
    # detection/color_kind.py.
    # --chroma-spread-thr 8.0
    # --dot-frac-thr 0.88
    # --cell-px 128
    # Порог «блок Surya — это штрих, а не растр» и порог страховки от её пропусков.
    # --surya-lineart-p99 4600
    # --safety-min-frac 0.03
    # Прогон без GPU: работают одни пиксели. Дешевле, но на полосах содержания появляются
    # ложные срабатывания, а тёмные фотографии со слипшимися точками теряются.
    # --no-use-surya-layout
)
# Аргументы скрипта дописываются в конец: click берёт последнее вхождение опции,
# поэтому любую из перечисленных выше можно переопределить на месте, не правя файл.
uv run python -m ocr_utils.scan_markup detect "${DETECT_ARGS[@]}" "$@"

# ОГЛАВЛЕНИЯ (scan_markup.toc) — отдельной командой ПОСЛЕ detect: дерево выпусков она берёт
# из базы, а меряет только окно (первые 5 и последние 12 полос выпуска) — метка surya из
# того же кэша плюс tesseract. Заострённых копий у пака-2 нет, читаются оригиналы. Версия
# детектора своя: --skip-detected пропускает выпуски, посчитанные текущей версией. Нужно
# шагу 2: из is_toc / is_year_index ставятся теги «Оглавление» / «Годовой указатель».
# Пороги — пака-1 (тот же журнал); выпуск без «Содержания» в выводе — красный флаг.
# Аргументы "$@" сюда не передаются: они адресованы detect (у toc другой набор опций).
TOC_ARGS=(
    --pack-dir "$PACK_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"
    --layout-cache "$LAYOUT_CACHE_DIR"
    --jobs 16
    --skip-detected
)
uv run python -m ocr_utils.scan_markup toc "${TOC_ARGS[@]}"
