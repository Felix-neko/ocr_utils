#!/usr/bin/env bash
#
# Шаг 7: боевой прогон очистки пака — закрас разметки и размытие фона за один проход.
#
# Вход — DB_REVIEWED, то есть разметка, уже выправленная руками в CVAT (шаги 2-3). До шага 3
# запускать не на чем.
#
# ИМЕНА ВЫХОДНЫХ ФАЙЛОВ СОДЕРЖАТ ОТПЕЧАТОК ИСХОДНИКА: 0034_1L.a1b2c3d4.tif, где a1b2c3d4 —
# начало sha256 исходного файла из базы (pages.file_hash). Имена полос повторяются из выпуска
# в выпуск, и любой инструмент, берущий их плоским списком, способен одноимённые перепутать
# (на паке-1 Capture One так подменил полосу). Отпечаток в имени делает подмену видимой, не
# открывая картинку. Подробности — в ocr_utils/scan_cleanup/naming.py.
#
# Куда легла каждая полоса, прогон записывает в базу (pages.cleaned_rel_path), иначе
# следующий шаг конвейера файл просто не найдёт. Отключается ключом --no-write-db.
#
# ВСЕ ПОЛОСЫ СОХРАНЯЮТСЯ ЦВЕТНЫМИ (--always-color, 2026-10-18): Capture One серые TIFF не
# видит. Без флага полосы без цветной разметки (color, color_text) писались одним серым каналом.
#
# МЕСТО: ~20 ГиБ на пак (~35 МиБ на полосу в цвете против ~8–11 МиБ в сером; 597 полос) плюс оверлеи.
#
# РАЗМЕРЫ НЕ ПЕРЕСЧИТАНЫ ОТНОСИТЕЛЬНО ПАКА-1, И ЭТО ПРОВЕРЕНО. «(300 dpi)» в имени папки —
# про исходный скан; полосы апскейлены до 600 dpi. Замер набора по четырём полосам пака-2
# (1977/01 0070_1L, 03 0320_2R, 05 0320_2R, 06 0440_1L; ocr_utils.defocus_detection.scale):
#   шаг строк      87-97 px   (пак-1: 89 px)
#   толщина штриха  6-8 px    (пак-1: 7 px)
# Все окна, радиусы и площади ниже — ровно те, что выбраны для пака-1 шагами 5-6 и
# проверены на его полном прогоне. ВСЕ РАЗМЕРЫ ЗАДАНЫ ЯВНО, В ММ БУМАГИ (в пиксели — по dpi
# полосы из базы; рядом — прежние пиксели при 600 dpi): выводить их из размера кадра нельзя,
# в «Готовое» попадают и неполные страницы.
#
# ПЕРЕД ПОЛНЫМ ПРОГОНОМ прогнать на одном выпуске (`run_7_cleanup.sh --only-issue 01`, ~100
# полос, пара минут) и посмотреть оверлеи: структуру подпапок, формат и DPI, обложки (они
# должны быть скопированы без размытия, но с закрашенными печатями) и то, что защитная маска
# накрывает бледные перемычки букв. Апскейл мог сделать край штриха мягче, чем у пака-1, —
# именно это и смотреть. При --skip-if-exists полный прогон пробный выпуск пропустит; если
# нужен пересчёт всего — --no-skip-if-exists (стоит по умолчанию ниже).
#
# Раскладка по процессам. Полосы с закрасом идут последовательно в родительском процессе,
# где живёт единственный GpuModels (видеопамять одна на всех). Остальные — в пуле. JOBS=6,
# а не 16: пул читает с NTFS-3G и пишет на другой том, то есть упирается в диск, а не в счёт;
# и каждый воркер держит полный кадр 600 dpi с картами размытия. 2026-10-18 при 8 воркерах и
# работающей VMware (30 ГБ) systemd-oomd по давлению на память убил группу PyCharm вместе с
# сессией и прогоном (пик группы 44,9 ГБ).
#
# ЗАПУСК ИЗ IDE ИЛИ СЕССИИ АГЕНТА — В СВОЁМ ЮНИТЕ: setsid меняет сессию, но не cgroup, и oomd
# убивает всю группу терминала. Своя группа — тогда при давлении погибнет только прогон:
#   systemd-run --user --scope --unit=pack2-cleanup --collect run_scripts/scan_markup/pack2/run_7_cleanup.sh
# Продолжение прерванного прогона — с --skip-if-exists (запись атомарная, готовые файлы целы).
#
# Умолчания остальных параметров выбраны шагами 5 и 6 пака-1; менять их здесь, а не в коде.

set -euo pipefail
# Пул процессов: при остановке скрипта гасить всю группу, иначе forkserver и воркеры остаются сиротами.
set -m
trap 'kill -- -$$ 2>/dev/null' EXIT INT TERM
source "$(dirname "$0")/common.sh"
JOBS="${JOBS:-6}"
echo "Выход:    $BLURRED_DIR"
echo "Оверлеи:  $CLEAN_DEBUG_DIR"
# Место на томе выхода (SSD /mnt/hotstore): ~5 ГиБ на пак плюс оверлеи.
mkdir -p "$CLEAN_ROOT"
df -h "$CLEAN_ROOT" | tail -1

CLEANUP_ARGS=(
    --db "$DB_REVIEWED"
    --pack-dir "$PACK_DIR"
    --pack-name "$PACK_NAME"
    --out-dir "$BLURRED_DIR"
    --debug-dir "$CLEAN_DEBUG_DIR"
    --report-csv "$CLEAN_ROOT/report.csv"

    # Проба одним выпуском — вернуть строку, если параметры менялись и нужен быстрый круг.
    # Для полного пака она должна оставаться закомментированной.
    # --only-issue 01

    # --- Закрас -------------------------------------------------------------
    # LaMa, не SD. По сравнению на 30 полосах пака-1 (шаг 5) SD выдумывала на месте
    # удалённого объекта псевдотекст и цветные фигуры. LaMa кладёт чистую бумагу.
    --backend lama
    # Нижняя граница припуска ПРИ ГРУППИРОВКЕ (правило «1/3 своего размера» у мелких
    # областей вырождается). В сеть маска идёт БЕЗ припуска: закрашивается ровно то,
    # что обвёл человек, — он и так обводит с запасом.
    --group-min-dilate-mm 0.677  # 16 px при 600 dpi
    # Группировка связных областей ПО ВСЕЙ ПОЛОСЕ, без деления по видам: раздуть на 1/3
    # своего размера, пересеклись — закрасить одной операцией. Соседние печать и
    # рукописная пометка идут вместе, и штрихи одной не затекают в дыру другой.
    --group-dilate-frac 0.3333
    --roi-scale 2.0
    # Ограничивается ДЫРА, а не сторона ROI. LaMa обучена на мелких кропах, и дыра шире
    # пары сотен пикселей ей уже не по зубам: сеть перестаёт видеть противоположный берег
    # и заливает кашей. Замер на печати 632x464 (пак-1, 1976/02 IMG_0054_2R): при пределе
    # дыры 300 px отклонение заливки от бумаги -2.6 против -14.5 при пределе ROI 1024.
    --lama-hole-max-px 300

    # --- Размеры, выведенные из набора (замер выше) -------------------------
    # Окно Саволы: порядка шага строк, чтобы в него попадали и строка, и межстрочье.
    --sauvola-window-mm 4.276  # 101 px при 600 dpi
    # Оценка уровня бумаги: раздутие в пару штрихов (буквы должны уйти из оценки
    # целиком), размытие крупнее буквы, но мельче неровности света.
    --paper-dilate-mm 0.635  # 15 px при 600 dpi
    --paper-blur-mm 6.35  # 150 px при 600 dpi
    # Площадь, с которой связная область подтверждается сама по себе: p99 реального
    # шума (области маски, целиком лежащие на пустом поле, имеют площадь до 34 px,
    # медиана 8), при этом точка в тексте — 40-80 px — порог проходит.
    --min-glyph-area-mm2 0.0609  # 34 px² при 600 dpi
    # Площадь, с которой область подтверждается САМА ПО СЕБЕ, без оглядки на отражение.
    # Без неё правило вырождается в «крупная И тёмная», и бледная линейка таблицы
    # удалялась целиком. Крапины просвета столько не набирают.
    --sure-glyph-area-mm2 0.896  # 500 px² при 600 dpi

    # --- Размытие фона ------------------------------------------------------
    # Sauvola по построению может только добрать контент: её локальная маска
    # ОБЪЕДИНЯЕТСЯ с глобальным порогом. При усиленном размытии это дешёвая страховка.
    --method sauvola
    --sauvola-k 0.10
    --threshold-bias 0.5
    # 25 px — диаметр 50 px, то есть ядро размером с целую букву (кегль ~52 px при 600 dpi).
    --dilate-mm 1.058  # 25 px при 600 dpi
    # Радиус размытия задаётся отдельно от припуска.
    --blur-mm 4.233  # 100 px при 600 dpi
    --blur-mode masked

    # Доля уровня бумаги, темнее которой область считается настоящей краской. Отражение,
    # а не яркость: на пересвеченной полосе краска светлее, чем крапины просвета на
    # тёмной, а по отражению они расходятся (0.53 против 0.83 на паке-1).
    # off — не учитывать, auto — порог Оцу по самой полосе (садится около 0.6).
    --ink-level 0.65
    # Не подтверждать область только за то, что она прошла глобальный порог: просвет
    # с оборота проходит его тоже.
    --no-trust-strong
    # Предохранитель «на полосе есть растр, трогать нельзя» — выключен. Растровые
    # области здесь размечены руками, полосные отсекаются по базе, а на паке-1 он
    # срабатывал только ложно (тёмная кромка у края скана, пятно поля), и цена ошибки
    # высокая и незаметная: полоса целиком уходит в копию.
    --no-halftone-guard

    # Прямоугольники «подозрение на печать» разметчик не подтверждает — не защищаем.
    --no-protect-stamp-suspect

    # Все полосы трёхканальными — для Capture One (см. шапку).
    --always-color

    --no-skip-if-exists
    --jobs "$JOBS"
    --log-level INFO
)
# Аргументы скрипта дописываются в конец: click берёт последнее вхождение опции,
# поэтому любую из перечисленных выше можно переопределить на месте, не правя файл.
uv run python -m ocr_utils.scan_cleanup run "${CLEANUP_ARGS[@]}" "$@"
