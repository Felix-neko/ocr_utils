#!/usr/bin/env bash
#
# Шаг 2a (разовый): удалить проект «пак-2» в CVAT и отвязать от него базу, чтобы шаг 2 завёл
# проект заново с нуля.
#
# Зачем: проект id=6 заведён 2026-09-21 с предразметкой старых детекторов (таблицы v1, line art v2,
# повёрнутый текст v1). Ручной правки в нём нет — все 6 джобов в состоянии new и не менялись с
# создания (проверено 2026-10-18), поэтому дозаливка (--append-kinds) смысла не имеет, а
# пересоздание ничего не теряет.
#
# Что делает (ocr_utils.scan_markup.cvat.delete):
#   1. опись проекта: задачи, джобы, тронутые разметчиком джобы, шейпы и теги по меткам;
#   2. с --yes — JSON-бэкап разметки каждой задачи в $PACK_WORK/cvat_backup/;
#   3. удаляет проект на сервере (задачи, джобы и разметку вместе с ним) — НЕОБРАТИМО;
#   4. обнуляет в базе id проекта, задач, джобов, номера кадров и отпечатки залитых файлов.
#      Уменьшенные копии в share и делители полос остаются — шаг 2 возьмёт их как есть.
#
# Без --yes — сухой прогон: только опись. Порядок: `./run_2a_delete_cvat_project.sh`, глазами
# убедиться, что «тронутых разметчиком» 0, затем `./run_2a_delete_cvat_project.sh --yes`.
# Секунды, CVAT должен быть поднят (docker/up.sh).

set -euo pipefail
source "$(dirname "$0")/common.sh"

DELETE_ARGS=(
    --db "$DB"
    --pack-name "$PACK_NAME"
)
uv run python -m ocr_utils.scan_markup delete-project "${DELETE_ARGS[@]}" "$@"
