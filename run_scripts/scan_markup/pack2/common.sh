#!/usr/bin/env bash
#
# Общие параметры разметки пака-2 (журнал «Материально-техническое снабжение», 1977, выпуски 01-06).
#
# Пак: один годовой комплект, 6 выпусков, 597 полос, TIFF RGB по 19-35 МБ. Оригиналы лежат на
# /mnt/dump3 (NTFS-3G на шпинделе), полное чтение — около 15 ГБ, то есть минуты, а не часы,
# как у пака-1.
#
# «(300 dpi)» В ИМЕНИ ПАПКИ — ПРО ИСХОДНЫЙ СКАН, А НЕ ПРО ФАЙЛЫ. Полосы апскейлены до 600 dpi
# (тег TIFF 600 dpi, кадры ~3350x5850 px). Замер набора (ocr_utils.defocus_detection.scale по
# четырём полосам 1977/01, 03, 05, 06): шаг строк 87-97 px, штрих 6-8 px — то же, что у пака-1
# (89 / 7 px при 600 dpi). Поэтому ВСЕ пиксельные размеры в run-скриптах взяты у пака-1 без
# пересчёта; делитель превью CVAT — тот же, 8.
#
# Имена полос — NNNN_1L.tif / NNNN_2R.tif без префикса IMG_; коду это безразлично, дерево
# обходится как у пака-1: {год}/{выпуск}/{полоса}, файлы .ScanTailor пропускаются по расширению.
#
# Сам ничего не запускает: подключается через `source` из соседних run_*.sh. Пути собраны
# здесь потому, что база связывает шаги между собой — разъехавшееся имя в одном из них
# заведёт ещё один пак вместо продолжения этого, и заметить это можно очень нескоро.

PACK_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/МТС/Готовое/пак-2 v.1 (1977-01 - 1977-06) (300 dpi)"
# Имя пака в базе, проекта в CVAT и подпапки в share. ЗАДАВАТЬ ЯВНО во всех командах: без
# --pack-name оно берётся из имени папки и станет «пак-2 v.1 (1977-01 - 1977-06) (300 dpi)».
PACK_NAME="пак-2"

# Рабочие файлы разметки — на SSD рядом с проектом, а не на /mnt/dump3. Оригиналы читаются
# по разу, а вот уменьшенные копии CVAT листает постранично, и на шпиндельном NTFS-3G это
# ощутимо медленнее. Корень общий с паком-1, но файлы пака-2 лежат в своей подпапке: у пака-1
# базы и debug/ лежат плоско в корне, и второй пак плоско класть нельзя — оверлеи и выборки
# перемешаются.
MARKUP_ROOT="/home/felix/Projects/mts_markup"
PACK_WORK="$MARKUP_ROOT/pack2"

DB="$PACK_WORK/pack2.sqlite"
DB_REVIEWED="$PACK_WORK/pack2_reviewed.sqlite"
DEBUG_DIR="$PACK_WORK/debug"

# Кэш разметки surya layout по сырым TIFF: pickle на полосу с той же раскладкой папок, что у
# пака. В отличие от пака-1, готового кэша нет — его набивает сам detect (модель зовётся на
# каждую полосу без файла, ~1 с GPU на полосу, то есть около 10 минут на пак). Повторный
# прогон разметку берёт отсюда и модель не зовёт.
LAYOUT_CACHE_DIR="/mnt/system/raw/mts/pack2_layout_surya"

# Очистка пака (шаг 7): закрас разметки и размытие фона. Результат — на SSD, а не на
# /mnt/dump3: корень /mnt/dump3 синхронит Яндекс.Диск, а он переименовывает новые файлы
# поверх исходных. Объём небольшой: ~5 ГиБ (597 полос, почти все в сером по ~8 МиБ).
# Регистр в /mnt/system ЗНАЧИМ: с 2026-09-20 том смонтирован как /mnt/system строчными;
# прежний /mnt/SYSTEM заглавными больше не существует.
CLEAN_ROOT="/mnt/system/raw/mts/pack2_background_blurred"
BLURRED_DIR="$CLEAN_ROOT/blurred"
CLEAN_DEBUG_DIR="$CLEAN_ROOT/debug"

# Должен лежать ВНУТРИ IMAGES_DIR из docker/.env (или совпадать с ним), иначе cvat_server
# не увидит картинок: задачи заводятся из смонтированного share, по сети файлы не передаются.
# Общий с паком-1: to-cvat сам кладёт превью в подпапку $PACK_NAME и заводит отдельный проект.
SHARE_ROOT="$MARKUP_ROOT/cvat_share"

# Все шаги запускаются из корня репозитория: там pyproject.toml, по которому uv собирает
# окружение. BASH_SOURCE, а не $0: путь нужен именно этого файла, а не того, кто его подключил.
cd "$(dirname "${BASH_SOURCE[0]}")/../../.."

mkdir -p "$PACK_WORK"

echo "Пак:      $PACK_DIR"
echo "База:     $DB"

# Бэкап базы перед любым шагом, который её правит. Файл маленький, а внутри лежит ручная
# разметка из CVAT, которой на диске больше нигде нет: пересобрать её нельзя.
if [ -f "$DB" ]; then
    cp -f "$DB" "$DB.bak"
fi
