#!/usr/bin/env bash
#
# Шаг 7: боевой прогон очистки пака — закрас разметки и размытие фона за один проход.
#
# ОСТОРОЖНО: выход весит примерно столько же, сколько вход, — около 300 ГиБ, плюс ~70 ГиБ
# оверлеев при --debug-dir. На /mnt/system свободно порядка 500 ГБ: это влезает ОДИН раз.
# Второй вариант прогона рядом уже не поместится, старый придётся удалять.
#
# ПЕРЕД ПОЛНЫМ ПРОГОНОМ прогнать на одном годе (--only-year 1976) и посмотреть оверлеи:
# структуру подпапок, формат и DPI, обложки (они должны быть скопированы без размытия, но
# с закрашенными печатями) и то, что защитная маска накрывает бледные перемычки букв.
#
# Один проход, а не два. Оригиналы лежат на медленном NTFS-3G; отдельный прогон закраса
# означал бы запись и повторное чтение ещё трёхсот гигабайт.
#
# Раскладка по процессам. Закрас нужен 282 полосам из 12 135 — они идут последовательно в
# родительском процессе, где живёт единственный GpuModels (видеопамять одна на всех).
# Остальные 11 853 полосы — в пуле. --jobs 8, а не 16: пул читает ~300 ГиБ с NTFS-3G и
# пишет столько же на другой том, то есть упирается в диск, а не в счёт.
#
# Умолчания параметров выбраны шагами 5 и 6; менять их здесь, а не в коде.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Выход:    $BLURRED_DIR"
echo "Оверлеи:  $CLEAN_DEBUG_DIR"
df -h /mnt/system | tail -1

CLEANUP_ARGS=(
    --db "$DB_REVIEWED"
    --pack-dir "$PACK_DIR"
    --pack-name "$PACK_NAME"
    --out-dir "$BLURRED_DIR"
    --debug-dir "$CLEAN_DEBUG_DIR"
    --report-csv "$CLEAN_ROOT/report.csv"

    # Проба одним годом — снять комментарий перед первым запуском.
    # --only-year 1976

    # --- Закрас -------------------------------------------------------------
    # LaMa, не SD. По сравнению на 30 полосах (шаг 5) SD выдумывала на месте удалённого
    # объекта псевдотекст и цветные фигуры — на плашке обложки белые псевдобуквы, на
    # бумаге под пометкой строчки поддельного текста. LaMa кладёт чистую бумагу.
    --backend lama
    # Припуск к маске: её рисовали на копии 1/8, край известен с точностью до 8 px.
    --mask-dilate-px 16
    # Группировка связных областей ПО ВСЕЙ ПОЛОСЕ, без деления по видам: раздуть на 1/3
    # своего размера, пересеклись — закрасить одной операцией. Соседние печать и
    # рукописная пометка идут вместе, и штрихи одной не затекают в дыру другой.
    --group-dilate-frac 0.3333
    --roi-scale 2.0
    # 1024, а не 512: при 512 (значение, калиброванное на пальцах) на разметке
    # оставались артефакты — видно на сравнении шага 5.
    --lama-roi-max-side 1024

    # --- Размытие фона ------------------------------------------------------
    # Sauvola по построению может только добрать контент: её локальная маска
    # ОБЪЕДИНЯЕТСЯ с глобальным порогом. При усиленном размытии это дешёвая страховка.
    --method sauvola
    --sauvola-k 0.10
    --threshold-bias 0.5
    # 25 px — диаметр 50 px, то есть ядро размером с целую букву (кегль ~52 px при 600 dpi).
    --dilate-px 25
    # Радиус размытия задаётся отдельно от припуска. Не задан — dilate-px x blur-mult (=100).
    # --blur-px 120
    --blur-mode masked

    # Прямоугольники «подозрение на печать» разметчик НЕ подтвердил — не защищаем.
    --no-protect-stamp-suspect

    --skip-if-exists
    --jobs 8
    --log-level INFO
)
uv run python -m ocr_utils.scan_cleanup run "${CLEANUP_ARGS[@]}"
