#!/usr/bin/env bash
#
# Шаг 7: боевой прогон очистки пака — закрас разметки и размытие фона за один проход.
#
# ОСТОРОЖНО С МЕСТОМ. Замер по прогону 1976 года (1194 полосы): вывод 28 ГиБ, оверлеи
# 1014 МиБ, то есть на все 12 135 полос это около 285 ГиБ вывода и ~10 ГиБ оверлеев.
# На /mnt/system свободно 469 ГиБ (из них 29 ГиБ уже занял 1976), так что прогон влезает
# ОДИН раз: второй вариант рядом не поместится, старый придётся удалять.
#
# ПЕРЕД ПОЛНЫМ ПРОГОНОМ прогнать на одном годе (--only-year 1976) и посмотреть оверлеи:
# структуру подпапок, формат и DPI, обложки (они должны быть скопированы без размытия, но
# с закрашенными печатями) и то, что защитная маска накрывает бледные перемычки букв.
# Проба на 1976 с нынешними параметрами сделана: 1194 полосы, размыто 1176, скопировано 18
# (все — полосные иллюстрации из базы), ошибок 0, 33 зоны закраса, ~60 полос/мин.
# ЭТОТ ГОД УЖЕ ЛЕЖИТ В ВЫВОДЕ, и при --skip-if-exists полный прогон его пропустит; если
# нужен именно пересчёт всего — добавить --no-skip-if-exists.
#
# Один проход, а не два. Оригиналы лежат на медленном NTFS-3G; отдельный прогон закраса
# означал бы запись и повторное чтение ещё трёхсот гигабайт.
#
# Раскладка по процессам. Закрас нужен 282 полосам из 12 135 — они идут последовательно в
# родительском процессе, где живёт единственный GpuModels (видеопамять одна на всех).
# Остальные 11 853 полосы — в пуле. --jobs 8, а не 16: пул читает ~300 ГиБ с NTFS-3G и
# пишет столько же на другой том, то есть упирается в диск, а не в счёт.
#
# ВСЕ РАЗМЕРЫ ЗАДАНЫ ЯВНО, В ПИКСЕЛЯХ. Выводить их из размера кадра нельзя: в «Готовое»
# попадают и НЕПОЛНЫЕ страницы — если текст занимал треть листа, пустые две трети
# обрезаны, — и доля от высоты такого кадра дала бы втрое меньшее окно на том же наборе.
# Размеры определяются НАБОРОМ, поэтому меряются один раз на паке и подставляются сюда.
#
# Замер по паку-1 при 600 dpi (ocr_utils.defocus_detection.scale по выборке полос):
#   толщина штриха      7 px
#   шаг строк          89 px  -> кегль ~52 px, x-height ~37 px, межстрочье ~37 px
# Для другого пака или другого разрешения ПЕРЕМЕРИТЬ и переписать числа ниже.
#
# Умолчания остальных параметров выбраны шагами 5 и 6; менять их здесь, а не в коде.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Выход:    $BLURRED_DIR"
echo "Оверлеи:  $CLEAN_DEBUG_DIR"
df -h /mnt/system | tail -1

CLEANUP_ARGS=(
    --db "$DB_REVIEWED"
    --pack-dir "$PACK_DIR"
    --pack-name "$PACK_NAME"
    --out-dir "$BLURRED_DIR"
    --debug-dir "$CLEAN_DEBUG_DIR"
    --report-csv "$CLEAN_ROOT/report.csv"

    # Проба одним годом — вернуть строку, если параметры менялись и нужен быстрый круг
    # (1194 полосы, ~20 минут). Для полного пака она должна оставаться закомментированной.
    # --only-year 1976

    # --- Закрас -------------------------------------------------------------
    # LaMa, не SD. По сравнению на 30 полосах (шаг 5) SD выдумывала на месте удалённого
    # объекта псевдотекст и цветные фигуры — на плашке обложки белые псевдобуквы, на
    # бумаге под пометкой строчки поддельного текста. LaMa кладёт чистую бумагу.
    --backend lama
    # Нижняя граница припуска ПРИ ГРУППИРОВКЕ (правило «1/3 своего размера» у мелких
    # областей вырождается). В сеть маска идёт БЕЗ припуска: закрашивается ровно то,
    # что обвёл человек, — он и так обводит с запасом.
    --group-min-dilate-px 16
    # Группировка связных областей ПО ВСЕЙ ПОЛОСЕ, без деления по видам: раздуть на 1/3
    # своего размера, пересеклись — закрасить одной операцией. Соседние печать и
    # рукописная пометка идут вместе, и штрихи одной не затекают в дыру другой.
    --group-dilate-frac 0.3333
    --roi-scale 2.0
    # Ограничивается ДЫРА, а не сторона ROI. У LaMa нет «своего» разрешения (сеть
    # полностью свёрточная, ей нужна лишь кратность 8), но обучена она на мелких
    # кропах, и дыра шире пары сотен пикселей ей уже не по зубам: сеть перестаёт
    # видеть противоположный берег и заливает кашей. Замер на печати 632x464
    # (1976/02 IMG_0054_2R), отклонение заливки от бумаги вокруг: при пределе ROI
    # 1024 дыра остаётся 539 px и даёт -14.5 (голубая клякса), при пределе дыры
    # 300 px -- -2.6. Предел ROI сюда не годится в принципе: одна и та же цифра
    # даёт на мелкой пометке и на печати во весь угол совершенно разную дыру.
    --lama-hole-max-px 300

    # --- Размеры, выведенные из набора --------------------------------------
    # Окно Саволы: порядка шага строк, чтобы в него попадали и строка, и межстрочье.
    --sauvola-window 101
    # Оценка уровня бумаги: раздутие в пару штрихов (буквы должны уйти из оценки
    # целиком), размытие крупнее буквы, но мельче неровности света.
    --paper-dilate-px 15
    --paper-blur-px 150
    # Площадь, с которой связная область подтверждается сама по себе: p99 реального
    # шума (области маски, целиком лежащие на пустом поле, имеют площадь до 34 px,
    # медиана 8), при этом точка в тексте — 40-80 px — порог проходит.
    --min-glyph-area 34
    # Площадь, с которой область подтверждается САМА ПО СЕБЕ, без оглядки на отражение.
    # Без неё правило вырождается в «крупная И тёмная», и бледная линейка таблицы в
    # 14 731 px (1966/01 IMG_0047_2R) удалялась целиком. Крапины просвета столько не
    # набирают: самая крупная удаляемая — 243 px.
    --sure-glyph-area 500

    # --- Размытие фона ------------------------------------------------------
    # Sauvola по построению может только добрать контент: её локальная маска
    # ОБЪЕДИНЯЕТСЯ с глобальным порогом. При усиленном размытии это дешёвая страховка.
    --method sauvola
    --sauvola-k 0.10
    --threshold-bias 0.5
    # 25 px — диаметр 50 px, то есть ядро размером с целую букву (кегль ~52 px при 600 dpi).
    --dilate-px 25
    # Радиус размытия задаётся отдельно от припуска.
    --blur-px 100
    --blur-mode masked

    # Доля уровня бумаги, темнее которой область считается настоящей краской. Отражение,
    # а не яркость: на пересвеченной полосе (1966/01 IMG_0047_2R) краска имеет яркость
    # 123-193 при бумаге 255 — светлее, чем крапины просвета на 1976/01 IMG_0052_1L
    # (медиана 183 при бумаге 252). По отражению они расходятся: 0.53 против 0.83.
    # off — не учитывать, auto — порог Оцу по самой полосе (садится около 0.6).
    --ink-level 0.65
    # Не подтверждать область только за то, что она прошла глобальный порог: просвет
    # с оборота проходит его тоже (56.6% пикселей мусора на IMG_0052_1L).
    --no-trust-strong
    # Предохранитель «на полосе есть растр, трогать нельзя» — выключен. Растровые
    # области здесь размечены руками, полосные отсекаются по базе, а искать растр
    # где-то ЕЩЁ этот предохранитель толком не умеет: на 1976 году он сработал трижды
    # и все три раза ложно — на тёмной кромке у края скана и на пятне поля. Цена
    # ошибки при этом высокая и незаметная: полоса целиком уходит в копию.
    --no-halftone-guard

    # Прямоугольники «подозрение на печать» разметчик НЕ подтвердил — не защищаем.
    --no-protect-stamp-suspect

    --no-skip-if-exists
    --jobs 8
    --log-level INFO
)
# Аргументы скрипта дописываются в конец: click берёт последнее вхождение опции,
# поэтому любую из перечисленных выше можно переопределить на месте, не правя файл.
# Так, перепрогон поверх готового вывода — это `run_7_cleanup.sh --no-skip-if-exists`.
uv run python -m ocr_utils.scan_cleanup run "${CLEANUP_ARGS[@]}" "$@"
