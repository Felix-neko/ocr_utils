#!/usr/bin/env bash
#
# Шаг 2: уменьшенные копии полос в share + проект, задачи и джобы CVAT с предразметкой.
#
# Требует поднятого CVAT (docker/up.sh) и того, чтобы SHARE_ROOT лежал внутри IMAGES_DIR
# из docker/.env: задачи заводятся из смонтированного share, по сети файлы не передаются.
#
# Оригиналы читает второй и последний раз — ради уменьшенных копий. Идемпотентен: готовые
# копии пропускаются, существующие задачи не пересоздаются.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Share:    $SHARE_ROOT"

TO_CVAT_ARGS=(
    --db "$DB"
    --pack-name "$PACK_NAME"
    --share-root "$SHARE_ROOT"
    # Уменьшение упирается в CPU, а не в диск: на полосу 25 МиБ чтение с NTFS-3G 0.06 с,
    # декодирование LZW-TIFF 0.38 с, LANCZOS 1/8 — 0.13 с (замер 2026-09-21, пак-2 06/0300_2R).
    # В один процесс это 1.7 полосы/с; «--jobs 1» когда-то попал сюда отладочным остатком.
    --jobs 16
    # Разрешение уменьшенных копий: делитель полосы = round(её dpi / этого), 600 dpi -> 8.
    # Полосам, уже залитым в CVAT, делитель не меняется — их разметка в прежнем масштабе.
    # --cvat-dpi 75
    # Год за годом: задача на 1200 кадров заводится не мгновенно.
    # --only-year 1966
    # Картинки уже готовы прошлым прогоном.
    # --skip-images
    # ОСТОРОЖНО: заливка заменяет разметку задачи целиком, то есть затирает ручную правку.
    # --force-annotations
    # Пересоздать годы, в которых изменились исходники. Ручная разметка неизменившихся
    # полос переносится в новую задачу, изменившиеся получают свежую предразметку.
    # CVAT не умеет удалять отдельные джобы, поэтому пересоздаётся вся задача-год.
    # Перед этим стоит прогнать шаг 3: снимок разметки в базу — лучшая страховка.
    # --recreate-stale
    # Назначить джобы разметчику. БЕЗ ЭТОГО он не увидит ничего: роль worker показывает
    # только назначенное лично, и списки проектов и задач у неё пустые.
    --annotator user
    # Дозалить в УЖЕ размеченные задачи находки детектора таблиц: PATCH, ручная разметка и
    # теги целы; только на кадры, где таких меток ещё нет, — повторный прогон не удваивает.
    # Метки «Таблица», «Схема или line art» и «Повёрнутый текст» дописываются в проект тем же
    # прогоном; устаревшие метки крупного штриха (если проект их застал) — удаляются.
    --append-kinds table,line_art_schema,rotated_text
    # Теги оглавления («Оглавление», «Годовой указатель») из is_toc / is_year_index — тем же
    # PATCH-ем в существующие задачи, только на кадры без таких тегов.
    --append-tags
)
uv run python -m ocr_utils.scan_markup to-cvat "${TO_CVAT_ARGS[@]}"
