#!/usr/bin/env bash
#
# Сравнение детекторов ориентации на СИНТЕТИЧЕСКИХ поворотах настоящих полос пака-1.
#
# ЗАЧЕМ. Размеченного набора «эта полоса повёрнута» нет, и делать его руками по 12 тысячам
# полос никто не станет. Зато есть тысячи полос, про которые все детекторы согласны, что они
# прямые: их можно повернуть самим и знать правильный ответ заранее. Материал при этом
# настоящий — та же бумага, тот же кегль, тот же растр.
#
# Второй, не менее важный смысл: проверка ПРИШИВАЕТ ЗНАКОВЫЕ СОГЛАШЕНИЯ. Каждый чужой
# движок считает угол по-своему (docTR — против часовой, tesseract — по часовой), и ошибка
# в знаке даёт детектор, который уверенно и стабильно поворачивает не в ту сторону. На паке
# это заметить трудно, на матрице ошибок — сразу.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ ПОКАЗЫВАЕТ: как детектор ведёт себя на настоящей боковой полосе, где
# текста одна подпись, а всё остальное — чертёж. Повёрнутая текстовая полоса и полоса
# с боком напечатанным генпланом — разные задачи, и первая заметно легче. Ответ на вторую
# даёт run_orientation.sh и глаза.
set -euo pipefail
source "$(dirname "$0")/common.sh"

# Снятие ВСЕЙ группы процессов при выходе, а не только питона. Пул на forkserver переживает
# смерть своего хозяина: убитый по одному PID прогон оставляет forkserver и двенадцать
# воркеров сиротами, и они продолжают жить. Замер этой сессии: такое наследие прожило почти
# три часа, съедало 43% ядра вхолостую и разгоняло системное время до 49% при 1.28 млн
# прерываний в секунду — соседний прогон замедлился с 4.7 до 0.8 полосы в секунду.
#
# set -m кладёт прогон в отдельную группу, kill -- -$$ снимает её целиком.
set -m
trap 'trap - EXIT INT TERM; kill -- -$$ 2>/dev/null' EXIT INT TERM

BASE_NAME="orientation_validate_pack1"

ARGS=(
    validate
    --root "$SHARPENED_DIR"      # SSD и полное разрешение: это ровно то, что ушло в PDF
    --sample 150                 # 150 полос x 4 поворота = 600 попыток на детектор
    --seed 0                     # прогон должен воспроизводиться
    --jobs 14                    # 16 ядер минус два: родитель в это время занят GPU
    --md-report "${BASE_NAME}.md"
    # --detectors ink_axis,profile,osd,doctr,surya_lines,ocr_vote — умолчание. Выкидывать
    #   из ПРОВЕРКИ арбитра нельзя: именно он отбирает заведомо прямые полосы, и делает это
    #   независимо от остальных — он читает текст, а не судит о нём по геометрии.
)

echo "Проверка детекторов ориентации на $SHARPENED_DIR"
uv run python -m ocr_utils.page_layout.orientation "${ARGS[@]}"
