#!/usr/bin/env bash
#
# Поиск полос пака-1, напечатанных боком или вверх ногами.
#
# ЗАЧЕМ. FineReader с включённым «исправлять ориентацию страницы» падает на промежуточных
# PDF. Падает не на кривых сканах: полоса как страница ориентирована правильно, боком
# напечатана сама иллюстрация — генплан, аксонометрия, широкая таблица, — а текста на такой
# полосе одна подпись вдоль края.
#
# ВХОД — заострённые копии на SSD, а не оригиналы с /mnt/dump3. Во-первых, это ровно то, что
# ушло в PDF, то есть то, на чём падает FineReader. Во-вторых, 12 135 TIFF по 20 МБ с
# шпиндельного NTFS-3G читались бы вчетверо дольше самого счёта.
#
# ВЫХОД — каталог симлинков: подкаталог на детектор, плюс combo (сводный вердикт) и
# «спорные» (ось видна, а сторону детекторы назвали по-разному). Имя симлинка несёт год,
# выпуск, имя картинки, номер страницы в промежуточном PDF и тип поворота — то есть всё,
# что нужно, чтобы открыть эту страницу в FineReader, не ища её.
#
# ВРЕМЯ. Оценка: CPU-часть около 20 минут при --jobs 14, surya на GPU около часа, арбитр —
# по числу кандидатов. Запускать в фоне и ждать ПО СОХРАНЁННОМУ PID (см. CLAUDE.md):
#
#   ./run_scripts/scan_markup/pack1/run_orientation.sh & PID=$!
#   while kill -0 "$PID" 2>/dev/null; do sleep 30; done
set -euo pipefail
source "$(dirname "$0")/common.sh"

# Снятие ВСЕЙ группы процессов при выходе, а не только питона. Пул на forkserver переживает
# смерть своего хозяина: убитый по одному PID прогон оставляет forkserver и двенадцать
# воркеров сиротами, и они продолжают жить. Замер этой сессии: такое наследие прожило почти
# три часа, съедало 43% ядра вхолостую и разгоняло системное время до 49% при 1.28 млн
# прерываний в секунду — соседний прогон замедлился с 4.7 до 0.8 полосы в секунду.
#
# set -m кладёт прогон в отдельную группу, kill -- -$$ снимает её целиком.
set -m
trap 'trap - EXIT INT TERM; kill -- -$$ 2>/dev/null' EXIT INT TERM

BASE_NAME="orientation_pack1"

ARGS=(
    run
    --root "$SHARPENED_DIR"
    --link-root "$PACK_DIR"      # симлинки целим на ОРИГИНАЛЫ: смотреть глазами лучше их
    --db "$DB_REVIEWED"          # только чтение, ради номеров страниц промежуточного PDF
    --pack-name "$PACK_NAME"
    --angles 0,90                # какие повороты вообще рассматривать. Все 42 размеченные
                                 # вручную боковые полосы пака требуют поворота ПО ЧАСОВОЙ:
                                 # широкие рисунки в советских изданиях ставили одинаково.
                                 # Ответ вне набора не может быть дан в принципе, а арбитру
                                 # достаётся вдвое меньше прогонов распознавания. Замер:
                                 # на бланке «Карточка-баланс» отрыв вырос с 0.17 до 0.88.
    --jobs 12                    # не 14: постобработку surya родитель считает на CPU и
                                 # занимает три-четыре ядра, а всего физических шестнадцать
    --gpu-side 1024              # сторона кадра, уезжающего на GPU. ЗАМЕР на восьми
                                 # известных полосах: 1536 даёт 1.81 с/полоса, 1024 — 0.94
                                 # при том же разделении оси 8/8 и даже чуть лучшем запасе
                                 # на слабейшей полосе (-0.79 против -0.69). Узкое место
                                 # здесь не видеокарта (загрузка 6%), а постобработка surya,
                                 # и она считается по пикселям
    --link-dir "${BASE_NAME}_rotate"
    --csv "${BASE_NAME}.csv"     # все полосы и все метрики — по ним калибруются пороги
    --md-report "${BASE_NAME}.md"
    --sheet "${BASE_NAME}_sheet.png"   # миниатюры находок, УЖЕ повёрнутые на предложенный
                                       # угол: проверка глазами сводится к «читается или
                                       # нет», а не к разглядыванию боковой полосы
    # --detectors ink_axis,profile,osd,doctr,surya_lines,ocr_vote — умолчание.
    #   Без surya_lines прогон короче примерно на час, но пропадает единственный
    #   нейросетевой взгляд на ось, а он на разведке разделил все восемь известных полос.
    # --no-arbiter — снять второй проход целиком. Тогда у боковых полос сторону называть
    #   будет некому, и все они уедут в «спорные»: ось видна, а 90 от 270 не отличить.
)

echo "Поиск полос под поворот в $SHARPENED_DIR"
uv run python -m ocr_utils.scan_markup.orientation "${ARGS[@]}"
