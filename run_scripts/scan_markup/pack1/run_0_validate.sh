#!/usr/bin/env bash
#
# Шаг 0: проверка детекции по папкам-эталонам. Гоняется ПЕРЕД полным прогоном.
#
# Полный прогон по паку — это полтерабайта чтения с медленного NTFS-3G, полтора-два часа.
# Крутить по нему пороги нельзя, поэтому пороги крутятся здесь: сотня файлов, четыре
# гигабайта, около полуминуты.
#
# Выборка — папки в CASES_DIR, куда разобраны примеры неправильной разметки из DEBUG_DIR.
# Имя папки называет тип дефекта (список — в ocr_utils/scan_markup/validation/cases.py).
#
# Гоняет ту же связку, что и боевой прогон, включая Surya, — поэтому нужен GPU.
#
# Замер на текущих порогах: 109 дефектов из 110 починены, контроль чист (из 40 полос область
# не пропала ни у одной). Единственный оставшийся — 1970/03 IMG_0104_2R: там находится
# область stamp_suspect, а папка-эталон ждёт, что не найдётся ничего. Расхождение ожидания, а
# не дефект: на полосе действительно стоит библиотечная печать.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Эталоны:  $CASES_DIR"
echo "Отчёт:    $VALIDATE_DIR"

VALIDATE_ARGS=(
    --pack-dir "$PACK_DIR"
    --cases-dir "$CASES_DIR"
    --out-dir "$VALIDATE_DIR"
    # База нужна для двух вещей: узнать порядковые номера полос (без них не проверить
    # обложку) и набрать контрольную выборку из полос, где области уже находились.
    --db "$DB"
    --pack-name "$PACK_NAME"
    # Контроль — страховка от обратной ошибки: чинили одно, потеряли другое.
    --control 40
    --jobs 16
    # Без GPU: проверить одни пиксели.
    # --no-use-surya-layout
    # Пороги, которые чаще всего приходится крутить. Значения по умолчанию — в
    # detection/dots.py и detection/color_kind.py, там же замеры, по которым они выбраны.
    # --chroma-spread-thr 8.0
    # --dot-frac-thr 0.88
    # --cell-px 128
)
uv run python -m ocr_utils.scan_markup validate "${VALIDATE_ARGS[@]}"
