#!/usr/bin/env bash
#
# Шаг 6: сравнение защитных масок — метод бинаризации против радиуса припуска.
#
# Прогоняется ДО боевого прогона: им выбираются --method, --dilate-mm и --blur-mm шага 7.
#
# Что смотреть. crops/crop_N.jpg — ОДИН И ТОТ ЖЕ кусок полосы в масштабе 1:1, выложенный
# в ряд по всем вариантам. Судить надо о бледных перемычках букв: попали они под защиту
# или ушли под размытие. На уменьшенной странице этого не видно вовсе.
#
# Замеры, из которых взяты значения по умолчанию (пак-1, 600 dpi):
#   * шаг строк 89 px, кегль ~52 px, межстрочный просвет ~37 px;
#   * припуск 15 px (нынешний) — под защитой 47% кадра, 25 px — 60%, 35 px — 64%, 45 px — 66%;
#     при 25 px смыкается межстрочник и текстовый блок становится сплошной плашкой, дальше
#     радиус букв уже не защищает — только съедает поля;
#   * Sauvola добирает 0.2-0.3 pp краски сверх Otsu и по построению не может отнять:
#     её локальная маска ОБЪЕДИНЯЕТСЯ с глобальным порогом.
#
# Полосы в выборке — те, где замер показал самую неровную экспозицию по кадру.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Сравнение: $COMPARE_DIR/masks"

COMPARE_ARGS=(
    --db "$DB_REVIEWED"
    --pack-dir "$PACK_DIR"
    --pack-name "$PACK_NAME"
    --out-dir "$COMPARE_DIR/masks"

    --page "1969/12/IMG_0128_1L.tif"
    --page "1971/04/IMG_0042_1L.tif"
    --page "1972/02/IMG_0101_1L.tif"
    --page "1976/08/IMG_0054_1L.tif"

    --method otsu
    --method sauvola

    --dilate-mm 0.635  # 15 px при 600 dpi
    --dilate-mm 1.058  # 25 px
    --dilate-mm 1.482  # 35 px

    # Размытие развязано с припуском: иначе рост защитной маски молча усиливал бы и его,
    # и понять, что именно изменило картинку, было бы нельзя.
    --blur-mm 2.54  # 60 px при 600 dpi
    --blur-mm 5.08  # 120 px
    --blur-mm 10.16  # 240 px

    --crop-side-mm 50.8  # 1200 px при 600 dpi
    --crops 3
    --jobs 4
)
uv run python -m ocr_utils.scan_cleanup compare-masks "${COMPARE_ARGS[@]}"
