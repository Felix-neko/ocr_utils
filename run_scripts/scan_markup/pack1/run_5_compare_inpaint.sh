#!/usr/bin/env bash
#
# Шаг 5: сравнение закрасчиков — LaMa против Stable Diffusion.
#
# ИТОГ ПЕРВОГО ПРОГОНА (30 полос, 44 зоны): выбраны LaMa и сторона ROI 1024. У LaMa при
# 512 остаются артефакты, при 1024 их не видно. SD выдумывает на месте удалённого
# объекта псевдотекст и цветные фигуры и для этой обработки не используется. Скрипт
# оставлен для перекалибровки: сменится материал — сравнение надо повторить.
#
# Прогоняется ДО боевого прогона: от того, что здесь выберется, зависят умолчания шага 7.
#
# Что смотреть. По каждой зоне пишется полоска «до | вариант | вариант ...» в масштабе 1:1
# (уменьшенная страница ничего не покажет: заливка занимает сотни пикселей из шести тысяч),
# рядом — prompt.txt с тем промптом, которым это получено.
#
# Промпт у SD зависит от того, что под зоной: чистая бумага, цветная обложка или
# полутоновая фотография. По паку-1 внутри растровых областей стоят 226 масок из 431,
# то есть больше половины, — потому промпты и разные.
#
# Вариант --group-dilate-frac 0 — контрольный: закрас БЕЗ группировки, каждая связная
# область отдельной операцией. Именно с ним и надо сравнивать 1/3, чтобы понять, даёт ли
# группировка что-нибудь на рукописных надписях, обведённых по буквам.
#
# GPU: последовательно, один прогон на зону на вариант. Выборка детерминированная —
# перезапуск сравнивает тот же материал.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Сравнение: $COMPARE_DIR/inpaint"

COMPARE_ARGS=(
    --db "$DB_REVIEWED"
    --pack-dir "$PACK_DIR"
    --pack-name "$PACK_NAME"
    --out-dir "$COMPARE_DIR/inpaint"

    # ~30 полос с масками, все три вида разметки, оба случая «внутри растра» и вне его.
    --sample 30

    --backend lama
    --backend sd

    # 1/3 — предлагаемое правило, 0 — контроль «без группировки».
    --group-dilate-frac 0.3333
    --group-dilate-frac 0

    --roi-scale 2.0

    # Ось «до чего ужимать ДЫРУ перед сетью». Ограничивать надо именно дыру: предел
    # по стороне ROI даёт на разных зонах разный размер дыры, а качество заливки
    # зависит от неё (см. gpu_models.lama_fill_roi).
    --lama-hole-max-px 250
    --lama-hole-max-px 300
    --lama-hole-max-px 400

    --sd-steps 30
    --sd-guidance 7.0
    --sd-seed 0
)
uv run python -m ocr_utils.scan_cleanup compare-inpaint "${COMPARE_ARGS[@]}"
