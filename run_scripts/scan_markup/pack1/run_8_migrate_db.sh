#!/usr/bin/env bash
#
# Шаг 8: миграция схемы баз разметки под сборку PDF.
#
# Что делает. Переименовывает три колонки — packs.root_path -> source_pics_root,
# pages.file_name -> source_file_name, pages.rel_path -> source_rel_path — и дописывает
# новые: остальные корни путей пака, имена собранных PDF по выпускам, имя и путь
# заострённой копии полосы, номера страниц полосы в промежуточных PDF, а также поля,
# добавленные полосам при сборке полной промежуточной PDF (четыре стороны, в миллиметрах).
#
# ПОЧЕМУ ОТДЕЛЬНЫМ ШАГОМ, А НЕ ПРИ ОТКРЫТИИ БАЗЫ. Дописать пустую колонку безопасно при
# любом исходе — это и делает add_missing_columns на каждом open_db. Переименование
# безопасным не бывает: оно либо прошло целиком, либо нет. А внутри базы лежит ручная
# разметка из CVAT, которая делалась руками неделями и на диске больше нигде не хранится.
#
# ПРОГОНЯЕТСЯ ПО ВСЕМ ЧЕТЫРЁМ ФАЙЛАМ, включая .bak. Незамигрированный бэкап не упадёт
# сразу: open_db его просто не откроет, назвав команду миграции, — но случится это в тот
# момент, когда бэкап понадобился, то есть в самый неподходящий.
#
# Скрипт идемпотентен: повторный прогон по мигрированной базе ничего не делает. Свою
# копию каждой базы он снимает сам, в файл с суффиксом .bak-до-переименования.

set -euo pipefail
source "$(dirname "$0")/common.sh"

DATABASES=(
    "$DB"
    "$DB_REVIEWED"
    "$DB.bak"
    "$DB_REVIEWED.bak"
)

# Несуществующие файлы скрипт пропускает сам, поэтому список можно не подчищать руками.
uv run python -m ocr_utils.db.migrate "${DATABASES[@]}" "$@"
