#!/usr/bin/env bash
#
# Шаг 1: предварительная детекция растровых областей и обложек по оригиналам -> SQLite.
#
# Читает пак целиком, около полутерабайта с медленного NTFS-3G. Идемпотентен: прерванный
# прогон продолжается с того же места, если добавить --skip-detected.
#
# Замер по 1966/03 (97 полос, GPU): ~1.1 с на полосу, то есть на весь пак около 4 часов.
# Журнал текстовый, растра в нём мало — на этом выпуске нашлись обложка и одна полоса с
# чёрными плашками схемы; так и должно быть, пустой результат на текстовой полосе это норма.
#
# CVAT здесь не нужен, нужен GPU: Surya вытаскивает светлые фотографии, которые не попали
# ни в один диапазон яркости.

set -euo pipefail
source "$(dirname "$0")/common.sh"
echo "Оверлеи:  $DEBUG_DIR"

DETECT_ARGS=(
    --pack-dir "$PACK_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"
    # Оверлеи с подписями kind/chroma_frac: без них порог color/grayscale не откалибровать.
    --debug-dir "$DEBUG_DIR"
    # Продолжение прерванного прогона и обновление пака: перечитываются только полосы,
    # у которых разошлись размер и время правки, а из них пересчитываются те, у которых
    # разошёлся и хеш содержимого.
    # --skip-detected
    # Не верить stat вообще: пересчитать хеш каждой полосы. Это перечитывание всего пака.
    # --rehash-all
    # Один год или один выпуск — для пробы перед полным прогоном.
    # --only-year 1966
    # --only-issue 03
    # Пороги color/grayscale. Смещены к color: лишний цветной JPEG стоит мегабайт,
    # а серый вместо цветного — потерянной картинки.
    # --chroma-thr 10
    # --color-frac-thr 0.02
    # Без Surya прогон идёт без GPU, но светлые фотографии теряются.
    # --no-use-surya-layout
)
uv run python -m ocr_utils.scan_markup detect "${DETECT_ARGS[@]}"
