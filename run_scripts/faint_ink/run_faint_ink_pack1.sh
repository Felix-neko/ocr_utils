#!/usr/bin/env bash
#
# Поиск полос пака-1 с пересвеченными буквами и бледными перемычками.
#
# ЗАЧЕМ. Шапка run_7_cleanup.sh требует перед полным прогоном посмотреть глазами, «что
# защитная маска накрывает бледные перемычки букв». Проверки не было — пак очищен
# целиком. Скрипт находит худшие полосы, чтобы было на что смотреть.
#
# ЧТО МЕРИТСЯ И ГДЕ. Мерится ВЫХОД очистки (blurred/), а не оригиналы: вопрос в том, что
# уйдёт в OCR. Оригиналы читаются только по финалистам — ради второй колонки на листе
# врезок, которая и отвечает, дефект был в съёмке или его доела чистка фона.
#
# ЦЕНА ПРОГОНА. Примерно 3.2 секунды на полосу в один поток, из них 1.8 — построение
# РАБОЧЕЙ маски (Савола с окном 101 по 25 мегапикселям). При --jobs 16 это около
# полутора часов на весь пак; /mnt/system — NVMe, в диск прогон не упирается,
# упирается в память и счёт. Проба одним годом (--only-year 1966, 1194 полосы) —
# минут десять.
#
# ВСЕ РАЗМЕРЫ ЗАДАНЫ НАБОРОМ, А НЕ ДОЛЕЙ КАДРА. В «Готовое» попадают и неполные
# страницы, и доля от высоты такого кадра дала бы втрое меньшее окно на том же наборе.
# Замер по паку-1 при 600 dpi: толщина штриха 7 px, шаг строк 89 px. Для другого пака
# или разрешения ПЕРЕМЕРИТЬ (ocr_utils.defocus_detection.scale) и переписать числа.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня.
cd "$(dirname "$0")/../.."

CLEAN_ROOT="/mnt/system/raw/mts/pack1_background_blurred_v2"
BLURRED_DIR="$CLEAN_ROOT/blurred"
ORIGINALS="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/МТС/Готовое/пак-1"
DB="/home/felix/Projects/mts_markup/pack1_reviewed.sqlite"
PACK_NAME="пак-1"

BASE_NAME="faint_ink_pack1"
OUT_CSV="${BASE_NAME}.csv"
REPORT_MD="${BASE_NAME}.md"
SHEET="${BASE_NAME}_sheet.png"
LINK_DIR="${BASE_NAME}_worst"
OVERLAY_DIR="${BASE_NAME}_overlay"

echo "Вход:     $BLURRED_DIR"
echo "База:     $DB"
echo "CSV:      $OUT_CSV"

SCAN_ARGS=(
    --root "$BLURRED_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"

    # Статусы шага 7: полосы не со статусом ok он не размывал (скопировал как есть), и
    # рабочая маска к ним отношения не имеет — мерить по ним перемычки бессмысленно.
    --report-csv "$CLEAN_ROOT/report.csv"

    --out-csv "$OUT_CSV"

    # Сторона тайла. Порядка шести строк набора (шаг строк 89 px): мельче — в тайл не
    # попадает достаточно букв и перцентили скачут, крупнее — местный пересвет
    # размазывается по тайлу и перестаёт быть виден.
    --tile-size 512

    # Упирается в память и счёт, а не в диск (вход на NVMe), поэтому по числу ядер.
    --jobs 16

    # Проба одним годом — вернуть строку, если параметры менялись и нужен быстрый круг.
    # Для полного пака она должна оставаться закомментированной.
    # --only-year 1966
)

REPORT_ARGS=(
    --csv "$OUT_CSV"
    --root "$BLURRED_DIR"

    # Сколько худших в КАЖДОЙ из трёх таблиц. Финалисты — объединение трёх топов,
    # то есть их всегда больше, чем это число, но меньше чем втрое.
    --top 30

    --md "$REPORT_MD"

    # Лист врезок 1:1. Перемычка при 600 dpi — 3-5 пикселей, на превью целой полосы её
    # не видно вообще, поэтому только 1:1 и только вокруг худшего тайла.
    --sheet "$SHEET"
    --sheet-columns 2

    # Вторая колонка на листе: та же врезка из оригинала. Ради неё читается 30 файлов
    # с медленного NTFS-3G — меньше минуты.
    --originals "$ORIGINALS"

    # Симлинки: кликать по ссылкам в markdown получается не везде (PyCharm и Chrome
    # рендерят превью в Chromium, а он запрещает переход на file://).
    --link-dir "$LINK_DIR"

    # Оверлеи: красным та краска, которую щедрая маска видит, а рабочая уже нет.
    # Отвечают на вопрос «потери по всей полосе или в одном выгоревшем углу».
    --overlay-dir "$OVERLAY_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"

    # Должна совпадать с прогоном scan: по ней считались координаты худших тайлов.
    --tile-size 512
)

# Аргументы скрипта дописываются в конец обеих команд: click берёт последнее вхождение
# опции, поэтому любую из перечисленных выше можно переопределить на месте.
uv run python find_faint_ink.py scan "${SCAN_ARGS[@]}" "$@"
uv run python find_faint_ink.py report "${REPORT_ARGS[@]}"
