#!/usr/bin/env bash
#
# ЭГ 1968 04-06: подложить пересъёмку страниц, где текст ушёл под корешок, в копию подшивки.
#
# Читает:  подшивку «ЭГ/в работе/1968/04-06 готово ХП» (626 RAF, постранично; скрытые подпапки не
#          обходятся) и пересъёмку «неразобранное/2026-09-30 ЭГ/289_FUJI ЭГ 1968 3-4 переснятие …»
#          (57 RAF в подпапках «надо повернуть по часовой / против часовой» — уже повёрнуты, берём как есть).
# Пишет:   копию подшивки в $OUT_DIR на SSD; оригинал на Я.Диске не меняется. В копии заменённые
#          оригиналы → .gutter_loss_for_debugging/, пересъёмка → <оригинал>.<снимок>.replacement.RAF
#          (4 снимка с остаточной потерей у корешка — .replacement.gutter_loss.light.RAF), mapping.csv.
#
# Как: AKAZE по всему кадру, все пары «пересъёмка × оригинал», лучший оригинал (не зависит от поворота;
# допуск масштаба 2.0 — снято с другого расстояния). Первый запуск — без APPLY (только mapping.csv),
# спорные пары отсмотреть, потом APPLY=1.
#
set -euo pipefail
# Выход: погасить всю группу (воркеры пула), сохранив код выхода; сигналы на время гашения игнорируются,
# иначе свой же TERM снова зовёт ловушку — рекурсия до переполнения стека bash (SIGSEGV, код 139).
trap 'rc=$?; trap - EXIT; trap "" INT TERM; kill -- -$$ 2>/dev/null || true; exit $rc' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

cd "$(dirname "$0")/../.."

ORIG_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1968/04-06 готово ХП"
RESHOOT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/неразобранное/2026-09-30 ЭГ/289_FUJI ЭГ 1968 3-4 переснятие в порядке номеров (обложка в конце)"
OUT_DIR="/mnt/hotstore/scan_processing/newspapers/eg/1968_04-06"
CACHE_DIR="/mnt/hotstore/scan_processing/newspapers/eg/_cache_akaze"

# Чтение RAF упирается в NTFS-3G: 8 процессов достаточно
JOBS=8
# Порог «та же страница»: настоящие пары этой пересъёмки — сходство 0.178–0.405; первая полоса № 9
# (DSCF0064, другой подшивки III–IV № 9–17) ложно липла к первой полосе № 14 с 0.117 — отсекаем.
# Крышка (DSCF0062) и форзац (DSCF0063) подшивки III–IV пары не имеют (≤ 0.007).
MIN_SIM=0.15
APPLY="${APPLY:-0}"

# Снимки пересъёмки, где текст у корешка всё ещё немного теряется (по списку пользователя)
GUTTER_LIGHT=(
    --gutter-light "надо повернуть по часовой/DSCF0015.RAF"
    --gutter-light "надо повернуть по часовой/DSCF0018.RAF"
    --gutter-light "надо повернуть против часовой/DSCF0008.RAF"
    --gutter-light "надо повернуть против часовой/DSCF0011.RAF"
)
EXTRA=()
[ "$APPLY" = "1" ] && EXTRA+=(--apply)

uv run python replace_reshoots.py \
    "$ORIG_DIR" "$RESHOOT_DIR" "$OUT_DIR" \
    --cache-dir "$CACHE_DIR" \
    --jobs "$JOBS" \
    --min-sim "$MIN_SIM" \
    "${GUTTER_LIGHT[@]}" \
    "${EXTRA[@]}"
