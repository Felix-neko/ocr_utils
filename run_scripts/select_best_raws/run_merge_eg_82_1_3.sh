#!/usr/bin/env bash
#
# Сборка ЭГ 1982 01-03 из двух съёмок: по каждому развороту — снимок с лучшим фокусом.
#
# Читает:  старую съёмку (155 RAF, папка «01-03 (Химки) - перефотать мыло») и новую
#          (276_FUJI, 161 RAF), а также CSV прогонов defocus_detection по обеим
#          (run_defocus_tagged_eg_1982_1_3.sh и run_defocus_tagged_eg_276_82_1_3.sh) — балл DOM.
# Пишет:   выбранные RAF (копии) и manifest.csv в $OUT_DIR на SSD; исходники на Я.Диске только читаются.
#          Имя: <№ разворота>_<исходное имя>.<старый|новый>.RAF, пометки .blurry.* сохраняются.
#
# Как: AKAZE по всему кадру (кадрирование съёмок разное) → пересъёмки внутри съёмки в группы →
# сходство «старая × новая» в полосе ±BAND кадров → монотонное выравнивание (порядок разворотов
# один) → больший DOM, при разнице < 0.005 — новый. Разворот без пары тоже идёт на выход.
# Порог MIN_PAIR_SIM подобран по распределению сходства пар этого прогона (см. сводку в конце вывода).
#
# Время: первый прогон — чтение ~27 ГБ RAF с NTFS (минуты); признаки кэшируются в $CACHE_DIR.
# Первый запуск — с DRY_RUN=1 (только manifest.csv), проверить сопоставление, потом без него.
#
set -euo pipefail
# Выход: погасить всю группу (воркеры пула), сохранив код выхода; сигналы на время гашения игнорируются,
# иначе свой же TERM снова зовёт ловушку — рекурсия до переполнения стека bash (SIGSEGV, код 139).
trap 'rc=$?; trap - EXIT; trap "" INT TERM; kill -- -$$ 2>/dev/null || true; exit $rc' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

cd "$(dirname "$0")/../.."

OLD_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1982/01-03 (Химки) - перефотать мыло"
NEW_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/неразобранное/2026-09-22 ЭГ/276_FUJI ЭГ 1982 1-3"
OLD_CSV="defocus_dom_eg_82_1_3.csv"
NEW_CSV="defocus_dom_eg_276_82_1_3.csv"
OUT_DIR="/mnt/hotstore/scan_processing/newspapers/eg/1982_01-03"
CACHE_DIR="/mnt/hotstore/scan_processing/newspapers/eg/_cache_akaze"

# Чтение RAF упирается в NTFS-3G на /mnt/dump3, а не в счёт: 8 процессов достаточно
JOBS=8
BAND=15
MIN_PAIR_SIM=0.05
DRY_RUN="${DRY_RUN:-0}"
# Исключения: невыбранные кадры, которые всё равно нужны на выходе (идут подряд с выбранным,
# сначала старый, потом новый). DSCF0122 старой съёмки — карта «Единая энергетическая система
# СССР» (разворот 117), оставлен по просьбе пользователя рядом с новым DSCF0127. DSCF0016 новой
# съёмки — второй снимок первой полосы № 2 (разворот 15) рядом с DSCF0015: на снимках язычок
# отогнут в разные стороны, нужны оба.
KEEP_BOTH=(--keep-both "старый:DSCF0122.RAF" --keep-both "новый:DSCF0016.RAF")
# Ручной выбор вместо лучшего DOM: разворот 121 («Эффективная форма сотрудничества» / «В упряжке
# монополий») — старый DSCF0126 вместо нового DSCF0131 (DOM 3.123 против 3.139, разница в пределах
# шума), по решению пользователя.
FORCE_PICK=(--force-pick "старый:DSCF0126.RAF")

EXTRA=()
# Сборка уже существует: --overwrite докопирует новое, уберёт устаревшее и не перекачает то, что на месте
EXTRA=(--overwrite)
[ "$DRY_RUN" = "1" ] && EXTRA+=(--dry-run)

uv run python merge_best_shoots.py \
    "$OLD_DIR" "$OLD_CSV" "$NEW_DIR" "$NEW_CSV" "$OUT_DIR" \
    --cache-dir "$CACHE_DIR" \
    --band "$BAND" \
    --min-pair-sim "$MIN_PAIR_SIM" \
    --jobs "$JOBS" \
    "${KEEP_BOTH[@]}" \
    "${FORCE_PICK[@]}" \
    "${EXTRA[@]}"
