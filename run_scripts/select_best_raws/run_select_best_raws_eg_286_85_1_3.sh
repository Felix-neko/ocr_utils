#!/usr/bin/env bash
#
# Отчёт по группам дубликатов RAF (без копирования файлов) : ищем повторные кадры одной полосы
# методом AKAZE-признаков и показываем, какой файл в группе самый резкий.
# Печатаются только группы из двух и более файлов.
# Партия «286_FUJI ЭГ 1985 1-3» (съёмка 2026-09-30, 166 RAF). В начале папки, по пометке в её имени,
# пара повторных снимков снята не по порядку — повтор может стоять дальше 5 позиций от оригинала,
# поэтому окно поиска расширено с обычных 5 до 15 (166 × 15 сравнений — по-прежнему минуты).
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/неразобранное/2026-09-30 ЭГ/286_FUJI ЭГ 1985 1-3 (в самом начале пара повторных снимков не по порядку)/"
REPORT_FILE="eg_286_85_1_3.txt"
echo "select_best_raws (report):"
echo "  input  = $INPUT_DIR"
echo "  report = $REPORT_FILE"
uv run select_best_raws.py \
    "$INPUT_DIR" \
    --mode report \
    --method local \
    --n-search 15 \
    --min-match-ratio 0.2 \
    --max-scale-change 1.15 \
    2>&1 | tee "$REPORT_FILE"
