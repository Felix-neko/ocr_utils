#!/usr/bin/env bash
#
# ПРОВЕРКА ПЕРЕД БОЕМ: видит ли surya-ocr корпусный набор на газетной полосе.
#
# Оценка фокуса по областям строк осмысленна ровно настолько, насколько эти области
# находятся. Риск конкретный: DetectionPredictor ужимает вход до размера своего
# процессора (порядка 1024 px по стороне), а по высоте режет кадр чанками 1400 px —
# ширину не режет вовсе. Значит ширина превью (2944 px у портретного скана) давится
# втрое, и корпусная строка высотой ~17 px приходит в сеть высотой в пять пикселей.
# Если в таких условиях детектор видит одни заголовки, весь замер пойдёт не по тому
# тексту, а в таблице это будет выглядеть как совершенно нормальное число.
#
# Скрипт прогоняет одни и те же полосы в двух режимах (кадр целиком и перекрывающимися
# тайлами в нативном разрешении) и печатает по каждому: сколько строк найдено, каково
# РАСПРЕДЕЛЕНИЕ ИХ ВЫСОТ и сколько строк попало в самый бедный тайл сетки 3x3.
#
# Как читать результат:
#   * медиана высоты близка к высоте корпуса (16-20 px) — детектор видит нужный текст;
#     уехала вверх — он размечает заголовки;
#   * p90 высоты: у режима page на замеренных полосах 46-49 px против 30-31 у tiles —
#     это и есть перекос в сторону заголовков, видный числом;
#   * «тайлы 3x3 min» — сколько строк в самом бедном тайле. Зональная карта строится на
#     противопоставлении частей кадра друг другу, и тайл без строк — дыра в ней.
#
# Замер на пяти полосах «Социалистической индустрии» 1985 г. дал tiles втрое больше
# строк при вдвое-втрое лучшем покрытии бедного тайла, поэтому tiles и стоит дефолтом.
# Прогоняйте этот скрипт заново на НОВОМ материале: другая газета, другая оптика,
# другой масштаб съёмки — и вывод может смениться.
#
set -euo pipefail

cd "$(dirname "$0")/../.."

# Кадры берутся локально: чтение с /mnt/dump3 (NTFS-3G на шпинделе) медленное, а тут
# важна не пропускная способность диска, а время сети.
INPUT_DIR="${1:-/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Социалистическая индустрия/1985/01-03}"
OUT_DIR="${2:-surya_lines_check}"

echo "Проверка детекции строк:"
echo "  input = $INPUT_DIR"
echo "  out   = $OUT_DIR/  (наложения с рамками найденных строк)"

uv run python scripts/check_surya_line_detection.py "$INPUT_DIR" \
    --out "$OUT_DIR" \
    --count 5 \
    --mode both \
    --tile-side 1100 \
    --tile-overlap 300

echo
echo "Смотреть наложения: рамки должны сидеть на корпусном тексте, а не только на"
echo "заголовках. Зелёные — строки не выше 1.4 медианы кадра, красные — крупнее."
