#!/usr/bin/env bash
#
# Скрининг фокуса по партии «206_FUJI СИ 1987 01-03» (306 файлов RAF) — режим ПО СТРОКАМ:
# что из этой папки переснимать.
#
# Области строк текста находит surya-ocr, и резкость считается ТОЛЬКО по ним. Вопрос, на
# который отвечает прогон, поэтому не «резкий ли кадр в среднем», а «читается ли на нём
# мелкий корпусный текст» — на газетной полосе это разные вопросы: поля и фон резкими
# не бывают в принципе, а заголовки переживают такое размытие, от которого петит
# рассыпается.
#
# Строятся ДВА отчёта, они не заменяют друг друга:
#   1. Общее качество фокуса — насколько плох кадр целиком. Ключевая колонка —
#      «σ/высота», размытие в долях высоты строки: именно она отвечает за
#      распознавание, тогда как сырая σ говорит лишь о том, попала ли оптика в фокус.
#   2. Зональный расфокус — насколько резкость проваливается ВНУТРИ кадра (сетка 3x3,
#      строки привязаны центром тяжести). Кадр может быть хорош в среднем и всё равно
#      требовать пересъёмки, если поплыла его часть; в первый отчёт такой кадр по
#      построению не попадёт. Рядом печатается колонкой старый направленный отчёт —
#      расхождение между ними само по себе повод посмотреть кадр глазами.
#
# ЦЕНА: нужна видеокарта, детекция ~4 с на кадр (против ~1 с на весь тайловый замер), то
# есть первый прогон по 306 файлам — это порядка получаса. Зато результат детекции
# ложится в дисковый кэш, и повторные прогоны с другой агрегацией, сеткой или алгоритмом
# GPU уже не трогают и занимают секунды.
#
# КАК ОТКЛЮЧИТЬ SURYA (вернуться к замеру по равномерной сетке тайлов — без GPU, минуты
# вместо получаса, ценой того, что метрика считается по всему кадру вперемешку с полями):
# закомментируйте в массиве ARGS ниже опцию --use-surya-lines, а вместе с ней и все
# опции, которые без неё не имеют смысла или прямо запрещены, — они помечены пометкой
# [surya]. Особо: --debug-dir без --use-surya-lines не просто бесполезен, а роняет CLI
# ошибкой (по сетке тайлов рисовать нечего). Взамен станут работать --tile-size,
# --aggregate и --quantile; готовый пример тайлового прогона по такой же партии —
# run_defocus_detection_si_1985_1_3.sh.
#
# ЗАПУСКАТЬ ПО ОДНОЙ ПАРТИИ: пороги здесь не абсолютные, файлы ранжируются
# относительно друг друга внутри переданной папки.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/system/raw/SI/208_FUJI СИ 1987 04-06/"
BASE_NAME="defocus_lines_si_87_4_6"

REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
LINK_DIR="${BASE_NAME}_worst"
DEBUG_DIR="${BASE_NAME}_debug"

echo "defocus_detection (по строкам):"
echo "  input = $INPUT_DIR"
echo "  txt   = $REPORT_TXT"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"
echo "  links = $LINK_DIR/"
echo "  debug = $DEBUG_DIR/"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива переносы
# строк законны, и поэтому можно комментировать каждый аргумент отдельно (в цепочке
# с `\` комментарий разорвал бы команду).
ARGS=(
    "$INPUT_DIR"

    # [surya] Собственно режим: мерить только по областям строк, найденным surya.
#    --use-surya-lines

    # [surya] Как подавать кадр детектору. tiles — перекрывающимися тайлами в нативном
    # разрешении. Замер на полосах СИ 1985: page находит втрое меньше строк и смещён к
    # заголовкам (p90 высоты 46-49 px против 30-31), потому что сеть ужимает ширину
    # кадра втрое и корпусный набор до неё не доживает. Аппарат и газета здесь те же,
    # но материал новый — если результат вызовет сомнения, прогоните по этой папке
    # run_check_surya_lines.sh и посмотрите на распределение высот строк.
    --surya-detect-mode tiles

    # [surya] Все тайлы кадра уходят в сеть одним вызовом, surya сама режет их на батчи.
    # Уменьшите, если не хватает видеопамяти; 0 — её собственный выбор (36 для cuda).
    --surya-batch-size 0

    # [surya] Сторона зональной сетки: 3 — это 3x3, 4 — 4x4. Тайлов намеренно мало:
    # вопрос, на который отвечает метрика, — «какую часть кадра переснять», и ответ
    # «правый нижний угол» полезнее карты резкости из сотни ячеек.
    --zonal-tiles 3

    # [surya] Коридор перцентилей высоты строки — что считать мелким текстом. Верхняя
    # граница 60 отсекает заголовки и врезки. Коридор считается ВНУТРИ каждого тайла,
    # а не по кадру: при трапециевидных искажениях ближний край снят крупнее, и общий
    # на кадр коридор выкосил бы из зональной карты целую сторону — ровно ту, где
    # искажения сильнее всего.
    --line-height-percent 0 60

    # ОТЧЁТ 1 — общее качество фокуса, ОТЧЁТ 2 — зональный расфокус. Списки почти не
    # пересекаются, поэтому режутся отдельными опциями. Пятнадцать процентов от 306 —
    # это 46 кадров: список на просмотр, а не готовый приговор. Вместо доли можно
    # задать штуки: --worst-count 15 / --zonal-count 15.
    --worst-percent 15
    --zonal-percent 15

    # Направленный зональный отчёт считается ПАРАЛЛЕЛЬНО тайловому и печатается
    # колонкой рядом. all — все четыре направления, худшее в отчёт: rows ловит мягкий
    # верх/низ, cols — мягкий бок, diag и anti — заваленный УГОЛ. Снимают с рук, и в
    # одной подшивке попадается всё это вперемешку.
    --zonal-axis all

    # Текстовый отчёт: те же таблицы, что и в консоли, но пишет их сама Python-часть
    # напрямую в файл — полоса прогресса (stderr) ему не мешает, tee не нужен.
    --txt-report "$REPORT_TXT"

    # Md-отчёт: обе таблицы с кликабельными ссылками — по нему удобно проходить список
    # глазами в просмотрщике markdown.
    --md-report "$REPORT_MD"

    # CSV: ВСЕ файлы папки со всеми метриками и зональными колонками. Нужен не для
    # чтения, а чтобы подбирать пороги и сверять прогоны между собой.
    --csv "$REPORT_CSV"

    # Папка с симлинками на отобранные кадры (подпапки overall/ и zonal/),
    # пронумерованными по рейтингу. Нужна потому, что кликать по ссылкам в markdown
    # получается не везде: PyCharm и Chrome рендерят превью в Chromium, а он запрещает
    # переход из документа на file://. Эту папку достаточно открыть в XnView и листать
    # стрелками — порядок файлов совпадает с порядком в отчёте.
    --link-dir "$LINK_DIR"

    # [surya] Отладочные наложения: границы тайлов, рамка каждой найденной строки
    # (зелёная — резче медианы кадра, красная — мягче, серая — не измерена), балл и
    # число строк в углу каждого тайла, общий балл в углу кадра. Прогон по новой партии
    # без этой папки смотреть бессмысленно: по одному числу в таблице не отличить
    # «замер идёт по корпусному набору» от «детектор нашёл одни заголовки».
    # ВАЖНО: без --use-surya-lines эта опция не просто не нужна — CLI с ней падает.
#    --debug-dir "$DEBUG_DIR"

    # [surya] Дисковый кэш детекции. По умолчанию ~/.cache/ocr_utils/defocus_lines;
    # здесь задан явно, чтобы его было видно и можно было снести одной командой. Ключ
    # включает mtime файла и параметры детекции, так что чистить его вручную не нужно.
    --detect-cache ".cache/${BASE_NAME}"

    # Сколько ядер оставить системе. Прогон идёт долго, и всё это время машиной надо
    # продолжать пользоваться. Воркерам вдобавок понижается приоритет (nice +10) и
    # запрещается внутренняя многопоточность. Ставьте 4-6, если параллельно работаете
    # в чём-то тяжёлом.
    --reserve-cores 2
)

# $REPORT_TXT пишет сама Python-часть (см. --txt-report выше), поэтому ни tee, ни
# редирект stdout здесь не нужны.
uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
