#!/usr/bin/env bash
#
# Скрининг фокуса по подшивке «ЭГ 1982 01-03» (155 файлов RAF) алгоритмом DOM — тайловый
# режим, без GPU, минуты на всю папку.
#
# Прогон отвечает СРАЗУ НА ДВА ВОПРОСА, и это главное отличие от прежних скриптов:
#
#   1. «Что здесь объективно плохо» — отчёт 3, отбор по АБСОЛЮТНЫМ порогам. Порог не
#      зависит от содержимого папки: в удачной съёмке список окажется коротким или
#      пустым, в неудачной — длинным. Ровно то, чего нельзя получить долей худших.
#   2. «Что здесь хуже остального» — отчёт 1, привычные худшие 30 %, от самых плохих
#      сверху. Нужен затем, что порог не всеведущ: он поймает не всё, а взгляд на
#      худшую треть папки стоит недорого и ловит то, что порог пропустил. Почему именно
#      30 % — в разделе про вашу разметку ниже.
#
# ДРУГАЯ ГАЗЕТА — ЧТО ЭТО МЕНЯЕТ. Пороги пресета откалиброваны на «Социалистической
# индустрии», а тут «Экономическая газета»: другая гарнитура и более плотный набор. Вопрос
# переносимости закрыт двумя замерами. Во-первых, распределения баллов совпадают:
#
#     ЭГ 1982 01-03 (155):         p10 3.042   медиана 3.102   p90 3.130
#     СИ 1988, три подшивки (920): p10 3.058   медиана 3.090   p90 3.120
#
# Во-вторых, одинаков отклик на искусственное размытие: при σ=2.0 балл падает на 1.36-1.38
# у ЭГ против 1.29-1.31 у СИ. Шкала от кегля и гарнитуры не поехала, порог переносится.
#
# ЧТО ПОКАЗАЛА ВАША РАЗМЕТКА. Вы пометили здесь 11 кадров суффиксами .blurry.defocus_*:
# 6 ultralight, 4 light, 1 medium, ни одного тяжёлого. Сверка (ROC-AUC 0.872):
#
#     помечено порогами        5 из 11   (11 кадров в списке)
#     худшие 10 %  (16 кадров) 6 из 11
#     худшие 20 %  (31 кадр)   7 из 11
#     худшие 30 %  (47 кадров) 10 из 11   <- поэтому здесь и стоит 30
#     последняя пометка        ранг 68 из 155 (44 %)
#
# Отсюда главное: НА ЭТОМ МАТЕРИАЛЕ НУЖНЫ ОБА ОТЧЁТА. Ваши пометки — самый лёгкий класс
# дефекта (дефицит балла 0.01-0.09 при медиане хороших 3.106), а три первых порога
# откалиброваны на дефектах с дефицитом 0.1-0.3. Ради этого класса и заведён четвёртый
# уровень ultralight (< 3.04): он добирает три пометки, которые иначе остались бы
# безымянными. Но он же метит 3 % проверенно чистой подшивки СИ, поэтому читается как
# «посмотреть», а не «переснять». Выше поднимать нельзя: порог 3.08 ловит 9 пометок из 11,
# но в том же списке оказывается 112 кадров из 304 отсмотренных глазами и чистых.
#
# НЕТЕКСТОВЫЕ ПОЛОСЫ — ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ, ВОПРОС ЗАКРЫТ. В этом паке, в отличие от
# подшивок СИ, есть обложка и полосные схемы, и они стабильно занимают верх списка, будучи
# сняты резко: DSCF0007 (иллюстрированная обложка), DSCF0122 (карта энергосистемы),
# DSCF0020 и DSCF0033 (полосы диаграмм). В режиме best балл отвечает на вопрос «есть ли на
# полосе резкий МЕЛКИЙ текст», и там, где мелкого текста нет вовсе, ответ «нет» независимо
# от фокуса. Их единицы на пак, и вычёркиваются они глазами за минуту.
#
# Отсеивать их автоматически пробовали, три способа проверены и отвергнуты замером
# (defocus_validation_si_report.md, раздел 6): отбор тайлов по ритму строк роняет среднюю
# точность и выталкивает выше порога верное срабатывание DSCF0019; доля таких тайлов как
# признак полосы не переносится между съёмками. Не тратьте на это время заново.
#
# ПОЧЕМУ DOM. На тринадцати подшивках СИ (4009 кадров, 176 ручных пометок) он обошёл
# работавший до сих пор edge_width: средняя точность 0.732 против 0.664, а при просмотре
# худших 10 % подшивки находится 73 % брака против 61 %. Главное же — у DOM балл не
# зависит от экспозиции по построению (это отношение двух сумм, линейных по контрасту),
# поэтому на него МОЖНО вешать абсолютный порог, а на контраст-зависимые метрики нельзя.
# Разбор: defocus_validation_si_report.md.
#
# ОТКУДА ПОРОГИ. Пресет dom-si: тяжёлый < 2.92, средний < 2.96, лёгкий < 3.00,
# ультралёгкий < 3.04. Первые три проверены
# на подшивке 1988/01-03, отсмотренной глазами целиком и признанной чистой: 2 ложных
# срабатывания на 304 кадра. Посмотреть пороги и их происхождение, ничего не считая:
#
#     uv run python -m ocr_utils.defocus_detection --tag-preset list
#
# Пресет сам ставит --algorithm dom и --aggregate best: порог — это число на шкале
# КОНКРЕТНОЙ метрики при КОНКРЕТНОЙ агрегации, и на чужой шкале он ничего не значит.
# Поэтому задавать их здесь руками не надо, а если задать иначе — скрипт откажется
# считать, вместо того чтобы молча посчитать не то.
#
# ЧТО СМОТРЕТЬ ГЛАЗАМИ. Проще всего открыть в XnView папку симлинков: внутри неё
# defocus_heavy/, defocus_medium/, defocus_light/, defocus_ultralight/ — это результат
# порогов, и overall/ — худшие 30 %. Списки пересекаются, и это нормально.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

# Пак переехал из «неразобранное/26-08-2026» на своё место в «ЭГ/в работе» — там он и
# лежит теперь под именем, которое поставил ему пользователь по итогам первого прогона.
INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1982/01-03 (Химки) - перефотать мыло"
BASE_NAME="defocus_dom_eg_82_1_3"

REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
RETAKE_LIST="${BASE_NAME}_retake.txt"
LINK_DIR="${BASE_NAME}_worst"

echo "defocus_detection (DOM, абсолютные пороги + худшие 10%):"
echo "  input   = $INPUT_DIR"
echo "  txt     = $REPORT_TXT"
echo "  md      = $REPORT_MD"
echo "  csv     = $REPORT_CSV"
echo "  на пересъёмку = $RETAKE_LIST"
echo "  links   = $LINK_DIR/"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива переносы
# строк законны, и поэтому можно комментировать каждый аргумент отдельно (в цепочке
# с `\` комментарий разорвал бы команду).
ARGS=(
    "$INPUT_DIR"

    # Абсолютные пороги тяжести. Отсюда же берутся --algorithm dom и --aggregate best:
    # см. шапку. Свои пороги, если понадобится подвинуть чувствительность:
    #     --tag-thresholds heavy=2.90,medium=2.94,light=2.98,ultralight=3.02
    # (вместо --tag-preset, не вместе с ним; ultralight можно не указывать — тогда полоса
    # пуста). Ориентир из отчёта: порог 2.98 ловит 60 % размеченного брака СИ, 3.00 — 73 %,
    # 3.02 — 82 %, но список при этом растёт быстрее улова, а ложные срабатывания на
    # чистой подшивке идут с 2 до 6.
    --tag-preset dom-si

    # ОТЧЁТ 1 — худшие 30 %, от самых плохих сверху. Тридцать, а не десять: на вашей
    # разметке этого пака в худших 10 % оказалось 6 пометок из 11, а в 30 % — уже 10.
    # Отчёт 3 (по порогам) строится независимо от этого числа и не отменяется им.
    # Если нужен ТОЛЬКО список по порогам — заменить эту опцию на --tagged-only.
    --worst-percent 30

    # ОТЧЁТ 2 — зональный расфокус: кадр может быть хорош в среднем и всё равно требовать
    # пересъёмки, если поплыла его часть. В первый отчёт такой кадр по построению не
    # попадёт. all — все четыре направления, худшее в отчёт: rows ловит мягкий верх/низ,
    # cols — мягкий бок, diag и anti — заваленный угол.
    --zonal-percent 30
    --zonal-axis all

    # Текстовый отчёт: те же таблицы, что и в консоли, но пишет их сама Python-часть
    # напрямую в файл — полоса прогресса (stderr) ему не мешает, tee не нужен.
    --txt-report "$REPORT_TXT"

    # Md-отчёт: все три таблицы с кликабельными ссылками и колонкой тега.
    --md-report "$REPORT_MD"

    # CSV: ВСЕ файлы папки со всеми метриками, тегом и зональными колонками. Нужен не для
    # чтения, а чтобы сверять прогоны между собой и двигать пороги, ничего не пересчитывая.
    --csv "$REPORT_CSV"

    # Плоский список кадров на пересъёмку — то, с чем идут к камере. Пишется всегда, в том
    # числе пустым: пустой файл значит «переснимать нечего», а отсутствие файла — «прогон
    # не доехал», и путать эти два случая нельзя. С расширением .csv вышла бы таблица.
    --retake-list "$RETAKE_LIST"

    # Папка с симлинками: overall/ — худшие 30 %, zonal/ — зональный отчёт,
    # defocus_heavy|medium|light|ultralight/ — результат порогов. Пустая подпапка уровня — тоже
    # ответ: значит, такого брака здесь нет. Нужна потому, что кликать по ссылкам в
    # markdown получается не везде: PyCharm и Chrome рендерят превью в Chromium, а он
    # запрещает переход из документа на file://.
    --link-dir "$LINK_DIR"

    # Сколько ядер оставить системе. Воркерам вдобавок понижается приоритет (nice +10) и
    # запрещается внутренняя многопоточность. Ставьте 4-6, если параллельно работаете
    # в чём-то тяжёлом.
    --reserve-cores 4
)

# $REPORT_TXT пишет сама Python-часть (см. --txt-report выше), поэтому ни tee, ни
# редирект stdout здесь не нужны.
uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
