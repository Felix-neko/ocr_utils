#!/usr/bin/env bash
#
# Скрининг фокуса по выпуску «Социалистическая индустрия 1985, 01-03» (307 файлов RAF):
# что переснимать. Строятся ДВА отчёта, они отвечают на разные вопросы и не заменяют
# друг друга:
#
#   1. Общее качество фокуса — насколько плох кадр целиком.
#   2. Зональный расфокус — насколько резкость проваливается ВНУТРИ кадра.
#      Кадр может быть хорош в среднем и всё равно требовать пересъёмки, если
#      поплыла его часть; в первый отчёт такой кадр по построению не попадёт.
#
# Прогон занимает несколько минут: читаются встроенные в RAF превью, полноразмерный
# RAW не распаковывается. Подробности метода и оговорки — в
# ocr_utils/defocus_detection/README.md и defocus_detection_validation_report.md.
#
# ЗАПУСКАТЬ ПО ОДНОМУ ВЫПУСКУ: пороги здесь не абсолютные, файлы ранжируются
# относительно друг друга внутри переданной папки.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Социалистическая индустрия/1985/01-03"
BASE_NAME="defocus_si_85_01_03"

REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
LINK_DIR="${BASE_NAME}_worst"

echo "defocus_detection:"
echo "  input = $INPUT_DIR"
echo "  txt   = $REPORT_TXT"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"
echo "  links = $LINK_DIR/"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива
# переносы строк законны, и поэтому можно комментировать каждый аргумент отдельно
# (в цепочке с `\` комментарий разорвал бы команду).
ARGS=(
    "$INPUT_DIR"

    # Метрика Crete «The Blur Effect»: кадр размывается ещё раз, и меряется, какую долю
    # перепадов между соседними пикселями он при этом потерял — резкому терять есть что,
    # уже размытому нечего. Величина нормирована на собственную энергию перепадов кадра,
    # поэтому не зависит ни от контента, ни от контраста, и не требует ни одного порога.
    #
    # Почему именно reblur, а не дефолтный edge_width: на размеченной партии СИ того же
    # 1985 года (186_FUJI, 215 файлов, 38 размеченных) reblur разделил классы идеально —
    # AUC 1.000 против 0.940 у edge_width, и все 19 явных расфокусов уместились в топ-28,
    # тогда как edge_width требовал смотреть 79 кадров. Материал здесь тот же: тот же
    # аппарат, та же газета, тот же тип бумаги. Замеры — в
    # defocus_algorithms_comparison_186_fuji.md.
#    --algorithm reblur

    # ОТЧЁТ 1. Сколько худших по общему фокусу показать. Пятнадцать процентов от 307 —
    # это 47 кадров: заметно больше типовых пяти процентов, то есть список на просмотр,
    # а не готовый приговор. Вместо доли можно задать штуки: --worst-count 15.
    # Убрать обе опции — попадут все файлы с их метрикой.
    --worst-percent 15

    # ОТЧЁТ 2. То же самое, но для зонального расфокуса, отдельной опцией: списки
    # почти не пересекаются, и резать их одинаково смысла нет. Аналог по штукам —
    # --zonal-count 15, а --no-zonal убирает второй отчёт целиком.
    --zonal-percent 15
    # Вдоль чего искать провал резкости. all — все четыре направления, худшее в отчёт:
    # rows ловит мягкий верх/низ, cols — мягкий бок, diag и anti — заваленный УГОЛ
    # (полосы идут перпендикулярно диагонали, поэтому крайние из них это сами углы).
    # Снимают с рук, и в одной подшивке попадается всё это вперемешку, так что искать
    # только вдоль одной оси значит гарантированно пропустить часть кадров.
    #
    # Цена: cols шумнее rows (вертикальная полоса лежит внутри одной колонки и наследует
    # её кегль, тогда как горизонтальная пересекает все колонки и усредняет вёрстку), а
    # максимум по четырём коррелированным величинам сам по себе смещён вверх. Если по
    # выпуску известно, что завал всегда с одной стороны, поставьте это направление явно
    # (--zonal-axis rows) — список будет чище. Разбор — в README, § «Шум по направлениям».
    --zonal-axis all

    # Текстовый отчёт: те же таблицы, что и в консоли, но пишет их сама Python-часть
    # напрямую в файл, а не консольный stdout — полоса прогресса (stderr) ему не мешает,
    # и tee/редиректы не нужны.
    --txt-report "$REPORT_TXT"

    # Md-отчёт: обе таблицы с кликабельными ссылками на файлы — по нему и удобно
    # проходить список глазами в просмотрщике markdown.
    --md-report "$REPORT_MD"
    # CSV: ВСЕ файлы папки со всеми метриками и зональными колонками. Нужен не для
    # чтения, а чтобы подбирать пороги и сверять прогоны между собой.
    --csv "$REPORT_CSV"

    # Папка с симлинками на отобранные кадры, пронумерованными по рейтингу. Нужна
    # потому, что кликать по ссылкам в markdown получается не везде: PyCharm и Chrome
    # рендерят превью в Chromium, а он запрещает переход из документа на file://.
    # Эту папку достаточно открыть в XnView и листать стрелками — порядок файлов
    # совпадает с порядком в отчёте. Внутри подпапки overall/ и zonal/.
    --link-dir "$LINK_DIR"

    # Сколько ядер оставить системе. Прогон идёт минутами, и всё это время машиной надо
    # продолжать пользоваться. Одного этого числа мало, поэтому CLI дополнительно понижает
    # воркерам приоритет (nice +10) и запрещает им внутреннюю многопоточность: иначе
    # каждый процесс вправе развернуть по потоку OpenCV на ядро, и занята оказывается вся
    # машина. Ставьте 4-6, если параллельно работаете в чём-то тяжёлом.
    --reserve-cores 2
)

# $REPORT_TXT пишет сама Python-часть (см. --txt-report выше), поэтому ни tee, ни
# редирект stdout здесь не нужны: полоса прогресса (stderr) и служебные сообщения
# просто печатаются на терминал как обычно, ничего не разрывая в файле отчёта.
uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
