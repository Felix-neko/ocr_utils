#!/usr/bin/env bash
#
# Скрининг фокуса ЭГ 1987 11-12 (съёмка 2026-09-30, папка «287_FUJI ЭГ 1987 11-12 нечётная»: в неё сведены
# и нечётная 287, и чётная 288 — 200 RAF с именами NNNN_1 / NNNN_2). Алгоритм DOM, без GPU, минуты на папку.
#
# Читает: RAF папки (только чтение, на Я.Диск ничего не пишет); скрытые подпапки не обходятся.
# Пишет:  defocus_dom_eg_287_87_11_12.{txt,md,csv}, _retake.txt и папку симлинков _worst/ в корне репо.
#
# ПОСТРАНИЧНАЯ СЪЁМКА: кадры вертикальные (EXIF Rotate 90 CW у половины, Rotate 270 CW у другой — чётные и
# нечётные страницы сняты с разворотом камеры), текст в кадре вдвое крупнее, чем при съёмке разворотом.
# Пресет dom-si калиброван на разворотах — абсолютные теги ориентировочные (ср. ЭГ 1962 сентябрь,
# run_defocus_tagged_eg_279_62_9.sh: медиана DOM 3.160). Верх списка займут крышки, форзацы, первые полосы
# с фото и рекламные полосы — отсматривать глазами.
#
# Настройки и их обоснование — как в run_defocus_tagged_eg_1982_1_3.sh (подробная шапка там): пресет
# dom-si (тяжёлый < 2.92, средний < 2.96, лёгкий < 3.00, ультралёгкий < 3.04), худшие 30 %, зональный
# отчёт 30 % по всем направлениям.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/неразобранное/2026-09-30 ЭГ/287_FUJI ЭГ 1987 11-12 нечётная"
BASE_NAME="defocus_dom_eg_287_87_11_12"

echo "defocus_detection (DOM, абсолютные пороги + худшие 30%):"
echo "  input = $INPUT_DIR"
echo "  отчёты = ${BASE_NAME}.{txt,md,csv}, ${BASE_NAME}_retake.txt, ${BASE_NAME}_worst/"

# Аргументы массивом — так каждую опцию можно прокомментировать
ARGS=(
    "$INPUT_DIR"
    # Абсолютные пороги тяжести; сам ставит --algorithm dom и --aggregate best
    --tag-preset dom-si
    # Отчёт 1: худшие 30 % папки, от самых плохих сверху
    --worst-percent 30
    # Отчёт 2: зональный расфокус (поплыла часть кадра), все четыре направления
    --zonal-percent 30
    --zonal-axis all
    # Отчёты: текст, markdown с ссылками, CSV по ВСЕМ кадрам, плоский список на пересъёмку
    --txt-report "${BASE_NAME}.txt"
    --md-report "${BASE_NAME}.md"
    --csv "${BASE_NAME}.csv"
    --retake-list "${BASE_NAME}_retake.txt"
    # Симлинки для XnView: overall/, zonal/, defocus_heavy|medium|light|ultralight/
    --link-dir "${BASE_NAME}_worst"
    # Сколько ядер оставить системе (воркеры с nice +10)
    --reserve-cores 4
)
uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
