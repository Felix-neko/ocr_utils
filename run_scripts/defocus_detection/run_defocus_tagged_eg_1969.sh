#!/usr/bin/env bash
#
# Скрининг фокуса ЭГ 1969 по кварталам (папка «ЭГ/в работе/1969»): 01-03 ХП (623 RAF), 04-06 готово ХП
# (315), 07-09 готово ХП (314), 10-12 ХП (315). Алгоритм DOM — тайловый режим, без GPU, минуты на квартал.
#
# Читает: RAF кварталов (только чтение, на Я.Диск ничего не пишет). Скрытые подпапки
#         `.defocus_for_debugging` (там отложенный брак) не обходятся — прогон без --recursive, а
#         collect_images скрытые подпапки пропускает и при --recursive.
# Пишет:  на каждый квартал свой набор в корне репо: defocus_dom_eg_69_<квартал>.{txt,md,csv},
#         _retake.txt и папку симлинков _worst/ — как у прочих прогонов ЭГ.
#
# ПО ОДНОЙ ПАРТИИ. Каждый квартал прогоняется отдельно: отчёт «худшие 30 %» ранжирует кадры внутри
# переданной папки, и смешивать кварталы разных дней съёмки в одном ранжировании нельзя. Абсолютные
# пороги (отчёт 3) от этого не зависят.
#
# ПОСТРАНИЧНАЯ СЪЁМКА. Все кадры вертикальные (EXIF Rotate 270 CW): страница во весь кадр, текст вдвое
# крупнее, чем при съёмке разворотом. Как у ЭГ 1962 сентябрь (run_defocus_tagged_eg_279_62_9.sh): там
# медиана DOM 3.160, p10 3.065 против 3.119 / 3.081 у разворотов. Пресет dom-si калиброван на разворотах
# («Соц. индустрия», ЭГ 1982) — на постраничной съёмке абсолютные теги ориентировочные, а верх списка
# занимают крышки, форзацы, первые полосы с фото и рекламные полосы: отсматривать глазами.
#
# Настройки и их обоснование — как в run_defocus_tagged_eg_1982_1_3.sh (подробная шапка там):
# пресет dom-si (тяжёлый < 2.92, средний < 2.96, лёгкий < 3.00, ультралёгкий < 3.04), худшие 30 %,
# зональный отчёт 30 % по всем направлениям.
#
# Запуск одного квартала: QUARTERS="07_09" ./run_defocus_tagged_eg_1969.sh
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

YEAR_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1969"

# Квартал → подпапка (имена папок пользователь меняет по ходу работы — править здесь)
declare -A QUARTER_DIRS=(
    [01_03]="01-03 ХП"
    [04_06]="04-06 готово ХП"
    [07_09]="07-09 готово ХП"
    [10_12]="10-12 ХП"
)
QUARTERS="${QUARTERS:-01_03 04_06 07_09 10_12}"

for Q in $QUARTERS; do
    INPUT_DIR="$YEAR_DIR/${QUARTER_DIRS[$Q]}"
    BASE_NAME="defocus_dom_eg_69_${Q}"
    echo "=== ЭГ 1969, квартал $Q: $INPUT_DIR → ${BASE_NAME}.*"

    # Аргументы массивом — так каждую опцию можно прокомментировать
    ARGS=(
        "$INPUT_DIR"
        # Абсолютные пороги тяжести; сам ставит --algorithm dom и --aggregate best
        --tag-preset dom-si
        # Отчёт 1: худшие 30 % квартала, от самых плохих сверху
        --worst-percent 30
        # Отчёт 2: зональный расфокус (поплыла часть кадра), все четыре направления
        --zonal-percent 30
        --zonal-axis all
        # Отчёты: текст, markdown с ссылками, CSV по ВСЕМ кадрам, плоский список на пересъёмку
        --txt-report "${BASE_NAME}.txt"
        --md-report "${BASE_NAME}.md"
        --csv "${BASE_NAME}.csv"
        --retake-list "${BASE_NAME}_retake.txt"
        # Симлинки для XnView: overall/, zonal/, defocus_heavy|medium|light|ultralight/
        --link-dir "${BASE_NAME}_worst"
        # Сколько ядер оставить системе (воркеры с nice +10)
        --reserve-cores 4
    )
    uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
done
