#!/usr/bin/env bash
#
# Скрининг фокуса по подшивке «СИ 1989 07-09» (304 файла RAF) метрикой Variance of
# Laplacian — та же папка, что и в run_defocus_tagged_si_1989_7_9.sh, но другой метрикой.
# Смысл прогона в сверке: два независимых взгляда на одну подшивку, и расхождение списков
# само по себе информация — кадр, который ругают обе метрики, почти наверняка брак.
#
# ЧТО ЭТО ЗА МЕТРИКА. Дисперсия лапласиана — классическая наивная база: изображение
# свёртывается лапласианом (оператор вторых производных, отклик на перепады яркости), и
# баллом служит дисперсия отклика. Резкий кадр даёт много сильных перепадов и большую
# дисперсию, размытый — мало и малую. Считается копейки, никаких настроек не требует.
#
# ЧЕМ ОНА ХОРОША. На четырёх подшивках 1987 (116 ручных пометок) laplacian/best дал
# среднюю точность 0.728 — почти вровень с dom (0.732) и заметно выше edge_width (0.330).
# То есть ВНУТРИ одной папки она ранжирует кадры хорошо.
#
# ЧЕМ ОНА ПЛОХА И ПОЧЕМУ ЗДЕСЬ НЕТ ПОРОГОВ. Балл лапласиана линеен по контрасту и потому
# зависит от экспозиции, ISO и плотности текста на полосе: между съёмочными сессиями его
# уровень плывёт, а внутри сессии он связан с яркостью сильнее прочих метрик (+0.103
# против +0.058 у dom). Абсолютный порог на такой шкале означал бы не «этот кадр размыт»,
# а «этот кадр снят темнее» — поэтому здесь НЕТ ни --tag-preset, ни тегов тяжести, ни
# списка на пересъёмку (CLI его без порогов и не даст: --retake-list требует порогов).
# Остаётся относительный отбор — «кто в этой папке хуже остальных», и запускать скрипт
# надо ПО ОДНОЙ подшивке, не сваливая годы в кучу. Разбор: reports/defocus_validation_si_report.md,
# разделы 3 и 4.
#
# ЧТО СМОТРЕТЬ ГЛАЗАМИ. Папку симлинков: overall/ — худшие 10 % по общему фокусу,
# zonal/ — худшие 10 % по зональному провалу. Подпапок с тегами здесь не будет — их
# ставят пороги, которых у этой метрики нет.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Социалистическая индустрия/1989/07-09"
BASE_NAME="defocus_lap_si_89_7_9"

REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
LINK_DIR="${BASE_NAME}_worst"

echo "defocus_detection (Variance of Laplacian, относительный отбор):"
echo "  input   = $INPUT_DIR"
echo "  txt     = $REPORT_TXT"
echo "  md      = $REPORT_MD"
echo "  csv     = $REPORT_CSV"
echo "  links   = $LINK_DIR/"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива переносы
# строк законны, и поэтому можно комментировать каждый аргумент отдельно (в цепочке
# с `\` комментарий разорвал бы команду).
ARGS=(
    "$INPUT_DIR"

    # Собственно Variance of Laplacian.
    --algorithm laplacian

    # Как сводить тайлы в балл кадра. best — квантиль самых РЕЗКИХ тайлов, то есть
    # вопрос «нашёлся ли на полосе хоть кусок чёткого текста». Именно эта агрегация
    # замерена на 1987 (AP 0.728); median даёт 0.719, а worst для газеты плох в принципе:
    # самые мягкие тайлы полосы — это поля и картинки, у которых мерить нечего.
    --aggregate best
    --quantile 0.80

    # ОТЧЁТ 1 — худшие 10 % по общему фокусу, от самых плохих сверху. Порогов у этой
    # метрики нет (см. шапку), поэтому доля худших здесь единственный способ отбора, а
    # не дополнение к тегам, как в dom-скриптах.
    --worst-percent 10

    # ОТЧЁТ 2 — зональный расфокус: кадр может быть хорош в среднем и всё равно требовать
    # пересъёмки, если поплыла его часть. В первый отчёт такой кадр по построению не
    # попадёт. all — все четыре направления, худшее в отчёт: rows ловит мягкий верх/низ,
    # cols — мягкий бок, diag и anti — заваленный угол.
    --zonal-percent 10
    --zonal-axis all

    # Текстовый отчёт: те же таблицы, что и в консоли, но пишет их сама Python-часть
    # напрямую в файл — полоса прогресса (stderr) ему не мешает, tee не нужен.
    --txt-report "$REPORT_TXT"

    # Md-отчёт: обе таблицы с кликабельными ссылками.
    --md-report "$REPORT_MD"

    # CSV: ВСЕ файлы папки со всеми метриками и зональными колонками. Ради него прогон
    # во многом и делается: рядом лежит csv от dom по той же папке, и списки сверяются
    # покадрово, ничего не пересчитывая.
    --csv "$REPORT_CSV"

    # Папка с симлинками: overall/ — худшие 10 %, zonal/ — зональный отчёт. Нужна потому,
    # что кликать по ссылкам в markdown получается не везде: PyCharm и Chrome рендерят
    # превью в Chromium, а он запрещает переход из документа на file://.
    --link-dir "$LINK_DIR"

    # Сколько ядер оставить системе. Воркерам вдобавок понижается приоритет (nice +10) и
    # запрещается внутренняя многопоточность. Ставьте 4-6, если параллельно работаете
    # в чём-то тяжёлом.
    --reserve-cores 8
)

# $REPORT_TXT пишет сама Python-часть (см. --txt-report выше), поэтому ни tee, ни
# редирект stdout здесь не нужны.
uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
