#!/usr/bin/env bash
#
# Скрининг фокуса по выпуску «Социалистическая индустрия 1985, 01-03» — режим ПО СТРОКАМ.
#
# Отличие от run_defocus_detection_si_1985_1_3.sh, который меряет по равномерной сетке
# тайлов: здесь области строк текста сначала находит surya-ocr, и резкость считается
# ТОЛЬКО по ним. Вопрос, на который отвечает такой прогон, уже: не «резкий ли кадр в
# среднем», а «читается ли на нём мелкий корпусный текст».
#
# Что это даёт:
#   * колонка «σ/высота» — размытие в долях высоты строки. Одно и то же размытие не
#     мешает заголовку и убивает петит, поэтому именно эта величина отвечает за
#     распознавание, а сырая σ говорит только о том, попала ли оптика в фокус;
#   * зональный расфокус ищется по сетке 3x3, куда строки привязаны центром тяжести.
#     Старый направленный отчёт при этом никуда не девается и печатается колонкой рядом:
#     обе оценки считаются независимо, и расхождение между ними — само по себе повод
#     посмотреть кадр глазами.
#
# ЦЕНА: нужна видеокарта, и первый прогон идёт заметно дольше тайлового (детекция ~4 с на
# кадр против ~1 с на весь замер). Зато результат детекции ложится в дисковый кэш, и
# повторные прогоны — с другой агрегацией, другой сеткой, другим алгоритмом — GPU уже
# не трогают вовсе и занимают секунды.
#
# ЗАПУСКАТЬ ПО ОДНОМУ ВЫПУСКУ: пороги здесь не абсолютные, файлы ранжируются
# относительно друг друга внутри переданной папки.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Социалистическая индустрия/1985/01-03"
BASE_NAME="defocus_lines_si_85_01_03"

REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
LINK_DIR="${BASE_NAME}_worst"
DEBUG_DIR="${BASE_NAME}_debug"

echo "defocus_detection (по строкам):"
echo "  input = $INPUT_DIR"
echo "  txt   = $REPORT_TXT"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"
echo "  links = $LINK_DIR/"
echo "  debug = $DEBUG_DIR/"

ARGS=(
    "$INPUT_DIR"

    # Собственно режим: мерить только по областям строк, найденным surya.
    --use-surya-lines

    # Как подавать кадр детектору. tiles — перекрывающимися тайлами в нативном
    # разрешении. Замер на пяти полосах этого же выпуска: page находит 542-761 строку
    # против 1533-2110 у tiles, и главное — смещён к заголовкам (p90 высоты 46-49 px
    # против 30-31), потому что сеть ужимает ширину кадра втрое и корпусный набор до
    # неё не доживает. Мельчить тайлы тоже вредно: при стороне 800 px строк нашлось
    # МЕНЬШЕ — строка чаще перерезается границей тайла.
    --surya-detect-mode tiles

    # Все тайлы кадра уходят в сеть одним вызовом, surya сама режет их на батчи.
    # Уменьшите, если не хватает видеопамяти; 0 — её собственный выбор (36 для cuda).
    --surya-batch-size 0

    # Сторона зональной сетки: 3 — это 3x3, 4 — 4x4. Тайлов намеренно мало: вопрос,
    # на который отвечает метрика, — «какую часть кадра переснять», и ответ «правый
    # нижний угол» полезнее карты резкости из сотни ячеек.
    --zonal-tiles 3

    # Коридор перцентилей высоты строки — что считать мелким текстом. Верхняя граница
    # 60 отсекает заголовки и врезки. Коридор считается ВНУТРИ каждого тайла, а не по
    # кадру: при трапециевидных искажениях ближний край снят крупнее, и общий на кадр
    # коридор выкосил бы из зональной карты целую сторону — ровно ту, где искажения
    # сильнее всего.
    --line-height-percent 0 60

    # ОТЧЁТ 1 — общее качество фокуса, ОТЧЁТ 2 — зональный расфокус. Списки почти не
    # пересекаются, поэтому режутся отдельными опциями.
    --worst-percent 15
    --zonal-percent 15

    # Направленный зональный отчёт считается ПАРАЛЛЕЛЬНО тайловому и печатается
    # колонкой рядом — сравнить их на одной папке полезно.
    --zonal-axis all

    --txt-report "$REPORT_TXT"
    --md-report "$REPORT_MD"
    --csv "$REPORT_CSV"
    --link-dir "$LINK_DIR"

    # Отладочные наложения: границы тайлов, рамка каждой найденной строки (зелёная —
    # резче медианы кадра, красная — мягче, серая — не измерена), балл и число строк в
    # углу каждого тайла, общий балл в углу кадра. Прогон по незнакомому материалу без
    # этой папки смотреть бессмысленно: по одному числу в таблице не отличить «замер
    # идёт по корпусному набору» от «детектор нашёл одни заголовки».
    #
    # Числами подписаны не все строки, а выборка поровну от каждого тайла: на газетной
    # полосе строк за тысячу, и подписать их все — значит залить кадр текстом. Сплошную
    # картину даёт цвет рамок.
    --debug-dir "$DEBUG_DIR"

    # Дисковый кэш детекции. По умолчанию ~/.cache/ocr_utils/defocus_lines; здесь задан
    # явно, чтобы его было видно и можно было снести одной командой. Ключ включает mtime
    # файла и параметры детекции, так что чистить его вручную не нужно.
    --detect-cache ".cache/${BASE_NAME}"

    --reserve-cores 2
)

uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
