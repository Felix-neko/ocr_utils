#!/usr/bin/env bash
#
# Сравнение ВСЕХ алгоритмов детекции расфокуса на одной папке: СИ 1985 07-09 чётная
# (186_FUJI, 215 файлов RAF). По каждому алгоритму сохраняется ПОЛНЫЙ отчёт — то есть
# все файлы папки, а не только худшие проценты: отбор здесь не нужен, потому что дальше
# отчёты читает не человек, а compare_defocus_algorithms.py, которому нужны позиции
# размеченных файлов во всём списке.
#
# По каждому алгоритму пишутся три файла:
#   <алг>_report.txt — консольный вывод обеих таблиц (как его видит человек);
#   <алг>_report.md  — то же в markdown с кликабельными ссылками на файлы;
#   <алг>_scores.csv — все файлы со всеми метриками и зональными колонками.
#
# ВАЖНО про второй отчёт. Зональный расфокус (zonal.py) считается через ширину края
# ВСЕГДА, какой бы алгоритм ни был выбран для общего балла. Поэтому вторая таблица во
# всех шести прогонах обязана совпасть до последнего знака; сравнивать по ней алгоритмы
# нечего, и compare_defocus_algorithms.py это совпадение проверяет явно.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/SYSTEM/raw/SI/186_FUJI - СИ 1985 07-09 четная"
OUT_DIR="defocus_compare_186_fuji"

# combo идёт последним: он считает сразу две метрики (edge_width + reblur) и потому
# самый долгий, а результаты первых пяти прогонов к тому моменту уже на диске.
# Полный прогон занимает около четверти часа, поэтому именами алгоритмов в аргументах
# можно пересчитать только часть: "$0 moire combo" после обрыва посреди списка.
ALGORITHMS=(edge_width reblur moire hf_mid laplacian combo)
if [[ $# -gt 0 ]]; then
    ALGORITHMS=("$@")
fi

mkdir -p "$OUT_DIR"

echo "Сравнение алгоритмов детекции расфокуса"
echo "  input = $INPUT_DIR"
echo "  out   = $OUT_DIR/"

for algorithm in "${ALGORITHMS[@]}"; do
    echo
    echo "=== $algorithm ==="

    ARGS=(
        "$INPUT_DIR"
        --algorithm "$algorithm"

        # Ни --worst-percent, ни --zonal-percent: в отчёт идут ВСЕ файлы. Это и есть
        # «полный отчёт» — по нему видно позицию каждого размеченного файла.

        # Все четыре направления зонального профиля (верх/низ, бок, оба угла), в отчёт
        # идёт худшее: заранее неизвестно, куда завалилась плоскость съёмки в этой партии.
        --zonal-axis all

        --md-report "$OUT_DIR/${algorithm}_report.md"
        --csv "$OUT_DIR/${algorithm}_scores.csv"

        # Два ядра из шестнадцати оставляем системе: прогон идёт минутами, и всё это
        # время машиной надо продолжать пользоваться.
        --reserve-cores 2

        # Полоса прогресса не нужна: вывод уходит в файл через tee.
        --quiet
    )

    uv run python -m ocr_utils.defocus_detection "${ARGS[@]}" 2>&1 | tee "$OUT_DIR/${algorithm}_report.txt"
done

echo
echo "Готово. Отчёты в $OUT_DIR/"
