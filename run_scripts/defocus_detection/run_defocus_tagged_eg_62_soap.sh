#!/usr/bin/env bash
#
# Скрининг фокуса ЭГ 1962 «мыло» по папкам (ЭГ/в работе/1962): 01-02 мыло (435 RAF, 13 уже помечены
# пользователем как расфокус), 03-04 мыло (442, 23), 05-06 мыло (437, 25), 10-12 2 мыло (242, 7).
# Алгоритм DOM — тайловый режим, без GPU, минуты на папку.
#
# Читает: RAF папок (только чтение, на Я.Диск ничего не пишет); скрытые подпапки не обходятся.
# Пишет:  на каждую папку свой набор в корне репо: defocus_dom_eg_62_<папка>.{txt,md,csv}, _retake.txt и
#         папку симлинков _worst/.
#
# ПО ОДНОЙ ПАРТИИ. Каждая папка прогоняется отдельно: отчёт «худшие 30 %» ранжирует кадры внутри папки,
# смешивать съёмки разных дней в одном ранжировании нельзя. Абсолютные пороги от этого не зависят.
#
# ПОСТРАНИЧНАЯ СЪЁМКА: кадры вертикальные (EXIF Rotate 90 CW; в 03-04 один кадр горизонтальный —
# разворот или вклейка), текст вдвое крупнее, чем при съёмке разворотом. Пресет dom-si калиброван на
# разворотах — абсолютные теги ориентировочные (ср. ЭГ 1962 сентябрь, run_defocus_tagged_eg_279_62_9.sh:
# медиана DOM 3.160). Верх списка займут крышки, форзацы, первые полосы с фото и рекламные полосы —
# отсматривать глазами. Пометки пользователя (*defocus* в имени) детектор не читает — по ним удобно сверить
# улов: сколько помеченных попало в теги и в худшие 30 %.
#
# Настройки и их обоснование — как в run_defocus_tagged_eg_1982_1_3.sh (подробная шапка там):
# пресет dom-si (тяжёлый < 2.92, средний < 2.96, лёгкий < 3.00, ультралёгкий < 3.04), худшие 30 %,
# зональный отчёт 30 % по всем направлениям.
#
# Запуск одной папки: PARTS="05_06" ./run_defocus_tagged_eg_62_soap.sh
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

YEAR_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1962"

# Метка → подпапка (имена папок пользователь меняет по ходу работы — править здесь)
declare -A PART_DIRS=(
    [01_02]="01-02 мыло"
    [03_04]="03-04 мыло"
    [05_06]="05-06 мыло"
    [10_12_2]="10-12 2 мыло"
)
PARTS="${PARTS:-01_02 03_04 05_06 10_12_2}"

for Q in $PARTS; do
    INPUT_DIR="$YEAR_DIR/${PART_DIRS[$Q]}"
    BASE_NAME="defocus_dom_eg_62_${Q}"
    echo "=== ЭГ 1962, $Q: $INPUT_DIR → ${BASE_NAME}.*"

    # Аргументы массивом — так каждую опцию можно прокомментировать
    ARGS=(
        "$INPUT_DIR"
        # Абсолютные пороги тяжести; сам ставит --algorithm dom и --aggregate best
        --tag-preset dom-si
        # Отчёт 1: худшие 30 % папки, от самых плохих сверху
        --worst-percent 30
        # Отчёт 2: зональный расфокус (поплыла часть кадра), все четыре направления
        --zonal-percent 30
        --zonal-axis all
        # Отчёты: текст, markdown с ссылками, CSV по ВСЕМ кадрам, плоский список на пересъёмку
        --txt-report "${BASE_NAME}.txt"
        --md-report "${BASE_NAME}.md"
        --csv "${BASE_NAME}.csv"
        --retake-list "${BASE_NAME}_retake.txt"
        # Симлинки для XnView: overall/, zonal/, defocus_heavy|medium|light|ultralight/
        --link-dir "${BASE_NAME}_worst"
        # Сколько ядер оставить системе (воркеры с nice +10)
        --reserve-cores 4
    )
    uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
done
