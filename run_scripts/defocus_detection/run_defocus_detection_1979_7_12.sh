#!/usr/bin/env bash
#
# Скрининг фокуса по выпуску «ЭГ 1979, 7-12» (317 файлов RAF): что переснимать.
# Строятся ДВА отчёта, они отвечают на разные вопросы и не заменяют друг друга:
#
#   1. Общее качество фокуса — насколько плох кадр целиком.
#   2. Зональный расфокус — насколько резкость проваливается ВНУТРИ кадра.
#      Кадр может быть хорош в среднем и всё равно требовать пересъёмки, если
#      поплыла его часть; в первый отчёт такой кадр по построению не попадёт
#      (эталонный пример — DSCF0196: 129-е место в первом отчёте и 1-е во втором).
#
# Прогон занимает около трёх минут: читаются встроенные в RAF превью 4416x2944,
# полноразмерный RAW не распаковывается. Подробности метода и оговорки —
# в ocr_utils/defocus_detection/README.md и defocus_detection_validation_report.md.
#
# ЗАПУСКАТЬ ПО ОДНОМУ ВЫПУСКУ: пороги здесь не абсолютные, файлы ранжируются
# относительно друг друга внутри переданной папки.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1979/7-12 дофотать лёгкие расфокусы"
REPORT_TXT="defocus_1979_7_12_report.txt"
REPORT_MD="defocus_1979_7_12_report.md"
REPORT_CSV="defocus_1979_7_12_scores.csv"

echo "defocus_detection:"
echo "  input = $INPUT_DIR"
echo "  txt   = $REPORT_TXT"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива
# переносы строк законны, и поэтому можно комментировать каждый аргумент отдельно
# (в цепочке с `\` комментарий разорвал бы команду).
ARGS=(
    "$INPUT_DIR"

    # Метрика: субпиксельная ширина края штриха. Единственная из набора, которая
    # не зависит ни от количества текста на полосе, ни от кегля, ни от ISO.
    # Альтернатива для незнакомого материала — combo (консенсус двух метрик).
    --algorithm edge_width

    # ОТЧЁТ 1. Сколько худших по общему фокусу показать. Пять процентов — примерно
    # столько кадров и приходится переснимать; вместо доли можно задать штуки:
    # --worst-count 15. Убрать обе опции — попадут все файлы с их метрикой.
    --worst-percent 5

    # ОТЧЁТ 2. То же самое, но для зонального расфокуса, отдельной опцией: списки
    # почти не пересекаются, и резать их одинаково смысла нет. Аналог по штукам —
    # --zonal-count 15, а --no-zonal убирает второй отчёт целиком.
    --zonal-percent 5
    # Поперёк чего искать зону. rows (горизонтальные полосы) верно для газетных
    # полос и книг: полоса пересекает все колонки и усредняет вёрстку. Ставить cols
    # имеет смысл только там, где текст идёт горизонтальными блоками во всю ширину.
    --zonal-axis rows

    # Md-отчёт: обе таблицы с кликабельными ссылками на файлы — по нему и удобно
    # проходить список глазами в просмотрщике markdown.
    --md-report "$REPORT_MD"
    # CSV: ВСЕ файлы папки со всеми метриками и зональными колонками. Нужен не для
    # чтения, а чтобы подбирать пороги и сверять прогоны между собой.
    --csv "$REPORT_CSV"

    # Сколько ядер оставить системе. Прогон идёт минутами, и всё это время машиной надо
    # продолжать пользоваться. Одного этого числа мало, поэтому CLI дополнительно понижает
    # воркерам приоритет (nice +10) и запрещает им внутреннюю многопоточность: иначе
    # каждый процесс вправе развернуть по потоку OpenCV на ядро, и занята оказывается вся
    # машина. Ставьте 4-6, если параллельно работаете в чём-то тяжёлом.
    --reserve-cores 2

    # Полоса прогресса не нужна: вывод и так уходит в файл через tee.
    --quiet
)

uv run python -m ocr_utils.defocus_detection "${ARGS[@]}" 2>&1 | tee "$REPORT_TXT"
