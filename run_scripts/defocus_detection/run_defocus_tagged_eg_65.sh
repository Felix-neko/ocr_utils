#!/usr/bin/env bash
#
# Скрининг фокуса ЭГ 1965 по папкам (ЭГ/в работе/1965): 01-03 готово дофотать мыло (314 RAF, 20 уже помечены
# пользователем как расфокус), 04-06 готово мыло (314, 79), 10-12 разгладить и перефотать н41с35 (314, пометок
# нет; скрытая .debug/ не обходится). Алгоритм DOM — тайловый режим, без GPU, минуты на папку.
#
# Читает: RAF папок (только чтение, на Я.Диск ничего не пишет); скрытые подпапки не обходятся.
# Пишет:  на каждую папку свой набор в корне репо: defocus_dom_eg_65_<папка>.{txt,md,csv}, _retake.txt и
#         папку симлинков _worst/.
#
# ПО ОДНОЙ ПАРТИИ. Каждая папка прогоняется отдельно: отчёт «худшие 30 %» ранжирует кадры внутри папки,
# смешивать съёмки разных дней в одном ранжировании нельзя. Абсолютные пороги от этого не зависят.
#
# СЪЁМКА РАЗВОРОТАМИ: кадры горизонтальные (EXIF Horizontal) — как у ЭГ 1982 и ЭГ 1962 июль-август, на
# которых пресет dom-si проверен (медиана DOM 3.10–3.12), так что абсолютные теги читаются напрямую.
# Верх списка всё равно займут крышки, форзацы и полосы почти без мелкого текста (фото, карты) —
# их отсеивать глазами. Пометки пользователя (*defocus* в имени) детектор не читает — по ним удобно
# сверить улов: сколько помеченных попало в теги и в худшие 30 %.
#
# Настройки и их обоснование — как в run_defocus_tagged_eg_1982_1_3.sh (подробная шапка там):
# пресет dom-si (тяжёлый < 2.92, средний < 2.96, лёгкий < 3.00, ультралёгкий < 3.04), худшие 30 %,
# зональный отчёт 30 % по всем направлениям.
#
# Запуск одной папки: PARTS="04_06" ./run_defocus_tagged_eg_65.sh
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути внутри отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

YEAR_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/ЭГ/в работе/1965"

# Метка → подпапка (имена папок пользователь меняет по ходу работы — править здесь)
declare -A PART_DIRS=(
    [01_03]="01-03 готово дофотать мыло"
    [04_06]="04-06 готово мыло"
    [10_12]="10-12 разгладить и перефотать н41с35"
)
PARTS="${PARTS:-01_03 04_06 10_12}"

for Q in $PARTS; do
    INPUT_DIR="$YEAR_DIR/${PART_DIRS[$Q]}"
    BASE_NAME="defocus_dom_eg_65_${Q}"
    echo "=== ЭГ 1965, $Q: $INPUT_DIR → ${BASE_NAME}.*"

    # Аргументы массивом — так каждую опцию можно прокомментировать
    ARGS=(
        "$INPUT_DIR"
        # Абсолютные пороги тяжести; сам ставит --algorithm dom и --aggregate best
        --tag-preset dom-si
        # Отчёт 1: худшие 30 % папки, от самых плохих сверху
        --worst-percent 30
        # Отчёт 2: зональный расфокус (поплыла часть кадра), все четыре направления
        --zonal-percent 30
        --zonal-axis all
        # Отчёты: текст, markdown с ссылками, CSV по ВСЕМ кадрам, плоский список на пересъёмку
        --txt-report "${BASE_NAME}.txt"
        --md-report "${BASE_NAME}.md"
        --csv "${BASE_NAME}.csv"
        --retake-list "${BASE_NAME}_retake.txt"
        # Симлинки для XnView: overall/, zonal/, defocus_heavy|medium|light|ultralight/
        --link-dir "${BASE_NAME}_worst"
        # Сколько ядер оставить системе (воркеры с nice +10)
        --reserve-cores 4
    )
    uv run python -m ocr_utils.defocus_detection "${ARGS[@]}"
done
