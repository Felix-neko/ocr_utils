#!/usr/bin/env bash
#
# Общие ключи прогонов scan_cropping v2 по паку-6 (МТС и РИСК, кадры 5875×4570). Сам ничего не запускает —
# подключается через `source` из run_v2_pack6*.sh и задаёт массив V2_PACK6_ARGS.
#
# Числа:
#   --px-per-mm 13.8 — кадры той же съёмки, что калибровочные МТО 1990 (~6.9 px/мм на ½ кадра).
#   --lama-hole-max-px 300 — предел рамки дыры в масштабе LaMa (research/lama_params: разметка CVAT — 300).
#   --finger-zone-light-increment 20,20 — высветление зоны пальца перед LaMa, как во всех прогонах МТС v1: LaMa
#       заливает дыру на 25–35 уровней темнее бумаги.
#   --layout-pad-px 18,36 — припуск блоков surya, один для copy back в зоне пальца и для защиты контента от вырезки
#       (решение 2026-10-14): по X как в v1 (≈ 1.3 мм), по Y вдвое меньше v1 (≈ 2.6 мм; 72 v1 — под тень пальца, теперь
#       её снимает --finger-shadow, а полоса 5 мм под блоком возвращала кончик пальца, МТС 1990/01 IMG_0842).
#   --copy-back-over-fingers — блоки surya, задетые закрасом, возвращаются с оригинала внутри «не фона» вместе с руками:
#       детектор пальцев ошибается, контент важнее вида (решение 2026-10-13). С 2026-10-14 — по классу блока: Picture и
#       Figure целиком (ложные пальцы на портретах), остальные — только зона дилатации пальца, без ядра (copy_back.py).
#   --fill-before-copy-back — закрас от точного края бумаги, защита контента и copy back — поверх готового закраса:
#       печать и край обложки, попавшие в блок surya у края, тянулись Telea шлейфом до края кадра (МТС 1990/03 IMG_0973).
#   --fill pull_push — закрас не-бумаги pull-push по пирамиде от полосы бумаги у края (10 мм) без подозрительного (ΔE от
#       медианы участка 25 мм, темнее медианы), по страницам с растушёвкой 8 мм. Telea тянул печати, край обложки и
#       тень у края шлейфом (research/border_fill: на 55 кадрах со шлейфом мера 21.9 тыс. → 3.5 тыс. мм² против
#       закраса Telea от точного края, 95 тыс. — прежний порядок).
#   --fit-sides — устранение выступов и ям на внешних боковых сторонах плоских страниц по робастной кривой (медиана 25 мм
#       + гаусс 4 мм): выбросы SAM 3 (заливка LaMa на торце, МТС 1991/05 IMG_0240), ямы до 10 мм (не фон).
#   --no-snap-sides — подтяжка стороны к краю листа (помогает на загнутой кромке, РИСК 1991/05 IMG_0538) выключена:
#       на МТС 1991/05 IMG_0217, 0222, 0224 она уводит сторону на торец (+2…+4 мм).
#   --keystone-layout — surya layout по кадру, выпрямленному по трапециям страниц; блоки возвращаются наклонными
#       четырёхугольниками. Осевые рамки по наклонным строкам выходили на обложку и фон (МТС 1990/03 IMG_1031).
#   --ink-fill — второй проход SAM 3 по кадру без крупной краски, бумага — объединение (research/sam3_ink_fill: толстая
#       напечатанная рамка останавливала SAM 3, МТС 1991/05 IMG_0250 — +366 тыс. px сегментации).
#   --refine-depth 35 — уточнение склейки не глубже 5 мм от фона (при 1.5 см съедало номер страницы у корешка).

V2_PACK6_ARGS=(
    --recursive
    --skip-if-exists
    --no-save-fingers
    --px-per-mm 13.8
    --lama-hole-max-px 300
    --finger-zone-light-increment 20,20
    --fill pull_push
    --layout-pad-px 18,36
    --refine-depth 35
    --ink-fill
    --keystone-layout
    --fit-sides
    --no-snap-sides
    --copy-back-over-fingers
    --fill-before-copy-back
    --compensate-levels
    --output-format tiff
    --force-dpi 450
)
