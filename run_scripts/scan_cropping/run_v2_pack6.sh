#!/usr/bin/env bash
#
# scan_cropping v2 по всему паку-6 (МТС 1990–1991, РИСК 1991–1993; 2526 кадров разворотов на чёрном коврике, пальцы):
# пальцы (высветление + LaMa inkback) → фон → SAM 3 1288 px → snap_bg → склейка страниц и уточнение у края (5 мм) →
# страницы: трапеции и класс «плоско / приподнята» → защита контента (блоки surya плоских страниц внутри «не фона») →
# закрас до осевой рамки бумаги pull-push от чистой бумаги у края, защита и copy back surya — поверх закраса →
# TIFF 450 dpi с растяжкой уровней.
# Читает: $PACK6_450_ROOT (Я.Диск, только чтение; скрытые папки .covers/.дубликаты/.replaced пропускаются).
# Пишет: всё на SSD, $PACK6_450_WORK/{output,cache,debug} (другая папка — `PACK6_WORK=... ./run_v2_pack6.sh`;
# кэш прежнего прогона в cache/ можно скопировать заранее — шаги с готовым кэшем не считаются) (итоги — структура подпапок входа; в «Готовое» на Я.Диске —
# после отсмотра). Кадр без пальцев в кэше не хранится (--no-save-fingers). Итоги, оверлеи и строки
# cache/summary.csv появляются по мере обработки кадров. Скрипт можно перезапускать: готовые итоги пропускаются.
#
# Время: ~10–11 с на кадр (замер check3 2026-10-13: упирается в GPU — пальцы, SAM 3 ×2, surya по выпрямленному кадру),
# на весь пак (~2480 видимых кадров) ~7–8 часов.
# Видеопамять: все модели живут весь прогон, пик ~7.4 ГБ выделено (nvidia-smi до 10.5 ГБ с рабочим столом) из 16 ГБ —
# замер 2026-10-12. Числа ключей — в v2_pack6_args.sh.
#
set -euo pipefail

# Пул процессов: при остановке скрипта гасим всю группу (forkserver и воркеры), иначе остаются сироты.
set -m
# Выход: погасить всю группу (воркеры пула), сохранив код выхода; сигналы на время гашения игнорируются,
# иначе свой же TERM снова зовёт ловушку — рекурсия до переполнения стека bash (SIGSEGV, код 139).
trap 'rc=$?; trap - EXIT; trap "" INT TERM; kill -- -$$ 2>/dev/null; exit $rc' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

cd "$(dirname "$0")/../.."
source run_scripts/scan_cropping/common.sh
source run_scripts/scan_cropping/v2_pack6_args.sh

WORK="${PACK6_WORK:-$PACK6_450_WORK}"
JOBS=12  # не 16: CPU-шаги идут параллельно GPU и упираются в чтение с NTFS, 12 воркеров хватает с запасом

mkdir -p "$WORK"
echo "scan_cropping v2: $PACK6_450_ROOT → $WORK/output (кэш и оверлеи: $WORK)"
uv run python -m ocr_utils.scan_cropping.v2 \
    --input-dir "$PACK6_450_ROOT" \
    --output "$WORK/output" \
    --cache "$WORK/cache" \
    --debug "$WORK/debug" \
    "${V2_PACK6_ARGS[@]}" \
    --jobs "$JOBS" \
    --log-level INFO
