#!/usr/bin/env bash
#
# Проверка имён файлов в сканах МТС на то, что порядок страниц может разъехаться между
# Windows и Linux.
#
# ЗАЧЕМ. Порядок страниц задаётся ТОЛЬКО именем файла, а сортировка по имени в двух
# системах разная: проводник Windows сравнивает числовые группы как числа и не различает
# регистр, Linux сравнивает байты. Пока имена в папке однотипные (IMG_0001.jpg …
# IMG_0123.jpg), обе сортировки дают один ряд. Ломается это на «лишних» именах — досканах
# IMG_0124_1.jpg, копиях IMG_0124 (1).jpg, парах, различающихся только регистром, и
# номерах разной разрядности. Такой файл встаёт в ряд по-разному, и разворот уезжает не на
# своё место молча — ошибку видно уже только в собранном PDF.
#
# Отдельно ловится доскан, у которого базовый кадр уже удалён (IMG_0005_1.jpg без
# IMG_0005.jpg): пары в папке нет, но в ряду страниц такой файл всё равно чужой, и в
# нумерации на его месте дыра. Он попадает в класс «редкая схема имени» — тот сравнивает
# имя не с шаблоном, а со схемой, по которой названа вся остальная папка.
#
# ЦЕНА: обход дерева и stat по находкам, без чтения содержимого файлов. По 14 тысячам
# кадров в «в работе» — секунды, даже на медленном NTFS-3G /mnt/dump3.
#
# ЧТО ДЕЛАТЬ С НАХОДКАМИ: переименовать «лишний» файл так, чтобы его место в ряду задавалось
# явно — доскан IMG_0124_1.jpg становится, например, IMG_0124a.jpg (буква сортируется
# одинаково везде) или получает свой номер в общей нумерации папки. Дубли с совпавшим
# размером (в отчёте помечены «совпали») — кандидаты на удаление, но сверьте их глазами:
# совпадение размера у JPEG почти наверняка означает копию, но не гарантирует её.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/МТС/в работе"
BASE_NAME="mts_risky_names"

REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"

echo "find_risky_duplicate_names:"
echo "  input = $INPUT_DIR"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"

ARGS=(
    "$INPUT_DIR"

    # Расширения, по которым идёт обход. Регистр не важен: пары вида x.jpg / x.JPG —
    # один из проверяемых классов, поэтому сравнение внутри скрипта регистронезависимое.
    # В «в работе» лежат только .jpg, но досканы и промежуточные варианты сюда попадают
    # и в tiff, а перепутанный порядок в них так же опасен.
    --ext .jpg .jpeg .tif .tiff

    # CSV со всеми находками — чтобы сверять прогоны между собой после переименований.
    --csv "$REPORT_CSV"
)

# Скрипт возвращает 2, когда что-то нашлось, — иначе прогон из шелла проходил бы молча.
# При set -e это оборвало бы пайплайн до tee, поэтому код возврата снимается отдельно и
# разбирается вручную.
set +e
uv run python scripts/find_risky_duplicate_names.py "${ARGS[@]}" 2>&1 | tee "$REPORT_MD"
STATUS="${PIPESTATUS[0]}"
set -e

case "$STATUS" in
    0) echo "Опасных имён не найдено." ;;
    2) echo "Найдены опасные имена, см. $REPORT_MD" ;;
    *) echo "Ошибка прогона, код $STATUS" >&2 ;;
esac
exit "$STATUS"
