#!/usr/bin/env bash
#
# Сглаживание фона на паке «МТС/Готовое» (584 файла в подпапках по годам/месяцам)
# перед бинаризацией в FineReader: контент под защитной маской остаётся нетронутым,
# всё остальное заменяется нормированным размытием. Подробности — в докстринге
# ocr_utils/background_smoothing/__init__.py.
#
# Формат выхода — TIFF (без потерь; DPI переносится из исходника), цвет как на входе.
# Обложки и растровые вкладки обрабатываются отдельно, здесь цель — текст и line art.
#
# ВНИМАНИЕ: том называется /mnt/SYSTEM ЗАГЛАВНЫМИ; /mnt/system строчными —
# пустая заглушка, принадлежащая root, и не точка монтирования.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/МТС/Готовое"
BASE_DIR="/mnt/SYSTEM/raw/mts/pack1_background_blurring"
OUTPUT_DIR="$BASE_DIR/background_blurred"
DEBUG_DIR="$BASE_DIR/debug"

echo "background_smoothing:"
echo "  input  = $INPUT_DIR"
echo "  output = $OUTPUT_DIR"
echo "  debug  = $DEBUG_DIR"

# Аргументы собраны в массив, а не склеены обратными слэшами: внутри массива
# переносы строк законны, и поэтому можно комментировать каждый аргумент отдельно
# (в цепочке с `\` комментарий разорвал бы команду).
ARGS=(
    # Откуда и куда. Относительные пути входа зеркалятся в выходе и в debug.
    --input-dir "$INPUT_DIR"
    --output-dir "$OUTPUT_DIR"
    # Оверлеи: исходник + полупрозрачные маски (жёлтая — что НЕ размывается,
    # красная — найденный контент). Убрать строку, если оверлеи не нужны.
    --debug-dir "$DEBUG_DIR"

    # Обходить подкаталоги (пак разложен по годам и месяцам). Включено и по
    # умолчанию, оставлено явно ради читаемости.
    --recursive
    # Формат выхода: TIFF+LZW, сжатие без потерь. DPI переносится из исходника —
    # без тега разрешения FineReader принял бы скан 600 dpi за страницу в 96 dpi.
    # Не указывать — формат останется таким же, как у входного файла.
    --output-format tiff
    # Не переделывать то, что уже посчитано: удобно доганивать прерванный прогон.
    --skip-if-exists

    # Как строится первичная маска контента. otsu — глобальный порог по гистограмме;
    # альтернатива sauvola добавляет локальный порог (нужен, если освещение гуляет
    # ВНУТРИ страницы; на этом паке ScanTailor его уже выровнял).
    --method otsu
    # Сдвиг порога от Оцу в сторону бумаги, доля расстояния до неё (0..1).
    # Больше — маска щедрее. 0.5 даёт порог ≈200 при чернилах ≤200 и бумаге ≈252,
    # то есть буквы берутся с запасом, а просвет с оборота (219-250) НЕ затягивается.
    --threshold-bias 0.5

    # Радиус размытия фона = множитель x радиус защитного припуска (≈15 px при
    # 600 dpi), то есть ≈60 px. Больше — сильнее усредняется фон.
    --blur-mult 4.0
    # masked — нормированное размытие: пиксели защитной маски исключены из
    # усреднения, поэтому чернила соседних строк не затягиваются в фон.
    # plain (наивное blur всего кадра) оставлен только для сравнения: он даёт
    # тёмные полосы между строками и делает «перец» ХУЖЕ, чем в исходнике.
    --blur-mode masked

    # Размечать страницу нейросетью Surya и защищать найденные ФОТОГРАФИИ (класс
    # Picture, дополнительно проверенный детектором растра — чертежи под ним не
    # числятся, а сам блок дотягивается до границ настоящего растра: Surya обводит
    # визуальный блок и может срезать край снимка) той же защитной маской и с тем
    # же припуском, что и текст. Без флага
    # страница с фотографией целиком копируется как есть, и «перец» вокруг
    # её текстовых колонок остаётся; с флагом фотография сохраняется побитово, а
    # фон вокруг текста сглаживается. Пороги Оцу и детектор растра считаются при
    # этом по кадру БЕЗ иллюстраций, а детектор остаётся страховкой: если растр
    # нашёлся ЕЩЁ и в остатке (обложка, полосное фото), кадр копируется как есть.
    # Цена — примерно 0.6 с на кадр на GPU плюс разовая загрузка весов Surya.
    --use-surya-layout

    # INFO печатает тайминги каждого шага по каждому кадру; WARNING — только ошибки.
    --log-level INFO
)

uv run python -m ocr_utils.background_smoothing "${ARGS[@]}"
