#!/usr/bin/env bash
#
# Калибровочный прогон детектора просвечивающей бумаги по выпуску «Плановое хозяйство»
# 1931 № 02-03 — тому самому, из которого взяты размеченные кадры
# (tests/ПХ_1931_02_03_кадры_с_просвечивающей_бумагой, 7 разворотов).
#
# ЗАЧЕМ ИМЕННО ЭТОТ ВЫПУСК. Он единственный, где есть внешняя разметка, и он же
# показателен: тонкая бумага идёт в нём двумя непрерывными кусками (кадры 0026–0046 и
# 0146–0155) — так и печатают, тетрадями. Прогон по нему проверяет не только «находит ли
# вообще», но и «не рассыпается ли находка по кадрам вперемешку», чего при настоящем
# дефекте бумаги быть не может.
#
# ЧТО СМОТРЕТЬ В РЕЗУЛЬТАТЕ. Колонка «×порог»: 1.0 — ровно калибровочный порог метрики.
# Все семь размеченных кадров обязаны оказаться выше порога, и четыре из них — в самом
# верху списка. Всего выше порога уходит около 18 % кадров выпуска.
#
set -euo pipefail

cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Плановое хозяйство/пак Сафронова/для нарезки разворотов (300 DPI)/1931/02-03"
BASE_NAME="show_through_ph_1931_02_03"
REPORT_TXT="${BASE_NAME}.txt"
REPORT_MD="${BASE_NAME}.md"
REPORT_CSV="${BASE_NAME}.csv"
LINK_DIR="${BASE_NAME}_worst"

echo "show_through_detection (калибровка):"
echo "  input = $INPUT_DIR"
echo "  txt   = $REPORT_TXT"
echo "  md    = $REPORT_MD"
echo "  csv   = $REPORT_CSV"
echo "  links = $LINK_DIR"

ARGS=(
    "$INPUT_DIR"

    # Основная метрика: доля межстрочий, которая переживёт предварительную бинаризацию.
    # Именно она отвечает на рабочий вопрос «помешает ли просвет», а не «есть ли он»:
    # бледный просвет обработка снимает сама, и в список он попадать не должен.
    --algorithm ghost_ink

    # Порог в ДОЛЯХ от калибровочного (0.010 у ghost_ink). Единица — как откалибровано
    # на паре «1931/02-03 против 1955/03». На незнакомой бумаге имеет смысл сначала
    # посмотреть распределение в CSV.
    --threshold 1.0

    # Показать заведомо больше, чем перешагнуло порог: калибровочный прогон нужен для
    # того, чтобы увидеть и пограничные полосы тоже.
    --worst-count 30

    --txt-report "$REPORT_TXT"
    --md-report "$REPORT_MD"
    --csv "$REPORT_CSV"
    --link-dir "$LINK_DIR"

    # Два ядра остаются системе: прогон по выпуску идёт минуты, по паку — часы.
    --reserve-cores 2
)

uv run python -m ocr_utils.show_through_detection "${ARGS[@]}"
