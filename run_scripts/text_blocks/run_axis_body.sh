# краски против оси по базовой линии глифов, согласованной с соседними строками.
#
# Контрольная выборка — 18 полос пака-1 «только текст» (не меньше 20 длинных строк), отбор по
# curved_lines_pack1.csv (2026-09-27):
#   * кривизна строк (line_fit_sagitta_rel_p90 — 0.40…0.55): 1971/10 IMG_0046_2R, 1973/07 IMG_0041_2R,
#     1976/05 IMG_0101_1L, 1973/08 IMG_0095_2R, 1973/07 IMG_0047_1L, 1971/10 IMG_0050_2R,
#     1966/04 IMG_0046_1L, 1971/09 IMG_0146_1L;
#   * трапеция — наклон строк меняется от верха полосы к низу (|line_fit_slope_grad_y| 5.2…7.0):
#     1969/07 IMG_0037_1L, 1967/10 IMG_0018_1L, 1967/10 IMG_0020_1L, 1971/04 IMG_0047_1L,
#     1976/04 IMG_0050_1L, 1972/04 IMG_0047_1L, 1971/03 IMG_0144_2R, 1966/01 IMG_0049_1L;
#   * пример пользователя (прыжки оси на «1975», «От», «В 1974») 1975/08 IMG_0087_2R и плотный набор
#     1975/05 IMG_0101_2R (с.97).
# Замер 2026-09-27 (медианы по полосам, прежняя → вторая): отклонение середины строчных от оси p90
# 0.121 → 0.063 мм, дрожание оси 0.019 → 0.004 мм, разность наклонов соседних строк на концах p90
# 4.40° → 2.00°, скрещиваний 0 → 0.
#
# Выход: $OUT/measures.csv, $OUT/summary.md, $OUT/картинки/<полоса>_{полоса,вырезка_N}.jpg.
# ~5 с на полосу, весь набор — меньше минуты на 8 воркерах.

set -euo pipefail
