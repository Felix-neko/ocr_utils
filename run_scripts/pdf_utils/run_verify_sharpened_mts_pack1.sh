#!/usr/bin/env bash
#
# Сверка заострённых копий пака-1 с их полосами: та ли картинка лежит под этим именем.
#
# ЗАЧЕМ. Capture One обрабатывает выпуски параллельно, а имена полос в разных выпусках
# ПОВТОРЯЮТСЯ: IMG_0034_1L есть в тридцати выпусках пака-1. Один раз это уже кончилось
# подменой: в 1975/04/IMG_0034_1L.jpg легла полоса из 1968/07.
#
# Размер такую подмену ловит только между выпусками разной геометрии — а пак снимался
# одной серией, и у большинства выпусков размеры совпадают. Поэтому сверка идёт по
# содержимому, двумя мерами сразу: профили «доля тёмного по строке и столбцу» (работают
# на тексте) и корреляция полос 64x64 (работает на фотографии). Решает максимум из двух.
#
# ПОРОГИ ВЫВЕРЕНЫ ПО ВСЕМУ ПАКУ, менять их наугад не надо. Подменённая полоса дала 0.35,
# худшая своя — 0.78, обычная 0.92-0.99; порог 0.6 стоит в провале между ними. Просевшие,
# но свои (обложки, которые Capture One перекрасил, и почти пустые полосы) выводятся
# отдельным списком «глянуть глазами» и прогон не роняют.
#
# ЗАПУСКАТЬ ПЕРЕД СБОРКОЙ ПРОМЕЖУТОЧНЫХ PDF. Подменённая полоса того же размера пройдёт
# сборку молча и обнаружится только глазами в готовом документе.
#
# Прогон читает весь пак — около 450 ГиБ с NVMe — и упирается в декодирование, поэтому
# --jobs 16 по числу физических ядер. TIFF разжимается целиком, JPEG декодируется в 1/8
# прямо из DCT, так что основное время уходит на оригиналы.

set -euo pipefail
source "$(dirname "$0")/../scan_markup/pack1/common.sh"

echo "Оригиналы:   $BLURRED_DIR"
echo "Заострённые: $SHARPENED_DIR"

VERIFY_ARGS=(
    --db "$DB_REVIEWED"
    --pack-name "$PACK_NAME"
    --originals-dir "$BLURRED_DIR"
    --sharpened-dir "$SHARPENED_DIR"
    --jobs 16
    --report-csv "$CLEAN_ROOT/verify_sharpened.csv"
    --log-level INFO
)
uv run python -m ocr_utils.pdf_utils.verify_sharpened "${VERIFY_ARGS[@]}" "$@"
