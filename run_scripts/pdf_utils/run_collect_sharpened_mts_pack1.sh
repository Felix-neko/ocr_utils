#!/usr/bin/env bash
#
# Разбор выгрузки Capture One по паку-1: sharpened-подпапки -> обычное дерево пака.
#
# Capture One складывает обработанные полосы в blurred/{год}/{выпуск}/sharpened, а всему
# остальному конвейеру нужна раскладка {год}/{выпуск}/полоса — такая же, как в «Готовое».
# Скрипт переносит картинки в $SHARPENED_DIR и убирает опустевшие подпапки.
#
# ПЕРЕНОС, А НЕ КОПИРОВАНИЕ, и это важно для места: заострённая копия пака весит около
# 144 ГиБ (12 135 полос по ~11.8 МиБ), и второй такой набор на том же томе лишний.
# Источник и приёмник — на одной файловой системе, поэтому перенос это мгновенный rename.
#
# ЗАПУСКАТЬ МОЖНО, НЕ ДОЖИДАЯСЬ КОНЦА ВЫГРУЗКИ. Файл моложе --min-age-minutes считается
# ещё пишущимся и не трогается вовсе, а выпуск переносится только целиком, поэтому
# половина выпуска на выход не попадёт. Недобранное забирается повторным запуском.

set -euo pipefail
source "$(dirname "$0")/../scan_markup/pack1/common.sh"

echo "Выгрузка: $BLURRED_DIR/*/*/sharpened"
echo "Выход:    $SHARPENED_DIR"

COLLECT_ARGS=(
    "$BLURRED_DIR"
    "$SHARPENED_DIR"
    --db "$DB_REVIEWED"
    --pack-name "$PACK_NAME"
    # Десять минут — с запасом: одна полоса 3830x5892 выгружается за десятки секунд.
    --min-age-minutes 10
    --require-complete
    --log-level INFO
)
uv run python -m ocr_utils.pdf_utils.collect_sharpened "${COLLECT_ARGS[@]}" "$@"
