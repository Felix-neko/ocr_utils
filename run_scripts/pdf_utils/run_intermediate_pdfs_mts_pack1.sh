#!/usr/bin/env bash
#
# Промежуточные PDF пака-1 под пакетное распознание в FineReader.
#
# По каждому из 123 выпусков собираются две PDF: полная (все полосы) и
# PAGES_WITH_PICS_ONLY (только полосы с размеченными иллюстрациями). В FineReader их
# гоняют по-разному: полную — с бинаризацией И распрямлением строк, вторую — с
# бинаризацией, но БЕЗ распрямления, чтобы геометрия страницы осталась прежней и
# иллюстрации потом легли ровно на свои места.
#
# ПОЛЯ. Полной PDF они добавляются, PAGES_WITH_PICS_ONLY — нет, и это ровно то же самое
# различие: распрямляя строки, FineReader увеличивает кадр, но MediaBox оставляет прежним
# и сажает кадр в левый нижний угол, так что вылезшее вправо и вверх обрезается краем
# страницы. По прошлому прогону это 38 % полос, обычно 2-3 мм вправо и 6 мм вверх, в
# худшем случае 12,7 мм, и режет оно концы строк, а не поля. Полосы, которую не
# распрямляют, это не касается, а лишние поля там сдвинули бы иллюстрации.
#
# ОСТОРОЖНО С МЕСТОМ. Байты заострённых копий переезжают в PDF как есть, поэтому полные
# PDF весят примерно столько же, сколько сама выгрузка Capture One, — около 144 ГиБ.
# Поля этого почти не меняют: заливка сплошная и жмётся в ничто, замер на реальных полосах
# дал +1 % байтов. А вот пикселей в полной PDF становится на 27 % больше, и на столько же
# дольше идёт распознание в FineReader — примерно +6 часов на пак в двух вариантах.
# Плюс PAGES_WITH_PICS_ONLY: полос с иллюстрациями 544 из 12 135, это ещё единицы ГиБ.
# После сборки сами заострённые JPEG становятся избыточны — их содержимое лежит внутри
# PDF, — и $SHARPENED_DIR можно снести, освободив те же 144 ГиБ.
#
# ПАМЯТЬ. Выпуск целиком держится в памяти до записи: сотня полос по 12 МиБ — порядка
# полутора гигабайт на воркер, при --jobs 8 до двадцати гигабайт. Если памяти меньше,
# убавлять --jobs.

set -euo pipefail
source "$(dirname "$0")/../scan_markup/pack1/common.sh"

# Колонки полей в таблице выпусков появились вместе с --page-margin-*-mm, и в базе,
# заполненной до них, их нет. Само по себе открытие базы их не допишет: сборщик читает план
# с create=False, а add_missing_columns работает только при create=True — на старой базе
# прогон падает на SELECT ещё до всякой записи, потратив время на чтение плана.
#
# Проверяем, но не мигрируем сами: миграция — это шаг 8, и он ходит по ВСЕМ четырём файлам
# базы, включая .bak. Незамигрированный бэкап не падает сразу, он падает в тот момент, когда
# понадобился, — и чинить это надо там, а не тут.
uv run python - "$DB_REVIEWED" <<'PYTHON'
import sqlite3
import sys

columns = {row[1] for row in sqlite3.connect(sys.argv[1]).execute("PRAGMA table_info(issues)")}
if "full_intermediate_pdf_margin_left_mm" not in columns:
    sys.exit(
        "В базе нет колонок полей промежуточных PDF. Сначала выполнить:\n"
        "    run_scripts/scan_markup/pack1/run_8_migrate_db.sh"
    )
PYTHON

echo "Оригиналы:  $BLURRED_DIR"
echo "Заострённые: $SHARPENED_DIR"
echo "Выход:      $FULL_PDF_DIR"
echo "            $PICS_ONLY_PDF_DIR"
df -h /mnt/system | tail -1

PDF_ARGS=(
    --db "$DB_REVIEWED"
    --pack-name "$PACK_NAME"
    --originals-dir "$BLURRED_DIR"
    --sharpened-dir "$SHARPENED_DIR"
    --full-pdf-dir "$FULL_PDF_DIR"
    --pics-only-pdf-dir "$PICS_ONLY_PDF_DIR"

    # Проба одним годом — вернуть строку, если что-то менялось и нужен быстрый круг
    # (6 выпусков, ~600 полос). Для полного пака она должна оставаться закомментированной.
    # --only-year 1966

    # Качество врезанных иллюстраций. Выше, чем 75 в финальной PDF, намеренно: этот файл —
    # полуфабрикат, из него ничего не пересобирается, а глазами по нему проверяют, на месте
    # ли картинки, и артефакты сжатия тут только мешают смотреть.
    --picture-quality 90

    # Поля ПОЛНОЙ PDF под рост кадра при распрямлении строк. Замер вылета по 6951 полосе
    # прошлого прогона: вправо p95 = 5,3 мм и p99 = 8,4 мм, вверх p95 = 7,5 мм и p99 = 9,4
    # мм. Отсюда 12 и 6: горизонталь закрыта с запасом, вертикаль — по p90.
    #
    # Если после этого прогона верх всё ещё будет резать (проверяется тем же замером
    # вылета по готовым бинарным PDF), поднимать НЕ горизонталь, а --page-margin-y-mm
    # до 10: прирост по вертикали у FineReader почти постоянный, 6-9 мм.
    --page-margin-x-mm 12
    --page-margin-y-mm 6

    # Поля не перекодируют полосу: DCT-блоки переносятся в залитую подложку через jpegtran.
    # Если он вдруг не справится, прогон честно упадёт на этом выпуске, а не подменит
    # заострённую копию пересжатой втихую. Разрешить пересжатие — --allow-jpeg-recode.

#    --skip-if-exists
    --jobs 8
    --log-level INFO
)
uv run python -m ocr_utils.pdf_utils.intermediate_pdfs "${PDF_ARGS[@]}" "$@"
