#!/usr/bin/env bash
#
# Экспорт страниц журнала «Плановое хозяйство» (пак Сафронова, переименованное)
# из PDF в картинки с полями под нарезку разворотов.
#
# Вокруг каждой страницы добавляется поле в 64 px, залитое цветом бумаги этой самой
# страницы, осветлённым на 10 тонов из 256. Все страницы пака — одиночные JPEG с
# субдискретизацией 4:2:0 (MCU 16x16), а 64 кратно 16, поэтому поля добавляются на
# уровне DCT-блоков: картинка не перекодируется и новых артефактов сжатия не получает.
#
# Всем файлам проставляется тег разрешения 300 DPI. Это именно тег: количество пикселей
# от него не меняется, картинка не масштабируется.
#
# PDF разбираются параллельно — по числу ядер, но не больше 16 процессов.
#
# После экспорта выбрасываются номера, отсканированные не в 300 DPI (см. список ниже
# и planhoz_pack_1_dpi_report.md): с ними пока возиться не хочется, а тег 300 DPI на
# них был бы неправдой. Проще выкинуть их папки, чем городить исключения в экспорте.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, а пути внутри отсчитываются от корня
# репозитория — поднимаемся на два уровня.
cd "$(dirname "$0")/../.."

INPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Плановое хозяйство/пак Сафронова/переименованное"
OUTPUT_DIR="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/Плановое хозяйство/пак Сафронова/для нарезки разворотов (с полями) (300 DPI)"

PADDING=64
BRIGHTEN=10
DPI=300

# Номера, у которых в исходном PDF картинки не на 300 DPI: «папка|фактический DPI».
# Список посчитан scripts/dpi_fast.py + scripts/dpi_report.py по всему паку.
SKIP_ISSUES=(
  "1938/05|150 DPI"
  "1938/09|150 DPI"
  "1959/01|200 DPI"
  "1959/02|200 DPI"
  "1959/03|200 DPI"
  "1959/04|200 DPI"
  "1959/05|200 DPI"
  "1959/06|200 DPI"
  "1959/07|200 DPI"
  "1959/08|200 DPI"
  "1959/09|200 DPI"
  "1959/10|200 DPI"
  "1959/11|200 DPI"
  "1959/12|200 DPI"
  "1960/01|200 DPI"
  "1960/02|200 DPI"
  "1960/03|200 DPI"
  "1960/04|200 DPI"
  "1960/05|200 DPI"
  "1960/06|200 DPI"
  "1960/07|200 DPI"
  "1960/08|200 DPI"
  "1960/09|200 DPI"
  "1960/10|200 DPI"
  "1960/11|200 DPI"
  "1960/12|200 DPI"
  "1965/10|400 DPI"
  "1965/11|400 DPI"
  "1965/12|400 DPI"
  "1966/01|400 DPI"
  "1966/02|400 DPI"
  "1966/03|400 DPI"
  "1973/01|плавающий 280-430 DPI"
  "1973/02|плавающий 260-430 DPI"
)

# Номера, сохранённые в своё время через Photoshop: сегмента JFIF в них нет, а все три
# таблицы квантования упакованы в один сегмент DQT (у остальных — по одной в двух).
# Картинки нормальные, 300 DPI, экспортируются беспотерьно, — но раскладка нетипичная,
# и именно на ней раньше ломалась проверка совместимости подложки. Держим список под
# рукой: если в этих номерах что-то пойдёт не так, причину стоит искать здесь.
PHOTOSHOP_ISSUES=(
  "1963/02"
  "1964/05"
  "1965/05"
  "1967/03"
  "1967/04"
  "1968/01"
  "1968/07"
  "1968/08"
  "1968/09"
  "1969/10"
  "1970/05"
  "1970/10"
)

echo "extract_images:"
echo "  input    = $INPUT_DIR"
echo "  output   = $OUTPUT_DIR"
echo "  padding  = $PADDING px"
echo "  brighten = $BRIGHTEN/256"
echo "  dpi      = $DPI"

mkdir -p "$OUTPUT_DIR"

uv run python -m ocr_utils.pdf_utils \
  "$INPUT_DIR" \
  "$OUTPUT_DIR" \
  --padding "$PADDING" \
  --brighten "$BRIGHTEN" \
  --dpi "$DPI"

echo
echo "============================================================"
echo "Выбрасываем номера, отсканированные не в 300 DPI:"

removed=0
missing=0
for entry in "${SKIP_ISSUES[@]}"; do
  issue="${entry%%|*}"
  reason="${entry#*|}"
  dir="$OUTPUT_DIR/$issue"
  # Причину печатаем последней: в ней кириллица, а printf выравнивает по байтам,
  # так что выровненное поле переменной ширины поехало бы.
  if [[ -d "$dir" ]]; then
    pages=$(find "$dir" -maxdepth 1 -type f | wc -l)
    rm -rf "$dir"
    printf '  удалено   %-10s страниц: %-4s — %s\n' "$issue" "$pages" "$reason"
    removed=$((removed + 1))
  else
    printf '  нет папки %-10s               — %s (уже удалено или не экспортировалось)\n' "$issue" "$reason"
    missing=$((missing + 1))
  fi
done

# Год мог остаться пустым — например, 1959 и 1960 выброшены целиком.
find "$OUTPUT_DIR" -mindepth 1 -type d -empty -delete

echo
echo "Удалено папок: $removed из ${#SKIP_ISSUES[@]} (не найдено: $missing)."
echo "Эти номера в работу не идут; почему — см. planhoz_pack_1_dpi_report.md."

echo
echo "============================================================"
echo "ВНИМАНИЕ: номера, сохранённые через Photoshop (${#PHOTOSHOP_ISSUES[@]} шт., по 50 страниц):"
echo
printf '  %s\n' "${PHOTOSHOP_ISSUES[@]}" | paste -sd' ' -
echo
echo "  Эти номера не удаляются и экспортируются наравне с остальными: разрешение у них"
echo "  честные 300 DPI, поля добавляются беспотерьно."
echo
echo "  Но раскладка JPEG у них нетипичная — нет сегмента JFIF, все три таблицы"
echo "  квантования в одном сегменте DQT. До правки от 2026-08-27 проверка совместимости"
echo "  подложки на этом спотыкалась, и картинка пересжималась ЦЕЛИКОМ вместо"
echo "  беспотерьной вставки полей — с предупреждением «Перекодирование всей картинки»."
echo
echo "  Если папки этих номеров остались от прогона более старой версией кода, в них"
echo "  лежат страницы с лишним поколением JPEG. Удалите их и прогоните экспорт заново:"
echo
for issue in "${PHOTOSHOP_ISSUES[@]}"; do
  echo "    rm -rf \"\$OUTPUT_DIR/$issue\""
done
echo
echo "  Проверить, что перекодирования больше нет, проще всего по логу: строк"
echo "  «Перекодирование всей картинки» в выводе выше быть не должно ни одной."
