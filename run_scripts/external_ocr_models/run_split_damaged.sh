#!/usr/bin/env bash
#
# Нарезка сырых фото-разворотов мини-набора повреждённых сканов на страницы по прямой
# сгиба. ВХОД — research/external_ocr_models/damaged/сырые сканы/<тип проблемы>/*.jpg,
# ВЫХОД — …/damaged/нарезанное по страницам/<тип проблемы>/<кадр>_L|_R.jpg и контрольные
# картинки с линией в …/_линии. Обе страницы сохраняются только для раздела «часть букв
# в словах совсем закрыта корешком», в остальных — левая. Секунды на кадр.
set -euo pipefail
cd "$(dirname "$0")/../.."

DAMAGED="research/external_ocr_models/damaged"

# Линии сгиба заданы руками (x сверху, x снизу в пикселях исходника), промерены по кропам
# полного разрешения. Автоподгонка (fit_fold из gutter_loss_detection) на этих кадрах
# промахивается на трёх из восьми: двухколонные страницы, и минимум профиля краски
# попадает в межколонный промежуток (IMG_0053, IMG_0067, IMG_0068) или в пустую колонку
# рядом со сгибом (IMG_0006); на остальных её линия отличается от промеренной на 2-35 px.
FOLDS=(
    --fold 0070.jpg=2681,2624
    --fold IMG_0006.jpg=2233,2251
    --fold IMG_0008.jpg=2220,2245
    --fold IMG_0046.jpg=2465,2490
    --fold IMG_0051.jpg=2563,2550
    --fold IMG_0053.jpg=2613,2537
    --fold IMG_0067.jpg=2436,2422
    --fold IMG_0068.jpg=2447,2438
    --fold IMG_0648.jpg=2836,2748
)
uv run python -m research.external_ocr_models split-spreads \
    --in-dir "$DAMAGED/сырые сканы" \
    --out-dir "$DAMAGED/нарезанное по страницам" \
    "${FOLDS[@]}" \
    "$@"
