#!/usr/bin/env bash
#
# Шаг 1: детекция по оригиналам -> SQLite: растр (цветной / серый), обложки, таблицы и блок-схемы, line art,
# повёрнутый текст, ориентация полосы; затем оглавления (scan_markup toc).
#
# Сначала — run_0_prefill_deepseek.sh: блоки image DeepSeek-OCR-2 идут в line art затравками (--deepseek-cache).
#
# Читает: $PACK_DIR (297 полос, ~3 ГБ с NTFS-3G), кэши surya ($LAYOUT_CACHE_DIR) и DeepSeek ($DEEPSEEK_CACHE_DIR).
# Пишет:  $DB, оверлеи $DEBUG_DIR, кэш surya варианта scan (полоса без файла считается, ~1 с GPU, и дописывается).
# Время:  по паку-2 (597 полос) — ~10 мин с пустым кэшем surya; здесь вдвое меньше. Нужен GPU (surya в родителе,
#         воркеры читают файлы и считают пиксельное). Идемпотентен: --skip-detected продолжает прерванный прогон и
#         после подъёма версий детекторов пересчитывает только устаревшие семейства.
#
# ПОРОГИ — УМОЛЧАНИЯ КОДА (откалиброваны на паке-1, тот же журнал). Все размеры в коде заданы в мм и переводятся
# в пиксели по dpi полосы (тег 450, см. common.sh про ~425), поэтому пересчитывать нечего. Но пак-1 — это 300 dpi с
# апскейлом, а здесь настоящие 450 dpi: полутона и штрих резче. Если оверлеи или CVAT покажут системный дефект
# растра, крутить пороги по выборке глазами по поясам score, а не по полному прогону (docs/data_layout.md).
#
# Проба перед полным прогоном — один выпуск: `run_1_detect.sh --only-issue 07` (99 полос).

set -euo pipefail
# Выход: погасить всю группу (воркеры пула), сохранив код выхода; сигналы на время гашения игнорируются,
# иначе свой же TERM снова зовёт ловушку — рекурсия до переполнения стека bash (SIGSEGV, код 139).
trap 'rc=$?; trap - EXIT; trap "" INT TERM; kill -- -$$ 2>/dev/null || true; exit $rc' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
source "$(dirname "$0")/common.sh"
JOBS="${JOBS:-16}"
echo "Оверлеи:  $DEBUG_DIR"

DETECT_ARGS=(
    --pack-dir "$PACK_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"
    # Оверлеи с подписями kind/разброс/доля точек: по ним и разбирается, что пошло не так.
    --debug-dir "$DEBUG_DIR"
    # Продолжение прерванного прогона и обновление пака: перечитываются только полосы, у которых разошлись
    # размер и время правки ИЛИ версия детектора.
    --skip-detected
    --jobs "$JOBS"
    # Кэш разметки surya: есть файл — модель не зовётся; нет или битый — разбирается и пишется.
    --layout-cache "$LAYOUT_CACHE_DIR"
    # Кэш разбора DeepSeek-OCR-2 (run_0): блоки image — затравки line art. Полоса без записи идёт без них.
    --deepseek-cache "$DEEPSEEK_CACHE_DIR"
    # Ориентация полосы — этим же прогоном. 180 не входит: на паке-1 все боковые полосы требовали поворота по
    # часовой, вверх ногами не оказалось ни одной.
    --angles 0,90,270
    # ocr_vote — арбитр (читает полосу на каждом повороте, дорог) — вторым проходом только по кандидатам.
    --orientation-detectors ink_axis,osd,surya_lines,ocr_vote
    # Первая полоса выпуска — обложка: одна цветная область во весь кадр (проверено глазами на 07, 08, 09).
    --first-page-is-cover
    # Один выпуск — для пробы перед полным прогоном.
    # --only-issue 07
    # Не верить stat вообще: пересчитать хеш каждой полосы (перечитывание всего пака).
    # --rehash-all
)
# Аргументы скрипта дописываются в конец: click берёт последнее вхождение опции, поэтому любую из перечисленных
# выше можно переопределить на месте, не правя файл.
uv run python -m ocr_utils.scan_markup detect "${DETECT_ARGS[@]}" "$@"

# ОГЛАВЛЕНИЯ (scan_markup.toc) — отдельной командой ПОСЛЕ detect: дерево выпусков берётся из базы, меряется только
# окно (первые 5 и последние 12 полос выпуска) — метка surya из того же кэша плюс tesseract. Нужно шагу 2: из
# is_toc / is_year_index ставятся теги «Оглавление» / «Годовой указатель». Выпуск без «Содержания» — красный флаг
# (у всех трёх оно на третьей полосе). "$@" сюда не передаётся: у toc другой набор опций.
TOC_ARGS=(
    --pack-dir "$PACK_DIR"
    --db "$DB"
    --pack-name "$PACK_NAME"
    --layout-cache "$LAYOUT_CACHE_DIR"
    --jobs "$JOBS"
    --skip-detected
)
uv run python -m ocr_utils.scan_markup toc "${TOC_ARGS[@]}"
