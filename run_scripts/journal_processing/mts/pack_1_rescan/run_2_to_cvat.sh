#!/usr/bin/env bash
#
# Шаг 2: уменьшенные копии полос в share + проект «досканы-1», задача 1970 и джобы-выпуски (07, 08, 09) CVAT
# с предразметкой.
#
# Требует поднятого CVAT (docker/up.sh) и того, чтобы SHARE_ROOT лежал внутри IMAGES_DIR из docker/.env: задачи
# заводятся из смонтированного share, по сети файлы не передаются. Превью — в $SHARE_ROOT/досканы-1/1970/{выпуск}/,
# делитель round(450/75) = 6 (тот же физический масштаб, что 8 при 600 dpi у паков 1-2).
#
# Читает оригиналы второй и последний раз (297 полос, ~2 мин в 16 процессов). Идемпотентен: готовые копии
# пропускаются, существующие задачи не пересоздаются.
#
# Метки проекта — ВСЕ (LABELS из scan_markup.cvat.project). Предразметка прямоугольниками — как у пака-2: растр
# (цветной и серый — разные метки), таблицы, line art включая блок-схемы; плюс теги поворота и оглавления.
# Повёрнутый текст и подозрения на печать в базе есть, но в предразметку не идут — решение пользователя по паку-2.

set -euo pipefail
set -m
# Выход: погасить всю группу (воркеры пула), сохранив код выхода; сигналы на время гашения игнорируются,
# иначе свой же TERM снова зовёт ловушку — рекурсия до переполнения стека bash (SIGSEGV, код 139).
trap 'rc=$?; trap - EXIT; trap "" INT TERM; kill -- -$$ 2>/dev/null || true; exit $rc' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
source "$(dirname "$0")/common.sh"
# Уменьшение упирается в CPU (декодирование LZW-TIFF), а не в диск — замер пака-2 2026-09-21.
JOBS="${JOBS:-16}"
echo "Share:    $SHARE_ROOT"

TO_CVAT_ARGS=(
    --db "$DB"
    --pack-name "$PACK_NAME"
    --share-root "$SHARE_ROOT"
    --jobs "$JOBS"
    # Назначить джобы разметчику: роль worker видит только назначенное лично.
    --annotator user
    # Виды прямоугольников первичной предразметки (см. шапку). Метки проекта это не сужает.
    --kinds color,grayscale,table,line_art_schema
    # Картинки уже готовы прошлым прогоном.
    # --skip-images
    # ОСТОРОЖНО: заливка заменяет разметку задачи целиком, то есть затирает ручную правку.
    # --force-annotations
    # Когда в задаче уже есть ручная правка, новые находки детекторов — только дозаливкой (PATCH):
    # --append-kinds table,line_art_schema
    # --append-tags
)
uv run python -m ocr_utils.scan_markup to-cvat "${TO_CVAT_ARGS[@]}" "$@"
