#!/usr/bin/env bash
#
# Снятие зонального смаза с разворота МТС пак-1, 1974/05, IMG_0059.
#
# У этого скана левая страница смазана, правая резкая: измеренная относительная
# сигма падает с 0.81 px у левого края до 0.22 у правого, а направление смаза
# плавно поворачивается с 54° до 3° — камера при съёмке повернулась.
#
# Результат прогона (сигма относительно резкой половины ОРИГИНАЛА):
#
#     зона            было    стало
#     левый край      0.81     0.19
#     лев. середина   0.69     0.00
#     лев. внутр.     0.66     0.15
#     правая          0.22     0.13
#
# Метод и грабли — в ocr_utils/zonal_deblur/README.md.
#
set -euo pipefail

# Скрипт лежит в run_scripts/<подсистема>/, пути отсчитываются от корня репозитория.
cd "$(dirname "$0")/../.."

SRC="/mnt/dump3/yandex_disk_linux_baby_zergling/Общее/Фотки/МТС/нарезка сканов/пак-1 (1966-1976)/cropped/1974/05/IMG_0059.tiff"
DST="${SRC%.tiff}_deblur.tiff"

echo "zonal_deblur:"
echo "  in  = $SRC"
echo "  out = $DST"

ARGS=(
    "$SRC"
    -o "$DST"

    # Сетку не задаём: по размеру кадра 3843x2927 выходит 4x6, а перебор показал,
    # что это и есть лучший вариант (остаточный смаз 0.19 против 0.26-0.28 у 3x6,
    # 4x5 и 5x6). Мельче сетка — меньше окон в ячейке и шумнее оценка.

    # Шум/сигнал для Винера. 0.01 — щадящее значение: зерно бумаги на этом скане
    # не поднимается. Уменьшать до 0.003 есть смысл, только если смаз сильнее и
    # готовы мириться с зерном.
    --nsr 0.01
)

uv run python -m ocr_utils.zonal_deblur "${ARGS[@]}"

# Проверка: тот же оценщик по готовому файлу. Разброс sigma_max по ячейкам должен
# заметно сжаться. Абсолютные числа с прогоном выше не сравнивать — эталон
# пересчитывается по обработанному кадру и сам уезжает.
echo
echo "=== контроль по результату ==="
uv run python -m ocr_utils.zonal_deblur "$DST" --dry-run
