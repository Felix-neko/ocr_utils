def collect_detector_pages(folders: "list[Path]", pages_csv: "Path | None" = None) -> list[DetectorPageLabel]:
    """Собрать разметку из папок, по которым человек разложил оверлеи.

    Имя картинки — то же, что делает ``check.image_name``: ``{выпуск}_с{страница:03d}_{скан}.jpg``,
    причём «с» здесь КИРИЛЛИЧЕСКАЯ. Разбор поэтому однозначен: латинских букв в выпуске и в
    номере страницы не бывает, а основа имени скана имеет одну из двух известных форм. Путь до
    скана собирается из имени: ``{год}/{выпуск}/{основа}.jpg`` — именно так лежат заострённые
    копии. Брать его из ``страницы.csv`` нельзя: призрачный оверлей (см. ``баннер_призрак``) в
    CSV последнего прогона не значится, а в разметке он нужен.

    Человек дописывает к имени пометку через « - » («… - а тут ещё и граница прошла по буквам»);
    она попадает в ``note``. Папки обходятся в поданном порядке, и при двух диагнозах на одну
    полосу побеждает ПОСЛЕДНИЙ — так более поздняя раскладка уточняет раннюю, а обе остаются
    видны в ``note``.
    """
    del pages_csv  # оставлен в сигнатуре ради старых вызовов; путь теперь берётся из имени
    collected: dict[tuple[str, int], DetectorPageLabel] = {}
    for folder in folders:
        code = DIAGNOSIS_CODES.get(folder.name)
        if code is None:
            raise KeyError(f"папка {folder.name!r} не описана в DIAGNOSIS_CODES — добавьте код или переименуйте")
        for image in sorted(folder.glob("*.jpg")):
            issue, page, scan, remark = _parse_image_name(image.name)
            expect, note = OVERRIDES.get((issue, page), (EXPECT[code], ""))
            if remark:
                note = f"{note}; {remark}" if note else remark
            earlier = collected.get((issue, page))
            if earlier is not None and earlier.diagnosis != code:
                note = f"{note}; раньше: {earlier.diagnosis}" if note else f"раньше: {earlier.diagnosis}"
            collected[(issue, page)] = DetectorPageLabel(
                scan_rel_path=scan,
                issue=issue,
                page=page,
                diagnosis=code,
                severity=SEVERITY[code],
                expect=expect,
                note=note,
            )
    return sorted(collected.values(), key=lambda label: label.key)


_IMAGE_NAME = re.compile(r"^(\d{4})_(\d{2})_с(\d{3})_(IMG_\d{4}(?:_[12][LR])?|\d{4}(?:_[12][LR])?)(.*?)(?:\.jpg)?$")


def _parse_image_name(name: str) -> tuple[str, int, str, str]:
    """``1966_01_с028_IMG_0017_2R.jpg`` → ``("1966_01", 28, "1966/01/IMG_0017_2R.jpg", "")``.

    Четвёртое значение — пометка человека после « - », если он дописал её к имени.
    """
    match = _IMAGE_NAME.match(name)
    if match is None:
        raise ValueError(f"{name}: имя не разбирается как {{выпуск}}_с{{страница}}_{{скан}}.jpg")
    year, month, page, stem, tail = match.groups()
    remark = tail.split(" - ", 1)[1].strip() if " - " in tail else ""
    remark = remark[: -len(".jpg")] if remark.endswith(".jpg") else remark
    return f"{year}_{month}", int(page), f"{year}/{month}/{stem}.jpg", remark


def cells_by_crop(labels: list[CellLabel]) -> dict[str, dict[tuple[int, int], bool]]:
    grouped: dict[str, dict[tuple[int, int], bool]] = {}
    for label in labels:
        grouped.setdefault(label.crop_id, {})[label.key] = label.rotated
    return grouped


def texts_by_crop(labels: list[TextLabel]) -> dict[str, dict[tuple[int, int], str]]:
    grouped: dict[str, dict[tuple[int, int], str]] = {}
    for label in labels:
        grouped.setdefault(label.crop_id, {})[label.key] = label.text
    return grouped


def _read(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8", newline="") as handle:
        return [row for row in csv.DictReader(handle) if row.get("crop_id") or row.get("scan_rel_path")]
