@dataclass(frozen=True)
class DetectorPageLabel:
    """Диагноз человека по ОДНОЙ ПОЛОСЕ, а не по одной находке.

    Зернистость именно такая, потому что человек раскладывал по папкам оверлеи ПОЛОС: на
    картинке обведены все принятые находки сразу. У 92 полос из 105 находка ровно одна, у
    тринадцати их две-три (это классы ``есть_ещё_таблицы`` и ``не_оценил``). Поэтому меры
    считаются на уровне полосы, а там, где нужна одна рамка, берётся объединение принятых —
    другого честного способа связать диагноз с конкретной находкой у нас нет.
    """

    scan_rel_path: str
    issue: str
    page: int
    diagnosis: str
    severity: str
    expect: str  # "таблица" | "нет" | "" (не знаем)
    note: str = ""

    @property
    def key(self) -> tuple[str, int]:
        return (self.issue, self.page)


@dataclass(frozen=True)
class CellLabel:
    crop_id: str
    row: int
    col: int
    rotated: bool
    note: str = ""

    @property
    def key(self) -> tuple[int, int]:
        return (self.row, self.col)


@dataclass(frozen=True)
class TextLabel:
    crop_id: str
    row: int
    col: int
    text: str

    @property
    def key(self) -> tuple[int, int]:
        return (self.row, self.col)


def load_tables(path: "Path | None" = None) -> list[TableLabel]:
    rows = _read(path or LABELS_DIR / "tables.csv")
    return [
        TableLabel(
            row["scan_rel_path"], Box(*(int(row[name]) for name in ("x0", "y0", "x1", "y1"))), row.get("note", "")
        )
        for row in rows
    ]


def load_detector(path: "Path | None" = None) -> list[DetectorLabel]:
    """Находки с вердиктом человека. На них калибровалась ``detection.verify``.

    Номер страницы в этом файле необязателен: часть строк размечалась прямо по пути скана,
    и номер там пустой. Он и не нужен — рамка задана в координатах скана, а не страницы.
    """
    rows = _read(path or LABELS_DIR / "detector.csv")
    return [
        DetectorLabel(
            row["scan_rel_path"],
            int(row["page"]) if row.get("page", "").strip() else 0,
            Box(*(int(row[name]) for name in ("x0", "y0", "x1", "y1"))),
            int(row["dpi"]),
            row["verdict"].strip() == "таблица",
            row.get("note", ""),
        )
        for row in rows
    ]


def load_detector_pages(path: "Path | None" = None) -> list[DetectorPageLabel]:
    """Диагнозы по полосам. Про зернительность — см. докстринг :class:`DetectorPageLabel`."""
    rows = _read(path or LABELS_DIR / "detector_pages.csv")
    return [
        DetectorPageLabel(
            row["scan_rel_path"],
            row["issue"],
            int(row["page"]),
            row["diagnosis"],
            row["severity"],
            row["expect"],
            row.get("note", ""),
        )
        for row in rows
    ]


def load_cells(path: "Path | None" = None) -> list[CellLabel]:
    rows = _read(path or LABELS_DIR / "cells.csv")
    return [
        CellLabel(
            row["crop_id"],
            int(row["row"]),
            int(row["col"]),
            row["rotated"].strip() in ("1", "да", "true"),
            row.get("note", ""),
        )
        for row in rows
    ]


def load_texts(path: "Path | None" = None) -> list[TextLabel]:
    rows = _read(path or LABELS_DIR / "cell_text.csv")
    return [TextLabel(row["crop_id"], int(row["row"]), int(row["col"]), row["text"]) for row in rows]


