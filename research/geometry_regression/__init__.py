"""Страницы, на которых коррекция геометрии FineReader сделала хуже, чем было.

ЗАЧЕМ. Полные PDF пака-1 сделаны в FineReader дважды: с коррекцией геометрии («исправлять
перекос», «искажение строк», «трапецию») и без неё. Коррекция чаще помогает — выпрямляет
прогиб у корешка и перекос, — но на части страниц (по оценке пользователя меньше 10 %) она
портит то, чего не видит её модель «страница — это строки текста»: наклоняет вертикальные
линейки таблиц и рамки, гнёт прямые на чертежах и блок-схемах, косит крупные заголовки и
дробные черты формул, заставляет разрядку прыгать внутри строки. При сборке финального PDF
такие страницы надо брать из прогона БЕЗ коррекции, и для этого нужен список.

ЧТО ДЕЛАЕМ. Рендерим одну и ту же страницу из обоих PDF и сравниваем ПОПАРНО, без эталона:
по полю смещений «без → с коррекцией» (что FineReader сделал со страницей), по линейкам и
длинным штрихам (наклон от оси, прямизна), по строкам текста (наклон и волнистость каждой
строки), по кромкам колонок. Каждая метрика — разность «стало − было» в шкале «больше —
хуже»; порог на разность калибруется по распределению на паке. На находки — картинки
«было | стало» с сеткой, по годам, для проверки глазами.

ГРАНИЦА ЗАДАЧИ. Подмена страниц в финальном PDF — отдельный шаг в ``ocr_utils.pdf_utils``.
Здесь только детектор, его метрики, калибровка и просмотр. Текстовые строки FineReader
выправляет и на «плохих» страницах, поэтому улучшение текста мерится лишь для контекста,
а решение принимают нетекстовые метрики.
"""

# Версия алгоритма: входит в кэш измерений, старые JSON при смене не подхватываются.
VERSION = 10

# Рабочее разрешение всех измерений по умолчанию. 150 dpi: пак-1 при 600 dpi — это 1/4,
# страница ~1000×1600. Все размеры в коде заданы в миллиметрах бумаги и переводятся в
# пиксели через ``mm_to_px`` от ФАКТИЧЕСКОГО dpi рендера — при смене разрешения ничего не плывёт.
WORK_DPI = 150

MM_PER_INCH = 25.4


def mm_to_px(mm: float, dpi: float) -> int:
    """Миллиметры бумаги → целые пиксели при данном dpi (не меньше 1)."""
    return max(1, int(round(mm * dpi / MM_PER_INCH)))


def px_to_mm(px: float, dpi: float) -> float:
    return px * MM_PER_INCH / dpi
