#!/bin/sh
# Счёт распознаваемости превью кадра в четырёх поворотах — основа решения «куда повернуть RAF».
#
# Вход: путь к JPEG-превью (вынутому из RAF `exiftool -b -PreviewImage`).
# Выход: одна строка «<файл> s0 s90 s180 s270», где sN — число уверенно распознанных слов
# (уверенность tesseract > 60, длина >= 4 букв) после поворота на N градусов ПО ЧАСОВОЙ
# (так поворачивает ImageMagick `-rotate N`). Счёт суммируется по трём квадратам 1400x1400:
# центр кадра и сдвиги на 900 px влево и вправо (на развороте/полосе с иллюстрацией в центре
# хотя бы один квадрат попадёт на текст).
#
# Почему --psm 6: он НЕ доворачивает текст сам. --psm 3 и OSD (--psm 0) доворачивают, и на кадрах,
# где текст в кадре уже горизонтален, сравнение 90 против 270 даёт случайный ответ
# (2026-10-08, ЭГ 2026-10-07: 45 кадров ушли не в ту сторону).
#
# Запуск по папке превью (16 ядер, по процессу на кадр):
#   ls <scratch>/*/*.jpg | xargs -P16 -n1 sh .claude/skills/raf-orientation/score4.sh | sort > score4.txt
f="$1"
t=$(mktemp -d)
for c in "+0+0" "-900+0" "+900+0"; do
    # Квадрат из превью в сером
    convert "$f" -gravity center -crop "1400x1400${c}" +repage -colorspace gray "$t/c.png"
    for a in 0 90 180 270; do
        convert "$t/c.png" -rotate $a "$t/r.png"
        # OMP_THREAD_LIMIT=1: параллелим процессами, не потоками tesseract
        n=$(OMP_THREAD_LIMIT=1 tesseract "$t/r.png" - -l rus --psm 6 tsv 2>/dev/null |
            awk -F'\t' 'NR>1 && $11>60 && length($12)>=4 {s++} END{print s+0}')
        eval "s$a=\$((\${s$a:-0}+n))"
    done
done
echo "$f $s0 $s90 $s180 $s270"
rm -rf "$t"
